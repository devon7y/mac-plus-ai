#!/usr/bin/env python3
"""Generate Rail Runner's C data from the Python masters.

    gen_data.py OUTDIR [--w 384 --h 240]

Writes OUTDIR/params.h (gameplay + view constants) and OUTDIR/data.c / data.h:
background rows, per-row depth, fill patterns, face art, obstacle patterns with coin trails,
and pre-shifted masked sprites.
"""
import argparse
import json
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
RUNNER = os.path.dirname(HERE)
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(RUNNER, "proto"))
import art  # noqa: E402
import geom as G  # noqa: E402
import params as P  # noqa: E402
import sim  # noqa: E402
import sprites as S  # noqa: E402


def carray(name, ctype, vals, per=16, fmt="{}"):
    s = [f"const {ctype} {name}[{len(vals)}] = {{"]
    for i in range(0, len(vals), per):
        s.append("    " + ", ".join(fmt.format(v) for v in vals[i:i + per]) + ",")
    s.append("};")
    return "\n".join(s)


# ------------------------------------------------------------------ sprites
# Each sprite set is stored pre-shifted: NSHIFT copies, copy k shifted right by k*16/NSHIFT px.
# Row layout per copy: for each of `ww` words: mask word (1 = keep background), ink word.
SPRITE_SETS = {
    # name prefix: shifts
    "rex_": 4, "grumble_": 2, "biscuit_": 4, "pu_": 4, "font_": 16, "hud_": 16, "title_": 1,
}


def shifts_for(name):
    for k, v in SPRITE_SETS.items():
        if name.startswith(k):
            return v
    return 2


def coin_sprite(d, frame):
    """Procedural coin of diameter d, spin frame 0..3 (0 = face on, 2 = edge on)."""
    wscale = [1.0, 0.65, 0.25, 0.65][frame]
    w = max(1, int(round(d * wscale)))
    h = d
    ink = np.zeros((h, w), bool)
    mask = np.zeros((h, w), bool)
    cy, cx = (h - 1) / 2, (w - 1) / 2
    ry, rx = max(h / 2, 0.5), max(w / 2, 0.5)
    for y in range(h):
        for x in range(w):
            e = ((x - cx) / rx) ** 2 + ((y - cy) / ry) ** 2
            if e <= 1.0:
                mask[y, x] = True
                edge = ((x - cx) / max(rx - 1.2, 0.3)) ** 2 + ((y - cy) / max(ry - 1.2, 0.3)) ** 2 > 1.0
                ink[y, x] = edge or d <= 3
    if d >= 7 and w >= 3:                          # embossed mark: a vertical bar in the middle
        x = w // 2
        for y in range(h // 4 + 1, h - h // 4 - 1):
            ink[y, x] = True
    if d >= 4 and frame == 2:
        ink[:, :] = mask
    sp = S.Sprite(f"coin{d}_{frame}", w // 2, h - 1, [])
    sp.ink, sp.mask = ink, mask
    return sp


COIN_SIZES = [2, 3, 4, 5, 6, 7, 9, 11, 13, 16, 19, 23, 27, 32]


def scaled(sp, f):
    """Nearest-neighbour + majority downscale of a master by factor f (<1)."""
    h, w = sp.ink.shape
    nh, nw = max(1, round(h * f)), max(1, round(w * f))
    ink = np.zeros((nh, nw), bool)
    mask = np.zeros((nh, nw), bool)
    for y in range(nh):
        for x in range(nw):
            y0, y1 = int(y / f), max(int(y / f) + 1, int((y + 1) / f))
            x0, x1 = int(x / f), max(int(x / f) + 1, int((x + 1) / f))
            m = sp.mask[y0:y1, x0:x1]
            k = sp.ink[y0:y1, x0:x1]
            mask[y, x] = m.mean() >= 0.4
            if mask[y, x]:
                ink[y, x] = (k & m).sum() >= 0.45 * max(m.sum(), 1)
    out = S.Sprite(sp.name, int(round(sp.ax * f)), int(round(sp.ay * f)), [])
    out.ink, out.mask = ink, mask
    return out


def pack_sprite(sp, nshift):
    """-> (header fields, word list). Header: w, h, ax, ay, ww (words per row incl. spill),
    nshift, offset of each shift copy."""
    h, w = sp.ink.shape
    ww = (w + 15) // 16 + (1 if nshift > 1 else 0)
    words = []
    offs = []
    for k in range(nshift):
        sh = k * 16 // nshift
        offs.append(len(words))
        for y in range(h):
            m = np.zeros(ww * 16, bool)
            i = np.zeros(ww * 16, bool)
            m[sh:sh + w] = sp.mask[y]
            i[sh:sh + w] = sp.ink[y] & sp.mask[y]
            for c in range(ww):
                mw = int("".join("1" if b else "0" for b in m[c * 16:c * 16 + 16]), 2)
                iw = int("".join("1" if b else "0" for b in i[c * 16:c * 16 + 16]), 2)
                words.append((~mw) & 0xFFFF)          # 1 = keep background
                words.append(iw)
    return dict(w=w, h=h, ax=sp.ax, ay=sp.ay, ww=ww, nshift=nshift, offs=offs), words


# ------------------------------------------------------------------ main
def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("out")
    ap.add_argument("--w", type=int, default=384)
    ap.add_argument("--h", type=int, default=240)
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    g = G.Geom(a.w, a.h)
    scale = a.w / 384

    # ---------------- params.h
    ph = ["/* Generated by runner/tools/gen_data.py from proto/params.py and tools/geom.py. */",
          "#ifndef PARAMS_H", "#define PARAMS_H"]
    for k in dir(P):
        v = getattr(P, k)
        if k.isupper() and isinstance(v, int):
            ph.append(f"#define {k} {v}")
    for k in ("CAM_H", "ZP", "WALL_X", "WALL_TOP", "POLE_X", "POLE_TOP", "POLE_ARM_Y", "POLE_ARM_X",
              "POLE_W", "POLE_SPACING", "SLEEPER_P", "SLEEPER_LEN", "ZNEAR"):
        ph.append(f"#define {k} {getattr(G, k)}")
    ph += [f"#define PF_W {g.W}", f"#define PF_H {g.H}", f"#define PF_RB {g.RB}",
           f"#define PF_F {g.F}", f"#define PF_HOR {g.HOR}", f"#define PF_CX {g.CX}",
           f"#define PF_FEET {g.FEET}",
           f"#define TIER_SPEED_INIT {{{', '.join(str(v) for v in sim.TIER_SPEED)}}}",
           f"#define START_CLEAR {sim.START_CLEAR}",
           "#endif", ""]
    open(os.path.join(a.out, "params.h"), "w").write("\n".join(ph))

    c = ['/* Generated by runner/tools/gen_data.py. Do not edit. */', '#include "data.h"', ""]
    h = ["/* Generated by runner/tools/gen_data.py. Do not edit. */", "#ifndef DATA_H", "#define DATA_H",
         '#include "params.h"', ""]

    # ---------------- background
    rows, srow = G.background(g)
    bg = G.pack_rows(rows[0]) + G.pack_rows(rows[1])
    bgw = [bg[i] << 8 | bg[i + 1] for i in range(0, len(bg), 2)]
    c.append(carray("bg_rows", "unsigned short", bgw, 16, "0x{:04X}"))
    h.append(f"extern const unsigned short bg_rows[{len(bgw)}];   /* [2][PF_H][PF_RB/2], word aligned */")
    zg = [int(min(v, 32767)) if srow[y] else 0 for y, v in enumerate(g.zground)]
    c.append(carray("row_sleeper_z", "short", zg))
    h.append(f"extern const short row_sleeper_z[{g.H}];   /* ground depth of animated rows, 0 = static */")

    # ---------------- patterns and face art
    flat = [w for p in art.PATTERNS for w in p]
    c.append(carray("fill_pats", "unsigned short", flat, 8, "0x{:04X}"))
    h.append(f"extern const unsigned short fill_pats[{len(flat)}];   /* [pattern][8 rows] */")
    for k, v in vars(art).items():
        if k.isupper() and isinstance(v, int) and k not in ("FILL", "FRAME"):
            h.append(f"#define ART_{k} {v}")
    h.append("typedef struct { unsigned char kind, u0, v0, u1, v1, pat; } FaceRect;")
    h.append("typedef struct { short y_from, y_to, pat; } SideBand;")
    for name in ("TRAIN_FRONT", "ONCOMING_FRONT", "WALL_FRONT", "LOW_FACE", "HIGH_FACE"):
        rects = getattr(art, name)
        c.append(f"const FaceRect art_{name.lower()}[{len(rects) + 1}] = {{")
        for r in rects:
            c.append("    {%d, %d, %d, %d, %d, %d}," % r)
        c.append("    {255, 0, 0, 0, 0, 0},")
        c.append("};")
        h.append(f"extern const FaceRect art_{name.lower()}[{len(rects) + 1}];")
    for name in ("TRAIN_SIDE", "ONCOMING_SIDE", "WALL_SIDE"):
        bands = getattr(art, name)
        c.append(f"const SideBand art_{name.lower()}[{len(bands) + 1}] = {{")
        for b in bands:
            c.append("    {%d, %d, %d}," % b)
        c.append("    {-1, -1, -1},")
        c.append("};")
        h.append(f"extern const SideBand art_{name.lower()}[{len(bands) + 1}];")

    # ---------------- obstacle patterns + coin trails
    pats = sim.load_patterns()
    coins = json.load(open(os.path.join(RUNNER, "proto", "coins.json")))
    h.append("typedef struct { unsigned char kind, lane, r0, r1; } PatObj;")
    h.append("typedef struct { unsigned char row, lane; short y; } PatCoin;")
    h.append("typedef struct { unsigned char tier, weight, rows, nobj, ncoin; unsigned short obj, coin; } PatDef;")
    objs, cl, defs = [], [], []
    for p in pats:
        cc = coins.get(p.name, [])
        defs.append((p.tier, p.weight, p.rows, len(p.objs), len(cc), len(objs), len(cl)))
        objs += p.objs
        cl += cc
    c.append(f"const PatObj pat_objs[{len(objs)}] = {{")
    c += ["    {%d, %d, %d, %d}," % o for o in objs]
    c.append("};")
    c.append(f"const PatCoin pat_coins[{max(len(cl), 1)}] = {{")
    c += ["    {%d, %d, %d}," % tuple(x) for x in cl]
    c.append("};")
    c.append(f"const PatDef pat_defs[{len(defs)}] = {{")
    c += ["    {%d, %d, %d, %d, %d, %d, %d}," % d for d in defs]
    c.append("};")
    h += [f"#define N_PATTERNS {len(defs)}", f"extern const PatObj pat_objs[{len(objs)}];",
          f"extern const PatCoin pat_coins[{max(len(cl), 1)}];", f"extern const PatDef pat_defs[{len(defs)}];"]
    c.append("const char *const pat_names[] = {" + ", ".join(f'"{p.name}"' for p in pats) + "};")
    h.append("extern const char *const pat_names[];")

    # ---------------- sprites
    spr = {}
    path = os.path.join(RUNNER, "art", "sprites.txt")
    if os.path.exists(path):
        spr = S.load(path)
    sprite_list = []                       # (C name, Sprite, nshift)
    for name, sp in spr.items():
        if name.startswith(("title_", "font_", "hud_")) or abs(scale - 1) < 1e-6:
            sprite_list.append((name, sp, shifts_for(name)))
        else:
            sprite_list.append((name, scaled(sp, scale), shifts_for(name)))
    coin_sz = [max(2, round(d * scale)) for d in COIN_SIZES]
    for i, d in enumerate(coin_sz):
        for f in range(4):
            sprite_list.append((f"coin{i}_{f}", coin_sprite(d, f), 8 if d < 16 else 4))
    # power-up icons at a few sizes
    pu_sizes = [0.25, 0.35, 0.5, 0.7, 1.0]
    for name, sp in list(spr.items()):
        if name.startswith("pu_"):
            for i, f in enumerate(pu_sizes):
                sprite_list.append((f"{name}_{i}", scaled(sp, f * scale) if f * scale < 1 else sp, 4))
    words, hdrs = [], []
    for name, sp, ns in sprite_list:
        hd, wl = pack_sprite(sp, ns)
        hd["base"] = len(words)
        words += wl
        hdrs.append((name, hd))
    c.append(carray("spr_words", "unsigned short", words or [0], 12, "0x{:04X}"))
    h.append(f"extern const unsigned short spr_words[{max(len(words), 1)}];")
    h.append("typedef struct { short w, h, ax, ay, ww, nshift; long base; unsigned short offs[16]; } SprDef;")
    c.append(f"const SprDef spr_defs[{max(len(hdrs), 1)}] = {{")
    for name, hd in hdrs:
        offs = (hd["offs"] + [0] * 16)[:16]
        c.append("    {%d, %d, %d, %d, %d, %d, %dL, {%s}},   /* %s */" % (
            hd["w"], hd["h"], hd["ax"], hd["ay"], hd["ww"], hd["nshift"], hd["base"],
            ", ".join(str(o) for o in offs), name))
    if not hdrs:
        c.append("    {0},")
    c.append("};")
    h.append(f"extern const SprDef spr_defs[{max(len(hdrs), 1)}];")
    for i, (name, hd) in enumerate(hdrs):
        h.append(f"#define SPR_{name.upper()} {i}")
    h.append(f"#define N_COIN_SIZES {len(coin_sz)}")
    c.append(carray("coin_diam", "short", coin_sz))
    h.append(f"extern const short coin_diam[{len(coin_sz)}];")
    has = {name for name, _ in hdrs}
    for flag in ("rex_run1", "rex_run2", "rex_run3", "rex_jump", "rex_fall", "rex_roll0", "rex_roll1",
                 "rex_left", "rex_right", "rex_stumble", "rex_crash", "rex_jet0", "rex_jet1",
                 "rex_board0", "rex_board1", "grumble_run0", "grumble_run1", "grumble_grab",
                 "biscuit_run0", "biscuit_run1", "title_logo", "title_rex", "hud_coin", "hud_board",
                 "pu_jetpack_0", "font_0"):
        if flag in has:
            h.append(f"#define HAVE_{flag.upper()} 1")
    h += ["#endif", ""]
    open(os.path.join(a.out, "data.c"), "w").write("\n".join(c) + "\n")
    open(os.path.join(a.out, "data.h"), "w").write("\n".join(h))
    total = len(bg) + len(words) * 2
    print(f"{g.describe()}; background {len(bg)} B, sprites {len(hdrs)} ({len(words) * 2} B), "
          f"patterns {len(defs)} ({len(objs)} objects, {len(cl)} coins); total data ~{total // 1024} KB")


if __name__ == "__main__":
    main()
