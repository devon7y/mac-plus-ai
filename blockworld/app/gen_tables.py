#!/usr/bin/env python3
"""Generate the C tables shared with the Python reference: gen_tables.py OUTDIR
Writes OUTDIR/tables.c and OUTDIR/tables.h:
  bw_sin[1024]     Q14 sine (1024 steps per turn), as engine/render.py SIN
  bw_sin256[256]   sine * 256, 256 steps (the cave walker)
  bw_pat[1024][8]  pattern rows per id, as engine/patterns.py PAT
  bw_names[]       block type names
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "engine"))
import patterns as PT  # noqa: E402
import render as R  # noqa: E402
import world as W  # noqa: E402


def main():
    out = sys.argv[1]
    os.makedirs(out, exist_ok=True)
    h = [
        "/* generated by app/gen_tables.py: do not edit */",
        "#ifndef BW_TABLES_H", "#define BW_TABLES_H",
        f"#define BW_NIDS {PT.NIDS}",
        f"#define BW_SKY {PT.SKY}", f"#define BW_HAZE {PT.HAZE}", f"#define BW_FOGBG {PT.FOGBG}",
        f"#define BW_LINE {PT.LINE}", f"#define BW_TURFBAND {PT.TURFBAND}", f"#define BW_TURFBAND_B {PT.TURFBAND_B}",
        f"#define BW_FARHILL {PT.FARHILL}", f"#define BW_FARLINE {PT.FARLINE}",
        "extern const short bw_sin[1024];",
        "extern const short bw_sin256[256];",
        "#define bw_cos256(i) bw_sin256[((i) + 64) & 255]",
        "extern const unsigned char bw_pat[BW_NIDS][8];",
        "#endif", ""]
    c = ["/* generated by app/gen_tables.py: do not edit */", '#include "tables.h"', "",
         "const short bw_sin[1024] = {"]
    for i in range(0, 1024, 16):
        c.append("    " + ", ".join(str(v) for v in R.SIN[i:i + 16]) + ",")
    c.append("};")
    c.append("const short bw_sin256[256] = {")
    for i in range(0, 256, 16):
        c.append("    " + ", ".join(str(v) for v in W.SIN256[i:i + 16]) + ",")
    c.append("};")
    c.append("const unsigned char bw_pat[BW_NIDS][8] = {")
    for i in range(PT.NIDS):
        c.append("    {" + ", ".join(f"0x{v:02X}" for v in PT.PAT[i]) + "},")
    c.append("};")
    open(os.path.join(out, "tables.h"), "w").write("\n".join(h))
    open(os.path.join(out, "tables.c"), "w").write("\n".join(c) + "\n")


if __name__ == "__main__":
    main()
