#!/usr/bin/env python3
"""Pick the M1 benchmark cameras (seed 2) and write OUTDIR/bench_cams.h and OUTDIR/bench_cams.json.
    gen_bench.py OUTDIR
Camera 0 is the check frame. Cameras: 6 ground-level views chosen for variety (proto/scenic.py
scoring), one looking down steeply, one in a cave."""
import json, math, os, random, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "engine")); sys.path.insert(0, os.path.join(ROOT, "proto"))
import world as W, render as R, views as V

SEED = 2
out = sys.argv[1]
os.makedirs(out, exist_ok=True)
b, hm = W.generate(SEED)
at = R.make_seg_lookup(W.all_segments(b))
cfg = R.Cfg()
rng = random.Random(1234)
cands = []
for _ in range(400):
    x, z = rng.randrange(8, W.WX - 8), rng.randrange(8, W.WX - 8)
    if W.column_segments(b, x, z)[0][2] not in (W.TURF, W.SAND):
        continue
    cam = R.Cam((x << 8) + 128, (V.ground(b, x, z) << 8) + 415, (z << 8) + 128, rng.randrange(1024), rng.choice((-30, -15, 0, 10)))
    ids, keys = R.render_cols(at, cam, cfg)
    cnt = {}
    for col in ids:
        for i in col[::4]:
            t = i >> 5 if i >= 32 else 0
            cnt[t] = cnt.get(t, 0) + 1
    n = sum(cnt.values())
    fr = {t: c / n for t, c in cnt.items()}
    if not (0.15 < fr.get(0, 0) < 0.55) or fr.get(W.LEAVES, 0) > 0.3:
        continue
    ent = -sum(p * math.log(p) for p in fr.values() if p > 0)
    cands.append((ent + 2 * min(fr.get(W.LEAVES, 0), 0.1) + 2 * min(fr.get(W.WATER, 0), 0.1), cam))
cands.sort(key=lambda c: -c[0])
cams = []
for s, cam in cands:
    if all(abs(cam.x - c.x) + abs(cam.z - c.z) > 12 * 256 for c in cams):
        cams.append(cam)
    if len(cams) == 6:
        break
c0 = cams[1]
cams.append(R.Cam(c0.x, c0.y, c0.z, (c0.yaw + 300) & 1023, -150))           # looking down
# a cave: air with solid above and below, well under the surface
for x in range(8, W.WX - 8):
    for z in range(8, W.WX - 8):
        g = hm[x * W.WX + z]
        for y in range(4, g - 6):
            if b[W.idx(x, z, y)] == W.AIR and b[W.idx(x, z, y + 1)] == W.AIR and W.SOLID[b[W.idx(x, z, y - 1)]]:
                cave = R.Cam((x << 8) + 128, (y << 8) + 415, (z << 8) + 128, 200, 0)
                break
        else:
            continue
        break
    else:
        continue
    break
cams.append(cave)
h = ["/* generated by tests/gen_bench.py: M1 benchmark cameras, seed 2 */",
     "#define BENCH_SEED 2", f"#define BENCH_NCAM {len(cams)}",
     "static const long bench_cams[BENCH_NCAM][5] = {"]
h += [f"    {{{c.x}, {c.y}, {c.z}, {c.yaw}, {c.pitch}}}," for c in cams]
h.append("};")
open(os.path.join(out, "bench_cams.h"), "w").write("\n".join(h) + "\n")
json.dump([[c.x, c.y, c.z, c.yaw, c.pitch] for c in cams], open(os.path.join(out, "bench_cams.json"), "w"))
print("\n".join(h))
