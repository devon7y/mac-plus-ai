#!/usr/bin/env python3
"""Write lut68k.s: the W4 ternary lookup-table kernels for Dream's 1 MB build (copied from the
chatbot's verified kernels, llm/app/gen_kernels.py, which come from llm/bench/gen_bench.py).

  void k_tab4(const short *x, long groups, short *lut);   81-entry table per group of 4 inputs:
       entry idx = sum_j d_j 3^j (d_j = w_j + 1) holds sum_j w_j x_j; tables are contiguous
  void k_mvw(const short *codes, const short *lutmid, long nout, long ngroups, short *out);
       out[o] = sum_g lutmid[codes[o][g] / 2] (16-bit wraparound), codes = (g*81 + idx)*2 - 32768,
       lutmid = lut + 16384 (shorts); ngroups <= 128
Registers: arguments on the stack, d2-d7/a2-a6 preserved (Retro68 C convention); a5 untouched.
"""
import sys

asm = []
emit = asm.append
SAVE = "%d2-%d7/%a2-%a6"
ARG = 48
MAXG = 128


def arg(i):
    return f"{ARG + 4 * i}(%sp)"


def digits(i, k):
    return [(i // 3 ** j) % 3 for j in range(k)]


emit("| Generated by dream/app/gen_lut.py (from llm/app/gen_kernels.py). 68000, position-independent.\n"
     "        .text")
emit("bld_4c: movem.w (%a0),%d1-%d4\n        move.w  %d1,%d6")
for j in range(1, 4):
    emit(f"        move.w  %d{j + 1},%d0\n        sub.w   %d6,%d{j + 1}\n        sub.w   %d6,%d{j + 1}\n"
         f"        add.w   %d0,%d6")
emit("        move.w  %d6,%d0\n        neg.w   %d0")
for idx in range(81):
    emit("        move.w  %d0,(%a3)+")
    if idx < 80:
        dg = digits(idx, 4)
        j = next(j for j in range(4) if dg[j] < 2)
        emit(f"        add.w   %d{1 if j == 0 else j + 1},%d0")
emit("        rts")
emit(f"""        .globl  k_tab4
k_tab4: movem.l {SAVE},-(%sp)
        movea.l {arg(0)},%a0
        move.l  {arg(1)},%d7
        movea.l {arg(2)},%a3
        move.l  %d7,%d0
        lsl.l   #3,%d0
        lea     0(%a0,%d0.l),%a4
1:      jsr     bld_4c(%pc)
        addq.l  #8,%a0
        cmpa.l  %a4,%a0
        bcs.s   1b
        movem.l (%sp)+,{SAVE}
        rts
        .globl  k_mvw
k_mvw:  movem.l {SAVE},-(%sp)
        movea.l {arg(0)},%a1
        movea.l {arg(1)},%a2
        move.l  {arg(2)},%d6
        move.l  {arg(3)},%d5
        movea.l {arg(4)},%a6
        lea     mvW_end(%pc),%a4
        mulu.w  #6,%d5
        suba.w  %d5,%a4
        subq.l  #1,%d6
1:      moveq   #0,%d1
        jsr     (%a4)
        move.w  %d1,(%a6)+
        dbf     %d6,1b
        movem.l (%sp)+,{SAVE}
        rts
mvW_blk:""")
for _ in range(MAXG):
    emit("        move.w  (%a1)+,%d0\n        add.w   0(%a2,%d0.w),%d1")
emit("mvW_end: rts")
# k_rq: requantise n row sums (FORMAT.md) without tables: v = (S >> k) + b [+ old] (int16),
# clamp to [lo, hi]; flags bit 0 = addh (add the old dst value), bit 1 = raw (store v as is).
#   void k_rq(const short *S, const signed char *k, const short *bias, short *dst, long n, long flags,
#             long lo, long hi);
emit(f"""        .globl  k_rq
k_rq:   movem.l {SAVE},-(%sp)
        movea.l {arg(0)},%a0
        movea.l {arg(1)},%a1
        movea.l {arg(2)},%a2
        movea.l {arg(3)},%a3
        move.l  {arg(4)},%d7
        move.l  {arg(5)},%d4
        move.l  {arg(6)},%d5
        move.l  {arg(7)},%d6
        subq.l  #1,%d7
        bmi     9f
        btst    #1,%d4
        bne     rq_raw
        btst    #0,%d4
        bne     rq_addh
rq_set: move.w  (%a0)+,%d0
        move.b  (%a1)+,%d1
        bmi.s   5f
        asr.w   %d1,%d0
3:      add.w   (%a2)+,%d0
        cmp.w   %d5,%d0
        bge.s   1f
        move.w  %d5,%d0
        bra.s   2f
1:      cmp.w   %d6,%d0
        ble.s   2f
        move.w  %d6,%d0
2:      move.w  %d0,(%a3)+
        dbf     %d7,rq_set
        bra     9f
5:      neg.b   %d1
        asl.w   %d1,%d0
        bra.s   3b
rq_addh: move.w (%a0)+,%d0
        move.b  (%a1)+,%d1
        bmi.s   5f
        asr.w   %d1,%d0
3:      add.w   (%a2)+,%d0
        add.w   (%a3),%d0
        cmp.w   %d5,%d0
        bge.s   1f
        move.w  %d5,%d0
        bra.s   2f
1:      cmp.w   %d6,%d0
        ble.s   2f
        move.w  %d6,%d0
2:      move.w  %d0,(%a3)+
        dbf     %d7,rq_addh
        bra     9f
5:      neg.b   %d1
        asl.w   %d1,%d0
        bra.s   3b
rq_raw: move.w  (%a0)+,%d0
        move.b  (%a1)+,%d1
        bmi.s   5f
        asr.w   %d1,%d0
3:      add.w   (%a2)+,%d0
        move.w  %d0,(%a3)+
        dbf     %d7,rq_raw
        bra     9f
5:      neg.b   %d1
        asl.w   %d1,%d0
        bra.s   3b
9:      movem.l (%sp)+,{SAVE}
        rts""")
# k_rq2: the same with two-term gains (k = (k1, e2) per channel: + s (acc >> k2), s = sign(e2),
# k2 = |e2| - 4); flags as k_rq. One loop with the mode tests inside (only used by the 1 MB build).
emit(f"""        .globl  k_rq2
k_rq2:  movem.l {SAVE},-(%sp)
        movea.l {arg(0)},%a0
        movea.l {arg(1)},%a1
        movea.l {arg(2)},%a2
        movea.l {arg(3)},%a3
        move.l  {arg(4)},%d7
        move.l  {arg(5)},%d4
        move.l  {arg(6)},%d5
        move.l  {arg(7)},%d6
        subq.l  #1,%d7
        bmi     9f
1:      move.w  (%a0)+,%d0
        move.w  %d0,%d2
        move.b  (%a1)+,%d1
        bpl.s   2f
        neg.b   %d1
        asl.w   %d1,%d0
        bra.s   3f
2:      asr.w   %d1,%d0
3:      move.b  (%a1)+,%d3
        beq.s   6f
        bmi.s   4f
        subq.b  #4,%d3
        bpl.s   21f
        neg.b   %d3
        asl.w   %d3,%d2
        bra.s   22f
21:     asr.w   %d3,%d2
22:     add.w   %d2,%d0
        bra.s   6f
4:      neg.b   %d3
        subq.b  #4,%d3
        bpl.s   23f
        neg.b   %d3
        asl.w   %d3,%d2
        bra.s   24f
23:     asr.w   %d3,%d2
24:     sub.w   %d2,%d0
6:      add.w   (%a2)+,%d0
        btst    #1,%d4
        bne.s   8f
        btst    #0,%d4
        beq.s   7f
        add.w   (%a3),%d0
7:      cmp.w   %d5,%d0
        bge.s   71f
        move.w  %d5,%d0
        bra.s   8f
71:     cmp.w   %d6,%d0
        ble.s   8f
        move.w  %d6,%d0
8:      move.w  %d0,(%a3)+
        dbf     %d7,1b
9:      movem.l (%sp)+,{SAVE}
        rts""")
open(sys.argv[1], "w").write("\n".join(asm) + "\n")
