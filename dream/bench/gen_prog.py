#!/usr/bin/env python3
"""Write prog_<cfg>.h (the layer program for the Mac bench) for each config.

    gen_prog.py <outdir> [cfg ...]
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "engine"))
import arch  # noqa: E402

KIND = {"pw": 0, "dw": 1}
MODE = {"relu": 0, "lin": 1, "seth": 2, "addh": 3, "raw": 4}


def tab_ranges(L):
    names = []
    for l in L:
        if l["tab"] != "raw" and l["tab"] not in names:
            names.append(l["tab"])
    rng = []
    for n in names:
        if n.startswith("relu"):
            rng.append((0, int(n[4:])))
        elif n == "lin":
            rng.append((-arch.LIN_MAX, arch.LIN_MAX))
        elif n.startswith("lin"):
            rng.append((-int(n[3:]), int(n[3:])))
        elif n == "res":
            rng.append((-arch.RES_MAX, arch.RES_MAX))
    return names, rng


def header(cfg):
    T, L = arch.build(cfg)
    tn = list(T)
    names, rng = tab_ranges(L)
    o = [f"/* Generated by dream/bench/gen_prog.py for {cfg}. */",
         f"#define CFG_NAME \"{cfg}\"",
         f"#define NT {len(tn)}", f"#define NL {len(L)}", f"#define NTAB {len(names)}",
         f"#define T_XT {tn.index('xt')}", f"#define T_OUT {tn.index('out')}",
         "static const short T_H[NT] = {" + ", ".join(str(T[n][0]) for n in tn) + "};",
         "static const short T_W[NT] = {" + ", ".join(str(T[n][1]) for n in tn) + "};",
         "static const short T_C[NT] = {" + ", ".join(str(T[n][2]) for n in tn) + "};",
         "static const short TAB_LO[NTAB] = {" + ", ".join(str(a) for a, b in rng) + "};",
         "static const short TAB_HI[NTAB] = {" + ", ".join(str(b) for a, b in rng) + "};",
         "static const LDesc LAY[NL] = {"]
    maxw = maxc = 0
    for l in L:
        n = l["cin"] if l["kind"] == "pw" else 9
        maxw = max(maxw, n * l["cout"])
        maxc = max(maxc, l["cout"])
        tab = 255 if l["tab"] == "raw" else names.index(l["tab"])
        o.append(f"  {{{KIND[l['kind']]}, {MODE[l['mode']]}, {int(l.get('gather') == 's2d')}, "
                 f"{int(l.get('scatter') == 'd2s')}, {int(bool(l.get('center')))}, {tab}, {int(l.get('wq') == 'q4')}, 0, "
                 f"{tn.index(l['src'])}, {tn.index(l['dst'])}, {l['cin']}, {l['cout']}, {l['grid']}}},  /* {l['tag']} */")
    o.append("};")
    o.append(f"#define MAXW {maxw}")
    o.append(f"#define MAXC {maxc}")
    s = arch.summary(cfg)
    o.append(f"#define CODE_BOUND {int(s['jit_kb'] * 1024 * 1.25) + 65536}L")
    return "\n".join(o) + "\n"


if __name__ == "__main__":
    out = sys.argv[1]
    os.makedirs(out, exist_ok=True)
    for cfg in sys.argv[2:] or list(arch.CONFIGS):
        open(os.path.join(out, f"prog_{cfg}.h"), "w").write(header(cfg))
        print("wrote", os.path.join(out, f"prog_{cfg}.h"))
