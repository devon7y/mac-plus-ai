# ---- sound tables (player.c) -------------------------------------------------------------------
import math
FS = 370 * 60.15 / 2                      # mixer rate: half the Plus's 22.25 kHz sound rate
S = ["/* Generated by gen_consts.py: Tune's sound tables (player.c). Mixer rate %.1f Hz. */" % FS]
mstep, bstep = [], []
for m in range(128):
    f = 440.0 * 2 ** ((m - 69) / 12.0)
    mstep.append(min(0xFFFFFF, int(round(f * 256 * 65536 / FS))))
    bstep.append(min(0xFFFF, int(round(f * 65536 / FS))))
S.append("const unsigned long pl_mstep[128] = {%s};" % ",".join("%dUL" % v for v in mstep))
S.append("const unsigned short pl_bstep[128] = {%s};" % ",".join(map(str, bstep)))


def wave(harm):
    w = [sum(a * math.sin(2 * math.pi * k * i / 256 + ph) for k, a, ph in harm) for i in range(256)]
    mx = max(abs(v) for v in w)
    return [int(round(127 * v / mx)) for v in w]


# fiddle: bright, falling harmonics with a little body around the 3rd-5th; flute: nearly pure
fiddle = wave([(1, 1.0, 0), (2, 0.55, 0.3), (3, 0.42, 0.9), (4, 0.30, 1.4), (5, 0.22, 2.0), (6, 0.12, 2.6),
               (7, 0.07, 3.1)])
flute = wave([(1, 1.0, 0), (2, 0.18, 0.5), (3, 0.08, 1.0)])
bass = wave([(1, 1.0, 0), (2, 0.35, 0), (3, 0.12, 0)])
bass[0] = 0
S.append("const signed char pl_wave[2][256] = {{%s},{%s}};" % (",".join(map(str, fiddle)), ",".join(map(str, flute))))
S.append("const signed char pl_bwave[256] = {%s};" % ",".join(map(str, bass)))
S.append("const signed char pl_vib[16] = {%s};" % ",".join(str(int(round(127 * math.sin(2 * math.pi * i / 16)))) for i in range(16)))
open(os.path.join(HERE, "sndtables.c"), "w").write("\n".join(S) + "\n")
