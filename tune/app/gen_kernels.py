#!/usr/bin/env python3
"""Generate kernels68k.s: Tune's two ternary matrix kernels for the 68000 (GNU as, Motorola syntax).

  void k_tab5(const short *x, long groups, short *lut)
      For each group of 5 inputs, the 243 sums  sum_j (d_j - 1) * x_j  for every base-3 index
      idx = sum_j d_j 3^j, stored contiguously (group g's table at lut + 486 g bytes). Built
      incrementally with 16-bit adds, as in Pixel's bld_5c (llm/app/gen_kernels.py); entries are
      exact modulo 2^16.
  void k_mv(const short *codes, const short *lutmid, long nrows, short *out)
      out[r] = sum over the row's G codes of the word at lutmid + code (code = byte offset - 32768).
      Row length G (<= 128) is the fifth argument: void k_mv(codes, lutmid, nrows, out, long G).
Args on the stack (Retro68 C convention); d2-d7/a2-a6 preserved.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SAVE = "%d2-%d7/%a2-%a6"
ARG = 48


def arg(i):
    return f"{ARG + 4 * i}(%sp)"


def digits(i, k):
    return [(i // 3 ** j) % 3 for j in range(k)]


def main(out):
    a = []
    e = a.append
    e("| Generated by gen_kernels.py. 68000.\n        .text")
    # group table builder: a0 -> 5 inputs (advanced), a3 -> table (advanced)
    e("bld5:   movem.w (%a0)+,%d1-%d5\n        move.w  %d1,%d6")
    for j in range(1, 5):
        e(f"        move.w  %d{j + 1},%d0\n        sub.w   %d6,%d{j + 1}\n        sub.w   %d6,%d{j + 1}\n"
          f"        add.w   %d0,%d6")
    e("        move.w  %d6,%d0\n        neg.w   %d0")
    n = 3 ** 5
    for idx in range(n):
        e("        move.w  %d0,(%a3)+")
        if idx < n - 1:
            dg = digits(idx, 5)
            j = next(j for j in range(5) if dg[j] < 2)
            e(f"        add.w   %d{j + 1},%d0")
    e("        rts")
    e(f"""        .globl  k_tab5
k_tab5: movem.l {SAVE},-(%sp)
        movea.l {arg(0)},%a0
        move.l  {arg(1)},%d7
        movea.l {arg(2)},%a3
        subq.l  #1,%d7
1:      jsr     bld5(%pc)
        dbf     %d7,1b
        movem.l (%sp)+,{SAVE}
        rts""")
    e(f"""        .globl  k_mv
k_mv:   movem.l {SAVE},-(%sp)
        movea.l {arg(0)},%a1
        movea.l {arg(1)},%a2
        move.l  {arg(2)},%d6
        movea.l {arg(3)},%a6
        move.l  {arg(4)},%d0
        mulu.w  #6,%d0
        lea     mv_end(%pc),%a4
        suba.l  %d0,%a4
        subq.l  #1,%d6
        bmi     9f
1:      moveq   #0,%d1
        jmp     (%a4)
mv_blk:""")
    for _ in range(128):
        e("        move.w  (%a1)+,%d0\n        add.w   0(%a2,%d0.w),%d1")
    e(f"""mv_end: move.w  %d1,(%a6)+
        dbf     %d6,1b
9:      movem.l (%sp)+,{SAVE}
        rts""")
    # ---- k_gru: one GRU layer's update, gates interleaved per unit (r, z, n)
    e(f"""        .globl  k_gru
| void k_gru(const short *x, const short *acc, const short *Mb, long k, short *h, long H,
|            const short *sigmid, const short *tanhmid)
|   x, acc: 3H words (r z n per unit); Mb: 4 words per unit (Mr Mz Mn bhn); h: H words (in/out)
k_gru:  movem.l {SAVE},-(%sp)
        movea.l {arg(0)},%a0
        movea.l {arg(1)},%a1
        movea.l {arg(2)},%a2
        move.l  {arg(3)},%d5
        movea.l {arg(4)},%a4
        move.l  {arg(5)},%d7
        movea.l {arg(6)},%a3
        movea.l {arg(7)},%a6
        subq.l  #1,%d7
1:      move.w  (%a1)+,%d0
        muls.w  (%a2)+,%d0
        swap    %d0
        asl.w   %d5,%d0
        add.w   (%a0)+,%d0
        bvc.s   2f
        jsr     sat(%pc)
2:      asr.w   #3,%d0
        add.w   %d0,%d0
        move.w  0(%a3,%d0.w),%d1
        move.w  (%a1)+,%d0
        muls.w  (%a2)+,%d0
        swap    %d0
        asl.w   %d5,%d0
        add.w   (%a0)+,%d0
        bvc.s   3f
        jsr     sat(%pc)
3:      asr.w   #3,%d0
        add.w   %d0,%d0
        move.w  0(%a3,%d0.w),%d2
        move.w  (%a1)+,%d0
        muls.w  (%a2)+,%d0
        swap    %d0
        asl.w   %d5,%d0
        add.w   (%a2)+,%d0
        bvc.s   4f
        jsr     sat(%pc)
4:      muls.w  %d1,%d0
        add.l   %d0,%d0
        swap    %d0
        add.w   (%a0)+,%d0
        bvc.s   5f
        jsr     sat(%pc)
5:      asr.w   #3,%d0
        add.w   %d0,%d0
        move.w  0(%a6,%d0.w),%d3
        move.w  (%a4),%d0
        sub.w   %d3,%d0
        muls.w  %d2,%d0
        add.l   %d0,%d0
        swap    %d0
        add.w   %d3,%d0
        move.w  %d0,(%a4)+
        dbf     %d7,1b
        movem.l (%sp)+,{SAVE}
        rts
| saturate d0.w after a signed overflow: the true sum had the opposite sign of the wrapped one
sat:    tst.w   %d0
        bmi.s   1f
        move.w  #-32768,%d0
        rts
1:      move.w  #32767,%d0
        rts""")
    # ---- k_scale: out[i] = sat16(wrap16(((acc[i]*M[i]) >> 16) << k) + b[i])
    e(f"""        .globl  k_scale
| void k_scale(const short *acc, const short *M, long k, const short *b, short *out, long n)
k_scale: movem.l {SAVE},-(%sp)
        movea.l {arg(0)},%a1
        movea.l {arg(1)},%a2
        move.l  {arg(2)},%d5
        movea.l {arg(3)},%a3
        movea.l {arg(4)},%a4
        move.l  {arg(5)},%d7
        subq.l  #1,%d7
1:      move.w  (%a1)+,%d0
        muls.w  (%a2)+,%d0
        swap    %d0
        asl.w   %d5,%d0
        add.w   (%a3)+,%d0
        bvc.s   2f
        jsr     sat(%pc)
2:      move.w  %d0,(%a4)+
        dbf     %d7,1b
        movem.l (%sp)+,{SAVE}
        rts""")
    # ---- k_sum5: out[i] (=|+=) p0[i] + p1[i] + p2[i] + p3[i] + p4[i]  (16-bit, no overflow by design)
    e(f"""        .globl  k_sum5
| void k_sum5(short *out, long n, const short *p0, const short *p1, const short *p2,
|             const short *p3, const short *p4, long accumulate)
k_sum5: movem.l {SAVE},-(%sp)
        movea.l {arg(0)},%a6
        move.l  {arg(1)},%d7
        movea.l {arg(2)},%a0
        movea.l {arg(3)},%a1
        movea.l {arg(4)},%a2
        movea.l {arg(5)},%a3
        movea.l {arg(6)},%a4
        subq.l  #1,%d7
        tst.l   {arg(7)}
        bne.s   2f
1:      move.w  (%a0)+,%d0
        add.w   (%a1)+,%d0
        add.w   (%a2)+,%d0
        add.w   (%a3)+,%d0
        add.w   (%a4)+,%d0
        move.w  %d0,(%a6)+
        dbf     %d7,1b
        bra.s   3f
2:      move.w  (%a0)+,%d0
        add.w   (%a1)+,%d0
        add.w   (%a2)+,%d0
        add.w   (%a3)+,%d0
        add.w   (%a4)+,%d0
        add.w   %d0,(%a6)+
        dbf     %d7,2b
3:      movem.l (%sp)+,{SAVE}
        rts""")
    open(out, "w").write("\n".join(a) + "\n")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "kernels68k.s"))
