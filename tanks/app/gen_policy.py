#!/usr/bin/env python3
"""Compile Tank Duel's integer policies (model.export_int, saved as .npz) to 68000 code.

    gen_policy.py OUTDIR name=path.npz [name=path.npz ...]
    gen_policy.py OUTDIR --random name [name ...]      (untrained nets, to test the pipeline)

Writes OUTDIR/policies.s and OUTDIR/policies.h. Each policy becomes
    void pol_<name>(const short *obs, short *scratch, long *logits)
straight-line code: per output neuron, moveq #0 then one add.w/sub.w d16(a0),d0 per nonzero
ternary weight (12 cycles each), muls.w by the neuron's multiplier, add.l the offset, asr.l by the
layer's shift, clamp to 0..127 (hidden layers) and store. The output layer stores the 15 int32
logits. Exactly model.int_forward (checked in MAME through the debug block).
"""
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(os.path.dirname(HERE), "train"))


def compile_policy(name, layers, emit):
    emit(f"        .globl  pol_{name}")
    emit(f"pol_{name}:")
    emit("        movem.l %d2-%d3/%a2-%a3,-(%sp)")
    emit("        movea.l 20(%sp),%a0")       # obs
    emit("        movea.l 24(%sp),%a1")       # scratch (2 x 64 shorts)
    emit("        movea.l 28(%sp),%a2")       # logits
    emit("        moveq   #127,%d3")
    nweights = 0
    for k, L in enumerate(layers):
        T, M, B, SH, last = L["T"], L["M"], L["B"], L["SH"], L["last"]
        if k == 0:
            src = "%a0"
        else:
            src = "%a1" if k % 2 == 1 else "%a3"
        if k == 0:
            dst_base = None
        nout, nin = T.shape
        if not last:
            if k % 2 == 0:
                emit("        lea     128(%a1),%a3")   # layer outputs alternate: a1 (layer 0), a3 (layer 1), ...
        for j in range(nout):
            emit("        moveq   #0,%d0")
            for i in range(nin):
                w = int(T[j, i])
                if w:
                    emit(f"        {'add' if w > 0 else 'sub'}.w  {2 * i}({src}),%d0")
                    nweights += 1
            m = int(M[j])
            assert -32768 <= m <= 32767
            emit(f"        muls.w  #{m},%d0")
            b = int(B[j])
            assert -2 ** 31 <= b < 2 ** 31
            if b:
                emit(f"        add.l   #{b},%d0")
            if last:
                emit("        move.l  %d0,(%a2)+")
                continue
            if SH == 16:                                # high word = floor(z / 65536)
                emit("        swap    %d0")
                emit("        tst.w   %d0")
                emit("        bpl.s   1f")
                emit("        moveq   #0,%d0")
                emit("        bra.s   2f")
                emit("1:      cmp.w   %d3,%d0")
                emit("        ble.s   2f")
                emit("        move.w  %d3,%d0")
            else:
                emit(f"        moveq   #{SH},%d1")
                emit("        asr.l   %d1,%d0")
                emit("        bpl.s   1f")
                emit("        moveq   #0,%d0")
                emit("        bra.s   2f")
                emit("1:      cmp.l   %d3,%d0")
                emit("        ble.s   2f")
                emit("        move.l  %d3,%d0")
            dst = "%a1" if k % 2 == 0 else "%a3"
            emit(f"2:      move.w  %d0,{2 * j}({dst})")
    emit("        movem.l (%sp)+,%d2-%d3/%a2-%a3")
    emit("        rts")
    return nweights


def main():
    out = sys.argv[1]
    os.makedirs(out, exist_ok=True)
    from model import load_int, export_int, Actor
    specs = []
    if sys.argv[2] == "--random":
        import torch
        for k, name in enumerate(sys.argv[3:]):
            torch.manual_seed(100 + k)
            a = Actor()
            a.quant = True
            specs.append((name, export_int(a)))
    else:
        for arg in sys.argv[2:]:
            name, path = arg.split("=", 1)
            specs.append((name, load_int(path)))
    from model import save_int
    for name, layers in specs:
        save_int(layers, os.path.join(out, f"policy_{name}.npz"))      # what was compiled (for tests)
    lines = ["| Generated by gen_policy.py. Do not edit. 68000, position-independent.", "        .text"]
    info = []
    for name, layers in specs:
        # layer 0 outputs go to scratch a1, layer 1 outputs to a3 = a1 + 128; the output layer reads a3
        assert len(layers) == 3
        n = compile_policy(name, layers, lines.append)
        info.append((name, n, [L["T"].shape for L in layers]))
    open(os.path.join(out, "policies.s"), "w").write("\n".join(lines) + "\n")
    h = ["/* Generated by gen_policy.py. Do not edit. */", "#ifndef POLICIES_H", "#define POLICIES_H",
         f"#define NPOL {len(specs)}",
         "typedef void (*PolFn)(const short *obs, short *scratch, long *logits);   /* scratch: 128 shorts */"]
    for name, n, shapes in info:
        h.append(f"void pol_{name}(const short *obs, short *scratch, long *logits);   /* {n} weights, {shapes} */")
        h.append(f"#define POL_{name.upper()} {info.index((name, n, shapes))}")
    h.append("#define POLICY_TABLE {" + ", ".join(f"pol_{name}" for name, _, _ in info) + "}")
    sys.path.insert(0, os.path.join(os.path.dirname(HERE), "sim"))
    from defs import PICK_SHIFT
    shifts = []
    for name, layers in specs:
        sh = layers[-1]["SH"] - PICK_SHIFT
        assert 0 <= sh <= 15, (name, sh)
        shifts.append(sh)
    h.append("/* sim_pick's noise shift per policy: the output layer's SH - PICK_SHIFT */")
    h.append("#define POLICY_SHIFT {" + ", ".join(str(v) for v in shifts) + "}")
    h.append("#define POLICY_NAMES {" + ", ".join(f'"{name}"' for name, _, _ in info) + "}")
    h += ["#endif", ""]
    open(os.path.join(out, "policies.h"), "w").write("\n".join(h))
    for name, n, shapes in info:
        print(f"policy {name}: {n} nonzero weights, layers {shapes}")


if __name__ == "__main__":
    main()
