#!/usr/bin/env python3
"""Write sim_tables.h / sim_tables.c (the C side of defs.py) into a folder (default: next to this file).

    gen_tables.py [OUTDIR]
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import defs as D  # noqa: E402


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else HERE
    os.makedirs(out, exist_ok=True)
    consts = ["TW", "TH", "SU", "TS", "MAXT", "MAXS", "HB", "HIT", "SHELL_HIT", "SHELL_LIFE", "BARREL",
              "RAYSTEP", "RAYN", "NRAY", "AIMSTEP", "AIMN", "AIMHIT", "NOBS", "DECIDE", "MAXEV",
              "EV_FIRE", "EV_RICOCHET", "EV_SHELL_END", "EV_KILL", "EV_CLANG", "EV_SHELLS", "EV_DUD", "EV_SHIELD",
              "BOT_SITTER", "BOT_HUNTER", "BOT_WANDER", "T_PLAYER", "T_RUSHER", "T_SNIPER", "T_CAREFUL",
              "PICK_SHIFT"]
    h = ["/* Generated by gen_tables.py from defs.py. Do not edit. */",
         "#ifndef SIM_TABLES_H", "#define SIM_TABLES_H"]
    for c in consts:
        h.append(f"#define {c} {getattr(D, c)}")
    h.append(f"#define NARENA {len(D.ARENAS)}")
    h.append(f"#define NTYPE {len(D.TYPES)}")
    for k, f in enumerate(D.TYPE_FIELDS):
        h.append(f"#define TY_{f.upper()} {k}")
    h += ["extern const short SIN_TAB[256];",
          "extern const short GUMBEL_Q8[256];",
          "extern const unsigned char ATAN_TAB[65];",
          f"extern const short TYPE_TAB[NTYPE][{len(D.TYPE_FIELDS)}];",
          "extern const unsigned char ARENA_MAP[NARENA][TH * TW];",
          "extern const unsigned char ARENA_SPAWN[NARENA][4][2];   /* P, a, b, c: tile x, y */",
          "extern const char *const ARENA_NAME[NARENA];",
          "#endif", ""]
    c = ["/* Generated by gen_tables.py from defs.py. Do not edit. */", '#include "sim_tables.h"', ""]

    def arr(vals, per=16):
        lines = []
        for i in range(0, len(vals), per):
            lines.append("    " + ", ".join(str(v) for v in vals[i:i + per]) + ",")
        return "\n".join(lines)
    c.append("const short SIN_TAB[256] = {\n" + arr(D.SIN) + "\n};")
    c.append("const unsigned char ATAN_TAB[65] = {\n" + arr(D.ATAN) + "\n};")
    c.append("const short GUMBEL_Q8[256] = {\n" + arr(D.GUMBEL_Q8) + "\n};")
    c.append(f"const short TYPE_TAB[NTYPE][{len(D.TYPE_FIELDS)}] = {{")
    for t in D.TYPES:
        c.append("    {" + ", ".join(str(v) for v in t[1:]) + "},   /* " + t[0] + " */")
    c.append("};")
    c.append("const unsigned char ARENA_MAP[NARENA][TH * TW] = {")
    spawns, names = [], []
    for i in range(len(D.ARENAS)):
        name, grid, sp = D.arena(i)
        flat = [v for row in grid for v in row]
        c.append("    { /* " + name + " */\n" + arr(flat, 24) + "\n    },")
        spawns.append([sp.get(k, (0, 0)) for k in "Pabc"])
        names.append(name)
    c.append("};")
    c.append("const unsigned char ARENA_SPAWN[NARENA][4][2] = {")
    for sp in spawns:
        c.append("    {" + ", ".join(f"{{{x}, {y}}}" for x, y in sp) + "},")
    c.append("};")
    c.append("const char *const ARENA_NAME[NARENA] = {" + ", ".join(f'"{n}"' for n in names) + "};")
    open(os.path.join(out, "sim_tables.h"), "w").write("\n".join(h))
    open(os.path.join(out, "sim_tables.c"), "w").write("\n".join(c) + "\n")


if __name__ == "__main__":
    main()
