#!/usr/bin/env python3
"""Build Tank Duel: generate tables, art and policies, compile with Retro68, make boot floppies.

    python3 tanks/build.py [--random] [--no-disk] [--se]

Policies come from tanks/policies/manifest.json ({"<type>": ["easy.npz", "normal.npz", "hard.npz"]},
paths relative to tanks/policies; types player, rusher, sniper, careful); --random uses untrained
nets instead (pipeline tests). Outputs in tanks/build/: gen/ (generated sources), cmake/ (build
tree, TankDuel.bin), app/TankDuel.bin (with its Finder icon), tankduel.img (800K Plus boot floppy:
trimmed System 6.0 + Narrow Screen + the game, which also boots an SE) and, with --se,
tankduel_se.img (1.44 MB System 6.0.7 floppy for the SE).
"""
import argparse
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
TC = os.path.expanduser("~/Retro68-build/toolchain/m68k-apple-macos/cmake/retro68.toolchain.cmake")
TYPES = ["player", "rusher", "sniper", "careful"]


def run(cmd, **kw):
    r = subprocess.run(cmd, capture_output=True, text=True, **kw)
    if r.returncode:
        sys.exit(f"FAILED: {' '.join(cmd)}\n{r.stdout[-4000:]}\n{r.stderr[-4000:]}")
    return r.stdout


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--random", action="store_true")
    ap.add_argument("--no-disk", action="store_true")
    ap.add_argument("--se", action="store_true")
    ap.add_argument("--out", default=os.path.join(HERE, "build"))
    ap.add_argument("--manifest", default=os.path.join(HERE, "policies", "manifest.json"))
    a = ap.parse_args()
    out = a.out
    gen = os.path.join(out, "gen")
    os.makedirs(gen, exist_ok=True)
    py = sys.executable
    run([py, os.path.join(HERE, "sim", "gen_tables.py")])
    print(run([py, os.path.join(HERE, "app", "gen_art.py"), gen]).strip())
    # policies: one compiled function per distinct file; POLMAP[type][difficulty] -> index
    polmap = [[-1, -1, -1] for _ in TYPES]
    if a.random:
        names = TYPES
        print(run([py, os.path.join(HERE, "app", "gen_policy.py"), gen, "--random"] + names).strip())
        for t in range(4):
            polmap[t] = [t, t, t]
    else:
        man = json.load(open(a.manifest))
        mdir = os.path.dirname(os.path.abspath(a.manifest))
        files = []
        for t, tname in enumerate(TYPES):
            for d, f in enumerate(man.get(tname, [])):
                if f not in files:
                    files.append(f)
                polmap[t][d] = files.index(f)
            if man.get(tname):
                for d in range(len(man[tname]), 3):
                    polmap[t][d] = polmap[t][len(man[tname]) - 1]
        specs = [f"p{k}={os.path.join(mdir, f)}" for k, f in enumerate(files)]
        print(run([py, os.path.join(HERE, "app", "gen_policy.py"), gen] + specs).strip())
    json.dump({"polmap": polmap, "names": TYPES if a.random else [f"p{k}" for k in range(len(files))]},
              open(os.path.join(gen, "polmap.json"), "w"))
    with open(os.path.join(gen, "polmap.h"), "w") as f:
        f.write("/* Generated by build.py: policy index per tank type (player, rusher, sniper, careful) and\n"
                "   difficulty (easy, normal, hard); -1 = scripted bot */\n")
        f.write("static const short POLMAP[4][3] = {" + ", ".join(
            "{" + ", ".join(str(v) for v in row) + "}" for row in polmap) + "};\n")
    cm = os.path.join(out, "cmake")
    run(["cmake", "-S", os.path.join(HERE, "app"), "-B", cm, "-G", "Ninja", f"-DCMAKE_TOOLCHAIN_FILE={TC}",
         f"-DGEN_DIR={gen}"])
    print(run(["cmake", "--build", cm]).strip().splitlines()[-1])
    size = run([os.path.expanduser("~/Retro68-build/toolchain/bin/m68k-apple-macos-size"),
                os.path.join(cm, "TankDuel.code.bin.gdb")])
    print(size.strip())
    appdir = os.path.join(out, "app")
    os.makedirs(appdir, exist_ok=True)
    app = os.path.join(appdir, "TankDuel.bin")
    print(run([py, "-I", os.path.join(ROOT, "toolchain", "icons", "add_icon.py"), os.path.join(cm, "TankDuel.bin"),
               "--icon", os.path.join(ROOT, "toolchain", "icons", "art", "tankduel.txt"), "--out", app]).strip())
    sys.path.insert(0, os.path.join(ROOT, "toolchain", "icons"))
    import rsrc                                   # the file is called "Tank Duel" on the disks
    h, d, r = rsrc.read_macbinary(app)
    h = bytearray(h)
    nm = b"Tank Duel"
    h[1] = len(nm)
    h[2:65] = nm + b"\0" * (63 - len(nm))
    rsrc.write_macbinary(app, bytes(h), d, r)
    print(f"app {os.path.getsize(app)} bytes -> {app}")
    if a.no_disk:
        return
    img = os.path.join(out, "tankduel.img")
    print(run([py, "-I", os.path.join(ROOT, "toolchain", "template", "build_disk.py"), "--app", app,
               "--out", img, "--label", "Tank Duel", "--keep-se"]).strip().splitlines()[-1])
    print("Plus floppy ->", img)
    if a.se:
        se = os.path.join(out, "tankduel_se.img")
        print(run([py, "-I", os.path.join(HERE, "app", "make_se_floppy.py"), "--app", app, "--out", se]).strip())
        print("SE floppy ->", se)


if __name__ == "__main__":
    main()
