#!/usr/bin/env python3
"""Make the firmware's CA bundle (firmware/plusmodem/ca_bundle.h) from Mozilla's root certificates.

    python3 modem/tools/gen_ca_bundle.py [cacert.pem]

Input: a PEM file of trusted roots, by default curl's extract of Mozilla's list
(https://curl.se/ca/cacert.pem, the roots Mozilla trusts for websites), plus the legacy roots in LEGACY
taken from macOS's own store (/etc/ssl/cert.pem). Those are needed because the core's verifier looks up
only the issuer of the top certificate a server sends: Anthropic, OpenAI, OpenRouter and Google send
GTS Root R4 cross-signed by GlobalSign Root CA, which Mozilla dropped in 2026 (macOS still trusts it,
until 2028), so without it every API call would fail. Output: the binary format the
Arduino core's WiFiClientSecure::setCACertBundle() reads (libraries/WiFiClientSecure/src/esp_crt_bundle.c):

    u16 count, then per root: u16 subject length, u16 key length, subject (DER Name), key (DER
    SubjectPublicKeyInfo); sorted by subject bytes, because the firmware looks roots up by binary search.

Only the subject and public key of each root are kept (about 0.5 KB each), so the whole Mozilla list
fits in about 70 KB of flash. Standard library only.
"""
import base64
import datetime
import hashlib
import os
import re
import sys
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "firmware", "plusmodem", "ca_bundle.h")
URL = "https://curl.se/ca/cacert.pem"
SYSTEM_PEM = "/etc/ssl/cert.pem"
# cross-signing roots still sent in chains (subject CN, organisation)
LEGACY = [b"GlobalSign Root CA", b"AAA Certificate Services"]


def tlv(b, i):
    """(tag, start of value, end of value) of the DER element at b[i]."""
    tag = b[i]
    n = b[i + 1]
    i += 2
    if n & 0x80:
        k = n & 0x7F
        n = int.from_bytes(b[i:i + k], "big")
        i += k
    return tag, i, i + n


def subject_and_key(der):
    _, s, _ = tlv(der, 0)                 # Certificate SEQUENCE
    _, i, _ = tlv(der, s)                 # tbsCertificate SEQUENCE
    fields = []
    while len(fields) < 7:
        tag, vs, ve = tlv(der, i)
        if not fields and tag == 0xA0:     # [0] version (optional)
            i = ve
            continue
        fields.append(der[i:ve])
        i = ve
    # serial, signature algorithm, issuer, validity, subject, subjectPublicKeyInfo
    return fields[4], fields[5]


def certs(pem):
    for m in re.finditer(rb"-----BEGIN CERTIFICATE-----(.*?)-----END CERTIFICATE-----", pem, re.S):
        yield base64.b64decode(b"".join(m.group(1).split()))


def cn_is(name, cn):
    """True if the DER Name's commonName (2.5.4.3) is exactly cn."""
    oid = bytes([0x06, 0x03, 0x55, 0x04, 0x03])
    i = name.find(oid)
    if i < 0:
        return False
    _, vs, ve = tlv(name, i + len(oid))
    return name[vs:ve] == cn


def main():
    if len(sys.argv) > 1:
        with open(sys.argv[1], "rb") as f:
            pem = f.read()
        source = os.path.basename(sys.argv[1])
    else:
        with urllib.request.urlopen(URL, timeout=60) as r:
            pem = r.read()
        source = URL
    date = re.search(rb"Certificate data from Mozilla as of: (.*)", pem)
    date = date.group(1).decode().strip() if date else "unknown"
    roots = [subject_and_key(der) for der in certs(pem)]
    n_mozilla = len(roots)
    with open(SYSTEM_PEM, "rb") as f:
        for der in certs(f.read()):
            name, key = subject_and_key(der)
            if any(cn_is(name, cn) for cn in LEGACY):
                roots.append((name, key))
    roots = sorted(set(roots))
    blob = bytearray(len(roots).to_bytes(2, "big"))
    for name, key in roots:
        blob += len(name).to_bytes(2, "big") + len(key).to_bytes(2, "big") + name + key
    lines = ["// Generated by modem/tools/gen_ca_bundle.py on %s. Do not edit." % datetime.date.today(),
             "// %d roots: %d from %s (Mozilla data as of %s, sha256 %s) and %d legacy cross-signing"
             % (len(roots), n_mozilla, source, date, hashlib.sha256(pem).hexdigest()[:16], len(roots) - n_mozilla),
             "// roots from %s (%s)." % (SYSTEM_PEM, ", ".join(x.decode() for x in LEGACY)),
             "// Format: libraries/WiFiClientSecure/src/esp_crt_bundle.c in the Arduino core for ESP32.",
             "#pragma once", "#include <stdint.h>",
             "static const uint8_t ca_bundle[%d] = {" % len(blob)]
    for k in range(0, len(blob), 24):
        lines.append("".join("%d," % x for x in blob[k:k + 24]))
    lines.append("};")
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("%s: %d roots, %d bytes (Mozilla data as of %s)" % (os.path.relpath(OUT), len(roots), len(blob), date))


if __name__ == "__main__":
    main()
