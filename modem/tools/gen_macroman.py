#!/usr/bin/env python3
"""Generate modem/firmware/plusmodem/macroman_tables.h for textconv.cpp (Python 3 stdlib only).

    python3 modem/tools/gen_macroman.py

The tables reproduce askai/relay/textconv.py's character decisions on the ESP32, which has no
unicodedata: Python's mac_roman codec, _REPLACE and _DROP (read from textconv.py itself, so they
stay in sync), and for every other code point what _mac_char() and _drop_symbols() do with it:

  SYM    categories So/Sk/Cs/Co: dropped by _drop_symbols (and by _mac_char)
  DROP   categories Cn/Mn/Me/Cf: dropped by _mac_char only
  bytes  NFKD gives encodable non-Mn characters: those Mac Roman bytes
  '?'    anything else

plus the sets behind str.isspace() / re's \\s and re's \\d. Everything is derived by calling
textconv's own functions on every code point U+0000..U+10FFFF, so the tables are exact for the
Unicode version of the Python that runs this script (recorded in the header).
"""
import os
import re
import sys
import unicodedata

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(ROOT, "askai", "relay"))
import textconv  # noqa: E402

OUT = os.path.join(ROOT, "modem", "firmware", "plusmodem", "macroman_tables.h")


def cstr(b):
    """bytes -> C string literal (octal escapes: no hex-digit or trigraph surprises)."""
    s = ""
    for x in b:
        c = chr(x)
        s += c if 32 <= x < 127 and c not in '"\\?' else "\\%03o" % x
    return '"' + s + '"'


def ranges(cps):
    out = []
    for cp in sorted(cps):
        if out and out[-1][1] == cp - 1:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return out


def rows(items, per=8):
    items = list(items)
    return "\n".join("    " + " ".join(items[i:i + per]) for i in range(0, len(items), per))


def main():
    mac_to_uni = [ord(bytes([b]).decode("mac_roman")) for b in range(256)]
    assert mac_to_uni[:128] == list(range(128))
    uni_to_mac = {cp: b for b, cp in enumerate(mac_to_uni)}

    replace = {}
    for k in textconv._REPLACE:
        if len(k) == 1:                       # the 2-char key "•​" can never match one character
            replace[ord(k)] = textconv._mac_char(k)
    drop = sorted(ord(c) for c in textconv._DROP)
    for cp in drop:
        assert textconv._mac_char(chr(cp)) == b""

    # textconv.cpp handles these itself; the run table doesn't care what they are
    explicit = set(range(128)) | set(uni_to_mac) | set(replace) | set(drop)
    # Mac Roman characters are never dropped by _drop_symbols (none of them is Mn)
    for cp in uni_to_mac:
        assert textconv._encodable(chr(cp))

    # run table: (start << 11) | payload; payload 0 '?', 1 SYM, 2 DROP, 3+b one byte b (incrementing
    # with the code point), 259+i the string kMulti[i]
    multi = []
    multi_ix = {}
    runs = []                                  # [start, payload, is_seq]
    for cp in range(0x110000):
        if cp in explicit:
            continue
        ch = chr(cp)
        r = textconv._mac_char(ch)
        sym = unicodedata.category(ch) in ("So", "Sk", "Cs", "Co")    # not encodable, not in _REPLACE
        if sym:
            assert r == b""
            pay, seq = 1, False
        elif r == b"":
            pay, seq = 2, False
        elif r == b"?":
            pay, seq = 0, False
        elif len(r) == 1:
            pay, seq = 3 + r[0], True
        else:
            if r not in multi_ix:
                multi_ix[r] = len(multi)
                multi.append(r)
            pay, seq = 259 + multi_ix[r], False
        if runs:
            st, p, s = runs[-1]
            if seq and s and pay == p + (cp - st) and pay <= 258:
                continue
            if not seq and not s and pay == p:
                continue
        runs.append([cp, pay, seq])
    runs[0][0] = 0
    assert len(multi) + 259 < 2048

    spaces = [cp for cp in range(0x110000) if chr(cp).isspace()]
    assert spaces == [cp for cp in range(0x110000) if re.match(r"\s", chr(cp))]
    digits = [cp for cp in range(0x110000) if re.match(r"\d", chr(cp))]

    L = []
    L.append("// Generated by modem/tools/gen_macroman.py from askai/relay/textconv.py. Do not edit.")
    L.append("// Python %s, Unicode %s (unicodedata.unidata_version)." % (sys.version.split()[0],
                                                                       unicodedata.unidata_version))
    L.append("#pragma once")
    L.append("#include <stdint.h>")
    L.append("")
    L.append("namespace tc {")
    L.append("namespace tab {")
    L.append("")
    L.append("// Mac Roman 0x80..0xFF -> Unicode (Python's mac_roman codec)")
    L.append("static const uint16_t kMacToUni[128] = {")
    L.append(rows(("0x%04X," % cp for cp in mac_to_uni[128:]), 8))
    L.append("};")
    L.append("")
    L.append("// (code point << 8) | Mac Roman byte for 0x80..0xFF, sorted by code point")
    L.append("static const uint32_t kUniToMac[128] = {")
    L.append(rows(("0x%06X," % (cp << 8 | uni_to_mac[cp]) for cp in sorted(uni_to_mac) if cp >= 128), 8))
    L.append("};")
    L.append("")
    L.append("// textconv._REPLACE: code point and what _mac_char() makes of it, sorted")
    L.append("struct Repl { uint32_t cp; const char *mac; };")
    L.append("static const Repl kReplace[] = {")
    L.append(rows(("{0x%04X, %s}," % (cp, cstr(replace[cp])) for cp in sorted(replace)), 4))
    L.append("};")
    L.append("")
    L.append("// textconv._DROP, sorted")
    L.append("static const uint32_t kDrop[] = {")
    L.append(rows(("0x%04X," % cp for cp in drop), 8))
    L.append("};")
    L.append("")
    L.append("// str.isspace() (= re's \\s), inclusive ranges")
    L.append("static const uint32_t kSpace[][2] = {")
    L.append(rows(("{0x%X, 0x%X}," % tuple(r) for r in ranges(spaces)), 5))
    L.append("};")
    L.append("")
    L.append("// re's \\d (Unicode decimal digits), inclusive ranges")
    L.append("static const uint32_t kDigit[][2] = {")
    L.append(rows(("{0x%X, 0x%X}," % tuple(r) for r in ranges(digits)), 5))
    L.append("};")
    L.append("")
    L.append("// Every other code point: (start << 11) | payload, sorted. payload 0: '?', 1: SYM (dropped,")
    L.append("// also by _drop_symbols), 2: DROP (dropped by _mac_char), 3..258: the one byte")
    L.append("// payload - 3 + (cp - start), 259..: the string kMulti[payload - 259].")
    L.append("enum { kQuest = 0, kSym = 1, kDropped = 2, kSeq = 3, kMultiBase = 259 };")
    L.append("static const uint32_t kRuns[] = {")
    L.append(rows(("0x%08X," % (st << 11 | p) for st, p, _ in runs), 8))
    L.append("};")
    L.append("")
    L.append("static const char *const kMulti[] = {")
    L.append(rows(("%s," % cstr(b) for b in multi), 8))
    L.append("};")
    L.append("")
    L.append("}  // namespace tab")
    L.append("}  // namespace tc")
    with open(OUT, "w") as f:
        f.write("\n".join(L) + "\n")
    flash = (256 + 512 + len(replace) * 8 + len(drop) * 4 + len(ranges(spaces)) * 8 + len(ranges(digits)) * 8
             + len(runs) * 4 + len(multi) * 4 + sum(len(b) + 1 for b in multi)
             + sum(len(b) + 1 for b in replace.values()))
    print("%s: %d runs, %d strings, %d replacements, about %d bytes of tables (Unicode %s)"
          % (os.path.relpath(OUT, ROOT), len(runs), len(multi), len(replace), flash,
             unicodedata.unidata_version))


if __name__ == "__main__":
    main()
