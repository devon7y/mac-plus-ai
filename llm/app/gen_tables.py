#!/usr/bin/env python3
"""Write tables.c (EXP12 and SILU) from the reference (llm/ref/model.py)."""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(os.path.dirname(HERE), "ref"))
import model  # noqa: E402


def arr(name, vals):
    body = ",".join(str(v) for v in vals)
    return f"const int16_t {name}[{len(vals)}] = {{{body}}};\n"


out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "tables.c")
open(out, "w").write('/* Generated by gen_tables.py from llm/ref/model.py. */\n#include "engine.h"\n'
                     + arr("px_exp12", model.EXP12) + arr("px_silu", model.SILU))
