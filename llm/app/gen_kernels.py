#!/usr/bin/env python3
"""Generate kernels68k.s: the benchmark's table kernels (llm/bench/gen_bench.py, verified bit-exact
in MAME) behind C-callable wrappers for Retro68 (args on the stack, d2-d7/a2-a6 preserved, a5 never
touched). Same instruction sequences as the benchmark; only entry/exit and the loop-count register of
wsum differ (wsum keeps its count in a0 instead of -12(a5)).

  void k_tab4(const int16_t *x, long groups, int16_t *lut);        W4 interleaved tables
  void k_mvw(const int16_t *codes, const int16_t *lutmid, long nout, long n, int16_t *out);
  void k_tab5(const int16_t *x, long groups, int16_t *lut);        B5 contiguous tables
  void k_mvb5(const uint8_t *codes, const int16_t *lut, long nout, long n, int16_t *out);
  void k_pairs(const int16_t *h, long npairs, int16_t *lut);       256-entry pair tables
  void k_ptab(const int16_t *u, long n, int16_t *ptab);            16 words (i-8)*u per position
  void k_wsum(const uint8_t *vb, const int16_t *ptab, long ctx, int16_t *out);   40 dims
"""
import os
import sys

NO_B5 = "--no-b5" in sys.argv          # Plus build: W4 only (the B5 kernels are for the SE)
sys.argv = [a for a in sys.argv if a != "--no-b5"]
asm = []
emit = asm.append
SAVE = "%d2-%d7/%a2-%a6"
ARG = 48            # 11 saved registers (44 bytes) + return address


def arg(i):
    return f"{ARG + 4 * i}(%sp)"


def digits(i, k):
    return [(i // 3 ** j) % 3 for j in range(k)]


emit("| Generated by gen_kernels.py (from llm/bench/gen_bench.py). 68000, position-independent.\n"
     "        .text")

# ---- group-table builders (bench: bld_ki / bld_kc)
for k, lay in ((4, "c"), (5, "c")):
    emit(f"bld_{k}{lay}:\n        movem.w (%a0),%d1-%d{k}\n        move.w  %d1,%d6")
    for j in range(1, k):
        emit(f"        move.w  %d{j + 1},%d0\n        sub.w   %d6,%d{j + 1}\n        sub.w   %d6,%d{j + 1}\n"
             f"        add.w   %d0,%d6")
    emit("        move.w  %d6,%d0\n        neg.w   %d0")
    n = 3 ** k
    for idx in range(n):
        emit("        move.w  %d0,(%a3)\n        adda.w  %d7,%a3" if lay == "i" else "        move.w  %d0,(%a3)+")
        if idx < n - 1:
            dg = digits(idx, k)
            j = next(j for j in range(k) if dg[j] < 2)
            emit(f"        add.w   %d{1 if j == 0 else j + 1},%d0")
    emit("        rts")

# ---- k_tab4 / k_tab5
emit(f"""        .globl  k_tab4
k_tab4: movem.l {SAVE},-(%sp)
        movea.l {arg(0)},%a0
        move.l  {arg(1)},%d7
        movea.l {arg(2)},%a3
        move.l  %d7,%d0
        lsl.l   #3,%d0
        lea     0(%a0,%d0.l),%a4
1:      jsr     bld_4c(%pc)
        addq.l  #8,%a0
        cmpa.l  %a4,%a0
        bcs.s   1b
        movem.l (%sp)+,{SAVE}
        rts""")
if True:
    emit(f"""        .globl  k_tab5
k_tab5: movem.l {SAVE},-(%sp)
        movea.l {arg(0)},%a0
        move.l  {arg(1)},%d0
        movea.l {arg(2)},%a1
        mulu.w  #10,%d0
        lea     0(%a0,%d0.l),%a4
1:      movea.l %a1,%a3
        jsr     bld_5c(%pc)
        lea     10(%a0),%a0
        lea     486(%a1),%a1
        cmpa.l  %a4,%a0
        bcs.s   1b
        movem.l (%sp)+,{SAVE}
        rts""")

# ---- k_mvw: computed entry into 128 unrolled lookups (bench mv_W)
emit(f"""        .globl  k_mvw
k_mvw:  movem.l {SAVE},-(%sp)
        movea.l {arg(0)},%a1
        movea.l {arg(1)},%a2
        move.l  {arg(2)},%d6
        move.l  {arg(3)},%d5
        movea.l {arg(4)},%a6
        lea     mvW_end(%pc),%a4
        mulu.w  #6,%d5
        suba.w  %d5,%a4
        subq.l  #1,%d6
1:      moveq   #0,%d1
        jsr     (%a4)
        move.w  %d1,(%a6)+
        dbf     %d6,1b
        movem.l (%sp)+,{SAVE}
        rts
mvW_blk:""")
for _ in range(128):
    emit("        move.w  (%a1)+,%d0\n        add.w   0(%a2,%d0.w),%d1")
emit("mvW_end: rts")

# ---- k_mvw40: rows of exactly 40 lookups, no jsr/rts per row
emit(f"""        .globl  k_mvw40
k_mvw40: movem.l {SAVE},-(%sp)
        movea.l {arg(0)},%a1
        movea.l {arg(1)},%a2
        move.l  {arg(2)},%d6
        movea.l {arg(3)},%a6
        subq.l  #1,%d6
        bmi     9f
1:      moveq   #0,%d1""")
for _ in range(40):
    emit("        move.w  (%a1)+,%d0\n        add.w   0(%a2,%d0.w),%d1")
emit(f"""        move.w  %d1,(%a6)+
        dbf     %d6,1b
9:      movem.l (%sp)+,{SAVE}
        rts""")

# ---- k_mvw32: rows of exactly 32 lookups (W5 gate/up)
emit(f"""        .globl  k_mvw32
k_mvw32: movem.l {SAVE},-(%sp)
        movea.l {arg(0)},%a1
        movea.l {arg(1)},%a2
        move.l  {arg(2)},%d6
        movea.l {arg(3)},%a6
        subq.l  #1,%d6
        bmi     9f
1:      moveq   #0,%d1""")
for _ in range(32):
    emit("        move.w  (%a1)+,%d0\n        add.w   0(%a2,%d0.w),%d1")
emit(f"""        move.w  %d1,(%a6)+
        dbf     %d6,1b
9:      movem.l (%sp)+,{SAVE}
        rts""")

# ---- k_mvb5 (bench mv_B5)
if not NO_B5:
  emit(f"""        .globl  k_mvb5
k_mvb5: movem.l {SAVE},-(%sp)
        movea.l {arg(0)},%a1
        movea.l {arg(1)},%a3
        move.l  {arg(2)},%d6
        move.l  {arg(3)},%d5
        movea.l {arg(4)},%a6
        lea     mvB5_end(%pc),%a4
        mulu.w  #14,%d5
        suba.w  %d5,%a4
        subq.l  #1,%d6
1:      moveq   #0,%d1
        movea.l %a3,%a2
        jsr     (%a4)
        move.w  %d1,(%a6)+
        dbf     %d6,1b
        movem.l (%sp)+,{SAVE}
        rts
mvB5_blk:""")
  for _ in range(103):
    emit("        moveq   #0,%d0\n        move.b  (%a1)+,%d0\n        add.w   %d0,%d0\n"
         "        add.w   0(%a2,%d0.w),%d1\n        lea     486(%a2),%a2")
  emit("mvB5_end: rts")

# ---- pair tables (bench bld_pair / bpairs)
emit("""bld_pair:
        move.w  (%a0),%d4
        move.w  2(%a0),%d2
        move.w  %d4,%d0
        add.w   %d2,%d0
        lsl.w   #3,%d0
        neg.w   %d0
        move.w  %d2,%d3
        lsl.w   #4,%d3
        sub.w   %d2,%d3
        sub.w   %d3,%d4""")
for row in range(16):
    for col in range(16):
        emit("        move.w  %d0,(%a3)+")
        if col < 15:
            emit("        add.w   %d2,%d0")
        elif row < 15:
            emit("        add.w   %d4,%d0")
emit(f"""        rts
        .globl  k_pairs
k_pairs: movem.l {SAVE},-(%sp)
        movea.l {arg(0)},%a0
        move.l  {arg(1)},%d6
        movea.l {arg(2)},%a3
        subq.l  #1,%d6
1:      jsr     bld_pair(%pc)
        addq.l  #4,%a0
        dbf     %d6,1b
        movem.l (%sp)+,{SAVE}
        rts""")

# ---- k_ptab: per-position tables (the bench's softmax inner loop, from given weights)
emit(f"""        .globl  k_ptab
k_ptab: movem.l {SAVE},-(%sp)
        movea.l {arg(0)},%a0
        move.l  {arg(1)},%d6
        movea.l {arg(2)},%a3
        subq.l  #1,%d6
1:      move.w  (%a0)+,%d2
        move.w  %d2,%d3
        lsl.w   #3,%d3
        neg.w   %d3""")
for i in range(16):
    emit("        move.w  %d3,(%a3)+")
    if i < 15:
        emit("        add.w   %d2,%d3")
emit(f"""        dbf     %d6,1b
        movem.l (%sp)+,{SAVE}
        rts""")

# ---- k_wsum (bench wsum; count kept in a0)
emit(f"""        .globl  k_wsum
k_wsum: movem.l {SAVE},-(%sp)
        movea.l {arg(0)},%a3
        movea.l {arg(1)},%a4
        movea.l {arg(2)},%a0
        movea.l {arg(3)},%a6
        subq.l  #1,%a0
        moveq   #0,%d0""")
off = 0
for blk in (6, 6, 6, 6, 6, 6, 4):
    emit(f"        lea     {off}(%a3),%a1\n        movea.l %a4,%a2")
    for r in range(1, blk + 1):
        emit(f"        moveq   #0,%d{r}")
    emit("        move.w  %a0,%d7")
    lbl = f"ws{off}"
    emit(f"{lbl}:")
    for r in range(1, blk + 1):
        emit(f"        move.b  (%a1)+,%d0\n        add.w   0(%a2,%d0.w),%d{r}")
    emit(f"        lea     {40 - blk}(%a1),%a1\n        lea     32(%a2),%a2\n        dbf     %d7,{lbl}")
    for r in range(1, blk + 1):
        emit(f"        move.w  %d{r},(%a6)+")
    off += blk
emit(f"""        movem.l (%sp)+,{SAVE}
        rts""")


# ======================================================================= scalar loops (not in the bench)
def prologue(name):
    emit(f"        .globl  {name}\n{name}: movem.l {SAVE},-(%sp)")


def epilogue():
    emit(f"        movem.l (%sp)+,{SAVE}\n        rts")


