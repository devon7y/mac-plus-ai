#!/usr/bin/env python3
"""Generate the 68000 benchmark for the 6.7M-parameter ternary mixture-of-experts chatbot.

Writes bench.s (68000 assembly, position-independent) plus layout.json describing buffers
and result tags. The program times each part of one token's forward pass on the real
model shapes, tests whether the full model fits in memory, and leaves small test cases in
memory so verify.py can check the kernels compute the right thing.

Model (option A): 6 layers, width 160, 4 query heads / 2 key-value heads (head dim 40),
4 experts per layer (one active, feed-forward width 512) + router, 2,048-token vocabulary
with a 4-bit output table, keys/values stored as 4-bit codes.

Ternary storage variants (weights in groups of k, looked up in per-token tables):
  W4/W5: 16-bit pre-scaled codes (4 / 3.2 bits per weight), interleaved tables
  B4/B5: byte codes (2 / 1.6 bits per weight), one table per group
"""
import json
import math
import os
import sys

OUT = sys.argv[1] if len(sys.argv) > 1 else "."

D, L, H, KVH, HD, FF, NE, VOCAB = 160, 6, 4, 2, 40, 512, 4, 2048
QKV = D + 2 * KVH * HD              # 320 rows
GU = 2 * FF + NE                    # gate + up of one expert + router = 1028 rows
HEAD_PAIRS, ATT_PAIRS = D // 2, HD // 2
CTX_MAX = 128
VARIANTS = {"W4": (4, "W"), "W5": (5, "W"), "B4": (4, "B"), "B5": (5, "B")}
CTXS = (16, 64, 128)
REPS = 3


def groups(n, k):
    return -(-n // k)


# ---------------------------------------------------------------- buffer layout
layout, cursor = {}, 0


def alloc(name, size):
    global cursor
    layout[name] = (cursor, size)
    cursor += (size + 3) & ~3


alloc("RES", 4096)
alloc("X160", 2 * 170)
alloc("H512", 2 * 520)
alloc("QKV", 2 * QKV)
alloc("ATTO", 2 * D)
alloc("T160", 2 * D)
alloc("GUO", 2 * GU)
alloc("LOGITS", 2 * VOCAB)
alloc("SC", 2 * CTX_MAX)
alloc("LUT", 64 * 1024)
alloc("EXPT", 512)
alloc("ATTT", ATT_PAIRS * 512)
alloc("KC", KVH * CTX_MAX * ATT_PAIRS * 2)
alloc("VC", KVH * CTX_MAX * HD)
alloc("PTAB", CTX_MAX * 32)
alloc("HEADT", HEAD_PAIRS * 512)
alloc("HEADW", VOCAB * HEAD_PAIRS * 2)
mats = {}
for v, (k, kind) in VARIANTS.items():
    unit = 2 if kind == "W" else 1
    g160, g512 = groups(D, k), groups(FF, k)
    for m, rows, g in (("QKV", QKV, g160), ("WO", D, g160), ("GU", GU, g160), ("DN", D, g512)):
        alloc(f"{v}_{m}", rows * g * unit)
        mats[f"{v}_{m}"] = (rows, g)
# correctness tests
TG, TR = 8, 6
for v, (k, kind) in VARIANTS.items():
    alloc(f"T{v}_X", 2 * TG * k)
    alloc(f"T{v}_W", TR * TG * (2 if kind == "W" else 1))
    alloc(f"T{v}_O", 2 * TR)
alloc("TLUT", 243 * TG * 2)
alloc("TP_H", 2 * 8)
alloc("TP_T", 4 * 512)
alloc("TP_W", 3 * 4 * 2)
alloc("TP_O", 2 * 3)
alloc("TS_SC", 2 * 5)
alloc("TS_PT", 5 * 32)
alloc("TS_VC", 5 * HD)
alloc("TS_ACC", 2 * HD)
MAIN = cursor


def full_model_bytes(k, kind):
    unit = 2 if kind == "W" else 1
    g160, g512 = groups(D, k), groups(FF, k)
    per_layer = (QKV + D) * g160 + NE * (2 * FF * g160 + D * g512) + NE * g160
    tern = L * per_layer * unit
    head = VOCAB * HEAD_PAIRS * 2
    kv = L * KVH * CTX_MAX * (ATT_PAIRS * 2 + HD)
    tables = (243 * groups(FF, 5) * 2 if k == 5 else 81 * groups(FF, 4) * 2) + HEAD_PAIRS * 512
    return tern + head + kv + tables + 32 * 1024


FIT = {v: full_model_bytes(*kv) for v, kv in VARIANTS.items()}


def fourcc(s):
    return "0x" + s.encode().hex()


# ---------------------------------------------------------------- code generation
asm = []
emit = asm.append


def ptr(reg, buf, extra=0):
    off = layout[buf][0] + extra
    emit(f"        movea.l -4(%a5),{reg}")
    if off:
        emit(f"        adda.l  #{off},{reg}")


def rec(tag, d2=None, d3=None, d4=None):
    emit(f"        move.l  #{fourcc(tag)},%d1")
    for r, v in (("%d2", d2), ("%d3", d3), ("%d4", d4)):
        if v is not None:
            emit(f"        move.l  #{v},{r}")
    emit("        jsr     rec")


emit("""| Generated by gen_bench.py. 68000, position-independent, no relocations.
        .text
        .globl _start
_start:
        .short  0xA063                  | _MaxApplZone""")

# memory-fit tests (before the main allocation)
for v, size in FIT.items():
    emit(f"""        move.l  #{size},%d0
        .short  0xA11E                  | _NewPtr
        moveq   #0,%d5
        move.l  %a0,%d0
        beq.s   1f
        moveq   #1,%d5
        .short  0xA01F                  | _DisposPtr
1:      move.l  %d5,-{44 + 4 * list(FIT).index(v)}(%a5)""")

emit(f"""        move.l  #{MAIN},%d0
        .short  0xA11E                  | _NewPtr
        move.l  %a0,%d0
        bne.s   2f
3:      bra.s   3b                      | out of memory: hang
2:      move.l  %a0,-4(%a5)
        move.l  #0x2545F491,-8(%a5)     | random seed""")
ptr("%a0", "RES")
emit("""        move.l  #0x424E4348,(%a0)       | 'BNCH'
        clr.l   4(%a0)                  | status: running
        clr.l   8(%a0)                  | entry count""")
for i, (v, size) in enumerate(FIT.items()):
    emit(f"        move.l  -{44 + 4 * i}(%a5),%d2")
    rec(f"F{v} ", None, size)

# ---- initialization
emit("        jsr     init_expt")
for buf, n in (("X160", 170), ("H512", 512), ("QKV", QKV), ("ATTO", D)):
    ptr("%a0", buf)
    emit(f"        move.w  #{n - 1},%d6\n        jsr     fill_rand")
for v, (k, kind) in VARIANTS.items():
    for m in ("QKV", "WO", "GU", "DN"):
        rows, g = mats[f"{v}_{m}"]
        ptr("%a0", f"{v}_{m}")
        emit(f"        move.w  #{rows - 1},%d6\n        move.w  #{g},%d5\n        jsr     fill_{kind}{k}")
ptr("%a0", "HEADW")
emit(f"        move.w  #{VOCAB - 1},%d6\n        move.w  #{HEAD_PAIRS},%d5\n        jsr     fill_pairs")
ptr("%a0", "KC")
emit(f"        move.w  #{KVH * CTX_MAX - 1},%d6\n        move.w  #{ATT_PAIRS},%d5\n        jsr     fill_pairs")
ptr("%a0", "VC")
emit(f"        move.w  #{KVH * CTX_MAX * HD - 1},%d6\n        jsr     fill_vcodes")

# ---- correctness tests
for v, (k, kind) in VARIANTS.items():
    ptr("%a0", f"T{v}_X")
    emit(f"        move.w  #{TG * k - 1},%d6\n        jsr     fill_rand")
    ptr("%a0", f"T{v}_W")
    emit(f"        move.w  #{TR - 1},%d6\n        move.w  #{TG},%d5\n        jsr     fill_{kind}{k}_rand")
    ptr("%a0", f"T{v}_X")
    ptr("%a4", f"T{v}_X", 2 * TG * k)
    ptr("%a1", "TLUT")
    emit(f"        move.w  #{TG * 2},%d7\n        jsr     bv_{v}")
    ptr("%a1", f"T{v}_W")
    ptr("%a2", "TLUT", 32768 if kind == "W" else 0)
    ptr("%a3", "TLUT")
    ptr("%a6", f"T{v}_O")
    bpg = {"W": 6, "B4": 10, "B5": 14}["W" if kind == "W" else v]
    emit(f"        lea     mv{'W' if kind == 'W' else v}_end(%pc),%a4\n        suba.w  #{TG * bpg},%a4")
    emit(f"        move.w  #{TR - 1},%d6\n        jsr     mv_{'W' if kind == 'W' else v}")
ptr("%a0", "TP_H")
emit("        move.w  #7,%d6\n        jsr     fill_rand")
ptr("%a0", "TP_W")
emit("        move.w  #2,%d6\n        move.w  #4,%d5\n        jsr     fill_pairs_rand")
ptr("%a0", "TP_H")
ptr("%a3", "TP_T")
emit("        moveq   #3,%d6\n        jsr     bpairs")
ptr("%a1", "TP_W")
ptr("%a2", "TP_T", 32768)
ptr("%a6", "TP_O")
emit("        lea     mvW_end(%pc),%a4\n        suba.w  #24,%a4\n        moveq   #2,%d6\n        jsr     mv_W")
ptr("%a0", "TS_SC")
emit("        moveq   #4,%d6\n        jsr     fill_rand")
ptr("%a0", "TS_VC")
emit(f"        move.w  #{5 * HD - 1},%d6\n        jsr     fill_vcodes_rand")
ptr("%a0", "TS_SC")
ptr("%a3", "TS_PT")
ptr("%a2", "EXPT")
emit("        moveq   #4,%d6\n        jsr     softmax")
ptr("%a3", "TS_VC")
ptr("%a4", "TS_PT")
ptr("%a6", "TS_ACC")
emit("        move.w  #4,-12(%a5)\n        jsr     wsum")
DUMPS = [f"T{v}_{p}" for v in VARIANTS for p in ("X", "W", "O")] + \
    ["TP_H", "TP_W", "TP_O", "TS_SC", "TS_PT", "TS_VC", "TS_ACC", "EXPT"]
for i, name in enumerate(DUMPS):
    ptr("%a0", name)
    emit("        move.l  %a0,%d2")
    rec("Dump", None, layout[name][1], i)

# ---- timings
for v in VARIANTS:
    emit(f"        lea     tern_{v}(%pc),%a0\n        move.l  #{fourcc('t' + v + ' ')},%d1\n        jsr     timeit")
for c in CTXS:
    emit(f"        lea     attn_{c}(%pc),%a0\n        move.l  #{fourcc('a%03d' % c)},%d1\n        jsr     timeit")
for name in ("head", "misc", "full"):
    emit(f"        lea     tok_{name}(%pc),%a0\n        move.l  #{fourcc(name)},%d1\n        jsr     timeit")
ptr("%a0", "RES")
emit("""        move.l  #1,4(%a0)               | status: done
done:   bra.s   done
""")

# ---- helpers: record, timing, random
emit(f"""| rec: append (d1 tag, d2, d3, d4) to the results block
rec:    movea.l -4(%a5),%a0
        move.l  8(%a0),%d0
        addq.l  #1,8(%a0)
        lsl.l   #4,%d0
        lea     12(%a0,%d0.l),%a0
        movem.l %d1-%d4,(%a0)
        rts

| timeit: a0 = routine, d1 = tag. Runs it {REPS} times, records ticks.
timeit: move.l  %a0,-20(%a5)
        move.l  %d1,-32(%a5)
        move.w  #{REPS},-24(%a5)
        move.l  (0x16A).w,-28(%a5)
1:      movea.l -20(%a5),%a0
        jsr     (%a0)
        subq.w  #1,-24(%a5)
        bne.s   1b
        move.l  (0x16A).w,%d2
        sub.l   -28(%a5),%d2
        move.l  -32(%a5),%d1
        moveq   #{REPS},%d3
        moveq   #0,%d4
        jsr     rec
        rts

| rand: xorshift32 (x ^= x<<13; x ^= x>>17; x ^= x<<5) -> d0. Preserves all but d0.
rand:   move.l  %d1,-(%sp)
        move.l  -8(%a5),%d0
        move.l  %d0,%d1
        lsl.l   #8,%d1
        lsl.l   #5,%d1
        eor.l   %d1,%d0
        move.l  %d0,%d1
        swap    %d1
        and.l   #0xFFFF,%d1
        lsr.l   #1,%d1
        eor.l   %d1,%d0
        move.l  %d0,%d1
        lsl.l   #5,%d1
        eor.l   %d1,%d0
        move.l  %d0,-8(%a5)
        move.l  (%sp)+,%d1
        rts

| fill_rand: a0 = words, d6 = n-1. Random int8 values sign-extended to words.
fill_rand:
        jsr     rand
        ext.w   %d0
        move.w  %d0,(%a0)+
        dbf     %d6,fill_rand
        rts

| fill_vcodes: a0 = bytes, d6 = n-1. Pre-doubled 4-bit codes (0..30), pattern.
fill_vcodes:
        moveq   #0,%d0
1:      addq.b  #5,%d0
        and.b   #15,%d0
        move.b  %d0,%d1
        add.b   %d1,%d1
        move.b  %d1,(%a0)+
        dbf     %d6,1b
        rts
fill_vcodes_rand:
        jsr     rand
        and.w   #15,%d0
        add.w   %d0,%d0
        move.b  %d0,(%a0)+
        dbf     %d6,fill_vcodes_rand
        rts

| fill_pairs: a0 = words, d6 = rows-1, d5 = pairs per row. code = p*512 + c*2 - 32768.
fill_pairs:
        moveq   #0,%d2                  | c
1:      move.w  %d5,%d4
        subq.w  #1,%d4
        move.w  #-32768,%d3             | p*512 - 32768
2:      add.b   #101,%d2
        moveq   #0,%d0
        move.b  %d2,%d0
        add.w   %d0,%d0
        add.w   %d3,%d0
        move.w  %d0,(%a0)+
        add.w   #512,%d3
        dbf     %d4,2b
        dbf     %d6,1b
        rts
fill_pairs_rand:
1:      move.w  %d5,%d4
        subq.w  #1,%d4
        move.w  #-32768,%d3
2:      jsr     rand
        and.w   #255,%d0
        add.w   %d0,%d0
        add.w   %d3,%d0
        move.w  %d0,(%a0)+
        add.w   #512,%d3
        dbf     %d4,2b
        dbf     %d6,1b
        rts

| init_expt: EXPT[i] = round-ish 255*exp(-i/16), 8.8 fixed point iteration
init_expt:
        movea.l -4(%a5),%a0
        adda.l  #{layout['EXPT'][0]},%a0
        move.w  #65280,%d1              | 255.0 in 8.8
        move.w  #255,%d6
1:      move.w  %d1,%d0
        lsr.w   #8,%d0
        move.w  %d0,(%a0)+
        mulu.w  #61566,%d1              | * exp(-1/16) in 0.16
        swap    %d1
        dbf     %d6,1b
        rts
""")

# fill routines for ternary storage
for (k, kind) in sorted(set(VARIANTS.values())):
    n = 3 ** k
    if kind == "W":
        emit(f"""| fill_W{k}: a0 = codes, d6 = rows-1, d5 = G. idx pattern +37 mod {n}; code=(idx*G+g)*2-32768
fill_W{k}:
        moveq   #0,%d2                  | idx
        moveq   #0,%d3                  | idx*G
1:      move.w  %d5,%d4
        subq.w  #1,%d4
        moveq   #0,%d1                  | g
2:      move.w  %d3,%d0
        add.w   %d1,%d0
        add.w   %d0,%d0
        sub.w   #32768,%d0
        move.w  %d0,(%a0)+
        addq.w  #1,%d1
        add.w   #37,%d2
        move.w  %d5,%d0
        mulu.w  #37,%d0
        add.w   %d0,%d3
        cmp.w   #{n},%d2
        bcs.s   3f
        sub.w   #{n},%d2
        move.w  %d5,%d0
        mulu.w  #{n},%d0
        sub.w   %d0,%d3
3:      dbf     %d4,2b
        dbf     %d6,1b
        rts
fill_W{k}_rand:
1:      move.w  %d5,%d4
        subq.w  #1,%d4
        moveq   #0,%d1
2:      jsr     rand
        and.l   #0xFFFF,%d0
        mulu.w  #{n},%d0
        swap    %d0                     | idx in 0..{n - 1}
        mulu.w  %d5,%d0
        add.w   %d1,%d0
        add.w   %d0,%d0
        sub.w   #32768,%d0
        move.w  %d0,(%a0)+
        addq.w  #1,%d1
        dbf     %d4,2b
        dbf     %d6,1b
        rts""")
    else:
        scale = "add.b   %d0,%d0" if k == 4 else ""
        emit(f"""| fill_B{k}: a0 = byte codes, d6 = rows-1, d5 = G
fill_B{k}:
        moveq   #0,%d2
1:      move.w  %d5,%d4
        subq.w  #1,%d4
2:      add.w   #37,%d2
        cmp.w   #{n},%d2
        bcs.s   3f
        sub.w   #{n},%d2
3:      move.w  %d2,%d0
        {scale}
        move.b  %d0,(%a0)+
        dbf     %d4,2b
        dbf     %d6,1b
        rts
fill_B{k}_rand:
1:      move.w  %d5,%d4
        subq.w  #1,%d4
2:      jsr     rand
        and.l   #0xFFFF,%d0
        mulu.w  #{n},%d0
        swap    %d0
        {scale}
        move.b  %d0,(%a0)+
        dbf     %d4,2b
        dbf     %d6,1b
        rts""")


def digits(i, k):
    return [(i // 3 ** j) % 3 for j in range(k)]


# group-table builders: a0 -> k activation words, a3 -> table for this group.
# interleaved: d7 = entry stride (G*2); contiguous: entries consecutive.
for k in (4, 5):
    for lay in ("i", "c"):
        emit(f"""| bld_{k}{lay}: entry idx = sum (d_j)*3^j, value = sum (d_j - 1) * x_j
bld_{k}{lay}:
        movem.w (%a0),%d1-%d{k}
        move.w  %d1,%d6                 | S = x0""")
        for j in range(1, k):
            emit(f"""        move.w  %d{j + 1},%d0
        sub.w   %d6,%d{j + 1}
        sub.w   %d6,%d{j + 1}                 | c{j} = x{j} - 2*(x0..x{j - 1})
        add.w   %d0,%d6""")
        emit("        move.w  %d6,%d0\n        neg.w   %d0                     | value at idx 0")
        n = 3 ** k
        for idx in range(n):
            if lay == "i":
                emit("        move.w  %d0,(%a3)\n        adda.w  %d7,%a3")
            else:
                emit("        move.w  %d0,(%a3)+")
            if idx < n - 1:
                dg = digits(idx, k)
                j = next(j for j in range(k) if dg[j] < 2)
                emit(f"        add.w   %d{1 if j == 0 else j + 1},%d0")
        emit("        rts")

# vector table builders per variant: a0 = x, a4 = x end, a1 = table, d7 = stride (W)
for v, (k, kind) in VARIANTS.items():
    lay, adv = ("i", 2) if kind == "W" else ("c", 2 * 3 ** k)
    emit(f"""bv_{v}:  movea.l %a1,%a3
        jsr     bld_{k}{lay}
        lea     {2 * k}(%a0),%a0
        lea     {adv}(%a1),%a1
        cmpa.l  %a4,%a0
        bcs.s   bv_{v}
        rts""")

# matrix-vector kernels (computed entry into an unrolled block)
MAXG = 128
emit("""| mv_W: a1 = codes, a2 = table+32768, a4 = entry, a6 = out, d6 = rows-1
mv_W:   moveq   #0,%d1
        jsr     (%a4)
        move.w  %d1,(%a6)+
        dbf     %d6,mv_W
        rts""")
emit("mvW_blk:")
for _ in range(MAXG):
    emit("        move.w  (%a1)+,%d0\n        add.w   0(%a2,%d0.w),%d1")
emit("mvW_end: rts")
emit("""mv_B4:  moveq   #0,%d0
1:      moveq   #0,%d1
        movea.l %a3,%a2
        jsr     (%a4)
        move.w  %d1,(%a6)+
        dbf     %d6,1b
        rts""")
emit("mvB4_blk:")
for _ in range(MAXG):
    emit("        move.b  (%a1)+,%d0\n        add.w   0(%a2,%d0.w),%d1\n        lea     162(%a2),%a2")
emit("mvB4_end: rts")
emit("""mv_B5:  moveq   #0,%d1
        movea.l %a3,%a2
        jsr     (%a4)
        move.w  %d1,(%a6)+
        dbf     %d6,mv_B5
        rts""")
emit("mvB5_blk:")
for _ in range(groups(FF, 5)):
    emit("        moveq   #0,%d0\n        move.b  (%a1)+,%d0\n        add.w   %d0,%d0\n"
         "        add.w   0(%a2,%d0.w),%d1\n        lea     486(%a2),%a2")
emit("mvB5_end: rts")

# pair tables (4-bit weights/keys): a0 -> (h1,h2), a3 -> 256-entry table
emit("""| bld_pair: entry c=(w1+8)*16+(w2+8) = w1*h1 + w2*h2
bld_pair:
        move.w  (%a0),%d4
        move.w  2(%a0),%d2
        move.w  %d4,%d0
        add.w   %d2,%d0
        lsl.w   #3,%d0
        neg.w   %d0
        move.w  %d2,%d3
        lsl.w   #4,%d3
        sub.w   %d2,%d3
        sub.w   %d3,%d4                 | h1 - 15*h2""")
for row in range(16):
    for col in range(16):
        emit("        move.w  %d0,(%a3)+")
        if col < 15:
            emit("        add.w   %d2,%d0")
        elif row < 15:
            emit("        add.w   %d4,%d0")
emit("""        rts
| bpairs: a0 = activations, a3 = tables, d6 = pairs-1
bpairs: jsr     bld_pair
        addq.l  #4,%a0
        dbf     %d6,bpairs
        rts""")

# softmax: a0 = scores, d6 = ctx-1, a3 = ptab out (16 words per position), a2 = EXPT
emit("""softmax:
        movea.l %a0,%a1
        move.w  %d6,%d5
        move.w  #-32768,%d1
1:      move.w  (%a1)+,%d0
        cmp.w   %d1,%d0
        ble.s   2f
        move.w  %d0,%d1
2:      dbf     %d5,1b
3:      move.w  %d1,%d0
        sub.w   (%a0)+,%d0
        lsr.w   #2,%d0
        cmp.w   #255,%d0
        bls.s   4f
        move.w  #255,%d0
4:      add.w   %d0,%d0
        move.w  0(%a2,%d0.w),%d2        | p
        move.w  %d2,%d3
        lsl.w   #3,%d3
        neg.w   %d3                     | -8p""")
for i in range(16):
    emit("        move.w  %d3,(%a3)+")
    if i < 15:
        emit("        add.w   %d2,%d3")
emit("""        dbf     %d6,3b
        rts""")

# weighted sum: a3 = V codes (ctx x 40 bytes), a4 = ptab (ctx x 32 bytes), a6 = out, -12(a5) = ctx-1
emit("wsum:   moveq   #0,%d0")
off = 0
for blk in (6, 6, 6, 6, 6, 6, 4):
    emit(f"        lea     {off}(%a3),%a1\n        movea.l %a4,%a2")
    for r in range(1, blk + 1):
        emit(f"        moveq   #0,%d{r}")
    emit("        move.w  -12(%a5),%d7")
    lbl = f"ws{off}"
    emit(f"{lbl}:")
    for r in range(1, blk + 1):
        emit(f"        move.b  (%a1)+,%d0\n        add.w   0(%a2,%d0.w),%d{r}")
    emit(f"        lea     {HD - blk}(%a1),%a1\n        lea     32(%a2),%a2\n        dbf     %d7,{lbl}")
    for r in range(1, blk + 1):
        emit(f"        move.w  %d{r},(%a6)+")
    off += blk
emit("        rts")

# elementwise (norms, quantization, SwiGLU): a0 = words, d6 = n-1
emit("""ew:     move.w  #83,%d0
        muls.w  (%a0),%d0
        asr.l   #8,%d0
        move.w  %d0,(%a0)+
        dbf     %d6,ew
        rts
argmax: move.w  #-32768,%d1
1:      move.w  (%a0)+,%d0
        cmp.w   %d1,%d0
        ble.s   2f
        move.w  %d0,%d1
        move.w  %d6,%d2
2:      dbf     %d6,1b
        rts""")

# ---- per-token parts
BPG = {"W": 6, "B4": 10, "B5": 14}
for v, (k, kind) in VARIANTS.items():
    mv = "W" if kind == "W" else v
    g160, g512 = groups(D, k), groups(FF, k)
    emit(f"tern_{v}:\n        move.w  #{L},-16(%a5)\n{v}_lay:")
    for src, n_in, g, mat, rows, dst in (("X160", D, g160, "QKV", QKV, "QKV"),
                                         ("ATTO", D, g160, "WO", D, "T160"),
                                         ("X160", D, g160, "GU", GU, "GUO"),
                                         ("H512", FF, g512, "DN", D, "T160")):
        ptr("%a0", src)
        ptr("%a4", src, 2 * g * k)
        ptr("%a1", "LUT")
        emit(f"        move.w  #{g * 2},%d7\n        jsr     bv_{v}")
        ptr("%a1", f"{v}_{mat}")
        ptr("%a2", "LUT", 32768 if kind == "W" else 0)
        ptr("%a3", "LUT")
        ptr("%a6", dst)
        emit(f"        lea     mv{mv}_end(%pc),%a4\n        suba.w  #{g * BPG['W' if kind == 'W' else v]},%a4")
        emit(f"        move.w  #{rows - 1},%d6\n        jsr     mv_{mv}")
    emit(f"        subq.w  #1,-16(%a5)\n        bne     {v}_lay\n        rts")

for c in CTXS:
    emit(f"attn_{c}:\n        move.w  #{L},-16(%a5)\nattn{c}_lay:")
    for h in range(H):
        kv = h // (H // KVH)
        ptr("%a0", "QKV", h * HD * 2)
        ptr("%a3", "ATTT")
        emit(f"        move.w  #{ATT_PAIRS - 1},%d6\n        jsr     bpairs")
        ptr("%a1", "KC", kv * CTX_MAX * ATT_PAIRS * 2)
        ptr("%a2", "ATTT", 32768)
        ptr("%a6", "SC")
        emit(f"        lea     mvW_end(%pc),%a4\n        suba.w  #{ATT_PAIRS * 6},%a4")
        emit(f"        move.w  #{c - 1},%d6\n        jsr     mv_W")
        ptr("%a0", "SC")
        ptr("%a3", "PTAB")
        ptr("%a2", "EXPT")
        emit(f"        move.w  #{c - 1},%d6\n        jsr     softmax")
        ptr("%a3", "VC", kv * CTX_MAX * HD)
        ptr("%a4", "PTAB")
        ptr("%a6", "ATTO", h * HD * 2)
        emit(f"        move.w  #{c - 1},-12(%a5)\n        jsr     wsum")
    emit(f"        subq.w  #1,-16(%a5)\n        bne     attn{c}_lay\n        rts")

emit("tok_head:")
ptr("%a0", "X160")
ptr("%a3", "HEADT")
emit(f"        move.w  #{HEAD_PAIRS - 1},%d6\n        jsr     bpairs")
ptr("%a1", "HEADW")
ptr("%a2", "HEADT", 32768)
ptr("%a6", "LOGITS")
emit(f"        lea     mvW_end(%pc),%a4\n        suba.w  #{HEAD_PAIRS * 6},%a4")
emit(f"        move.w  #{VOCAB - 1},%d6\n        jsr     mv_W")
ptr("%a0", "LOGITS")
emit(f"        move.w  #{VOCAB - 1},%d6\n        jsr     argmax\n        rts")

# misc per token: per layer 2*160 (attn norm) + 160 (attn out) + 2*160 (ffn norm + residual)
# + 512 (SwiGLU) + 512 (quantize hidden) = 1824; final norm 320
MISC = L * 1824 + 320
emit("tok_misc:")
left = MISC
while left > 0:
    n = min(left, VOCAB)
    ptr("%a0", "LOGITS")
    emit(f"        move.w  #{n - 1},%d6\n        jsr     ew")
    left -= n
emit("        rts")
emit("""tok_full:
        jsr     tern_W4
        jsr     attn_64
        jsr     tok_head
        jsr     tok_misc
        rts""")

