#!/usr/bin/env python3
"""Guess My Doodle's sound effects, synthesised from scratch (no samples, nothing copied).

    gen_sounds.py OUT_DIR [--wav]

Writes OUT_DIR/sounds.c: 8-bit unsigned (offset binary, 128 = silence) samples at 11,127 Hz (half the Mac Plus's 22,255 Hz sound
rate; app/sound.c plays each sample twice) and a table of (offset, length). --wav also writes one
WAV per sound for listening. Plain Python, deterministic. Same format as broadside/tools/gen_sounds.py.
"""
import math
import os
import sys
import wave

RATE = 11127
NAMES = ["tick", "chime", "fail", "blip", "start", "fanfare"]


def tone(freq, dur, amp=1.0, decay=0.15, attack=0.004, square=0.3):
    out = []
    for i in range(int(dur * RATE)):
        t = i / RATE
        env = min(1.0, t / attack) * math.exp(-t / decay)
        ph = (freq * t) % 1.0
        sine = math.sin(2 * math.pi * ph)
        sq = 1.0 if ph < 0.5 else -1.0
        out.append(amp * env * ((1 - square) * sine + square * sq))
    return out


def seq(parts, gap=0.0):
    out = []
    for p in parts:
        out += p + [0.0] * int(gap * RATE)
    return out


def mix(a, b, offset=0):
    n = max(len(a), offset + len(b))
    out = [0.0] * n
    for i, v in enumerate(a):
        out[i] += v
    for i, v in enumerate(b):
        out[offset + i] += v
    return out


def tick():                       # a dry wooden click for the last five seconds
    return tone(1800, 0.035, decay=0.008, square=0.6)


def chime():                      # two bell notes, the second one ringing out: "I know!"
    a = tone(784, 0.5, decay=0.18, square=0.1) + [0.0] * 200
    b = tone(1175, 0.9, decay=0.35, square=0.1)
    c = tone(1568, 0.9, amp=0.4, decay=0.3, square=0.0)
    return mix(a, mix(b, c), int(0.13 * RATE))


def fail():                       # a falling "aww"
    out = []
    n = int(0.55 * RATE)
    for i in range(n):
        t = i / RATE
        f = 330 * (1 - 0.45 * t / 0.55)
        env = min(1, t / 0.01) * (1 - t / 0.55)
        out.append(env * (0.6 * math.sin(2 * math.pi * f * t) + 0.4 * (1 if (f * t) % 1 < 0.5 else -1)))
    return out


def blip():                       # the guess changed: a soft little blip
    return tone(988, 0.06, amp=0.7, decay=0.03, square=0.2)


def start():                      # a rising "ready, go"
    return seq([tone(523, 0.09, decay=0.06), tone(659, 0.09, decay=0.06), tone(784, 0.16, decay=0.1)], 0.01)


def fanfare():                    # end of the game
    notes = [(523, 0.12), (659, 0.12), (784, 0.12), (1047, 0.45)]
    return seq([tone(f, d + 0.05, decay=d * 0.9, square=0.35) for f, d in notes], 0.0)


def to_s8(xs, peak):
    m = max(1e-9, max(abs(v) for v in xs))
    return [max(-127, min(127, int(round(v / m * peak)))) for v in xs]


def main():
    out_dir = sys.argv[1]
    os.makedirs(out_dir, exist_ok=True)
    funcs = [tick, chime, fail, blip, start, fanfare]
    peaks = [70, 70, 60, 45, 55, 65]
    data, table = [], []
    for f, pk in zip(funcs, peaks):
        s = to_s8(f(), pk)
        if len(s) & 1:
            s.append(0)
        table.append((len(data), len(s)))
        data += s
        if "--wav" in sys.argv:
            w = wave.open(os.path.join(out_dir, f.__name__ + ".wav"), "wb")
            w.setnchannels(1)
            w.setsampwidth(1)
            w.setframerate(RATE)
            w.writeframes(bytes((v + 128) & 255 for v in s))
            w.close()
    with open(os.path.join(out_dir, "sounds.c"), "w") as fo:
        fo.write("/* Generated by guess/tools/gen_sounds.py: synthesised sound effects, 8-bit offset binary, %d Hz. */\n" % RATE)
        fo.write("#include \"sound.h\"\n")
        fo.write("const unsigned char snd_data[%d] = {\n" % len(data))
        for i in range(0, len(data), 24):
            fo.write("    " + ",".join(str((v + 128) & 255) for v in data[i:i + 24]) + ",\n")
        fo.write("};\n")
        fo.write("const unsigned long snd_table[%d][2] = {\n" % len(table))
        for (o, n), name in zip(table, NAMES):
            fo.write("    {%d, %d},   /* %s */\n" % (o, n, name))
        fo.write("};\n")
    print("%d sounds, %d bytes (%.2f s)" % (len(table), len(data), len(data) / RATE))


if __name__ == "__main__":
    main()
