#!/usr/bin/env python3
"""Generate Endurance's game data: sprites (sprites.s/.h) and stage data (gamedata.s/.h).

    gen_assets.py OUTDIR [--w 384 --h 240 --hy 80] [--preview DIR]
"""
import argparse
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "engine"))
sys.path.insert(0, HERE)
import road  # noqa: E402
import sprites  # noqa: E402
from art import cars, stages, scenery  # noqa: E402

PLAYER_W, PLAYER_H = 56, 28
KP_BACK = 6                     # player car base row = KB - KP_BACK
RIVAL_W = [56, 50, 44, 39, 34, 30, 26, 22, 19, 16, 13, 11, 9, 7, 5, 3]
MTN_H = 30

FONT = {
    "E": ["#####", "#....", "#....", "####.", "#....", "#....", "#####"],
    "N": ["#...#", "##..#", "#.#.#", "#..##", "#...#", "#...#", "#...#"],
    "D": ["####.", "#...#", "#...#", "#...#", "#...#", "#...#", "####."],
    "U": ["#...#", "#...#", "#...#", "#...#", "#...#", "#...#", ".###."],
    "R": ["####.", "#...#", "#...#", "####.", "#.#..", "#..#.", "#...#"],
    "A": [".###.", "#...#", "#...#", "#####", "#...#", "#...#", "#...#"],
    "C": [".####", "#....", "#....", "#....", "#....", "#....", ".####"],
}


def logo(text="ENDURANCE", sc=5, gap=2, shear=4):
    h = 7 * sc
    w = len(text) * (5 * sc + gap * sc) + h // shear + 8
    ink = np.zeros((h + 8, w), np.uint8)
    x = 4
    for ch in text:
        g = FONT[ch]
        for gy in range(7):
            for gx in range(5):
                if g[gy][gx] == "#":
                    for yy in range(sc):
                        y = gy * sc + yy
                        off = (h - y) // shear
                        ink[4 + y, x + off + gx * sc:x + off + gx * sc + sc] = 1
        x += 5 * sc + gap * sc
    # speed lines through the letters' middle rows (white gaps)
    for y in (4 + h // 2 - sc // 2, 4 + h // 2 + sc // 2 + 1):
        ink[y, :] = 0
    opaque = ink.copy()
    for _ in range(2):   # 2-pixel white outline
        p = np.pad(opaque, 1)
        opaque = p[1:-1, 1:-1] | p[:-2, 1:-1] | p[2:, 1:-1] | p[1:-1, :-2] | p[1:-1, 2:]
    cols = np.where(opaque.any(0))[0]
    return opaque[:, cols[0]:cols[-1] + 1], ink[:, cols[0]:cols[-1] + 1]


def longs_lines(vals, per=8):
    return ["        .long   " + ",".join("0x%08X" % (v & 0xFFFFFFFF) for v in vals[i:i + per])
            for i in range(0, len(vals), per)]


def bytes_lines(b, per=32):
    return ["        .byte   " + ",".join(str(x) for x in b[i:i + per]) for i in range(0, len(b), per)]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("out")
    ap.add_argument("--w", type=int, default=384)
    ap.add_argument("--h", type=int, default=224)
    ap.add_argument("--hy", type=int, default=75)
    ap.add_argument("--preview")
    a = ap.parse_args()
    cfg = road.RoadConfig(W=a.w, H=a.h, HY=a.hy)
    KB = cfg.KB
    KP = KB - KP_BACK
    os.makedirs(a.out, exist_ok=True)

    # ---------------- sprites
    bank = sprites.SpriteBank()
    for f in ("straight", "left", "right", "crash"):
        o, b = sprites.scale(cars.player(f), PLAYER_W, PLAYER_H)
        bank.add("p_" + f, o, b, 16)
    for kind in ("black", "grey", "white"):
        for w in RIVAL_W:
            o, b = sprites.scale(cars.rival(kind), w, max(2, w // 2), outline=w >= 9)
            bank.add(f"{kind}_{w}", o, b, 8)
    for w in RIVAL_W:
        o, b = sprites.scale(cars.taillights(), w, max(2, w // 2), outline=False)
        bank.add(f"tail_{w}", o, b, 8)
    lo, li = logo()
    bank.add("logo", lo, li, 1)
    bank.emit(os.path.join(a.out, "sprites.s"), os.path.join(a.out, "sprites.h"))
    if a.preview:
        bank.sheet(os.path.join(a.preview, "sprites.png"), ["p_straight", "p_left", "p_crash", "black_56",
                   "grey_34", "white_22", "tail_39", "logo"])

    # rival size index per road row: car width at row k = PLAYER_W * k / KP
    size_idx = []
    for k in range(KB + 1):
        cw = PLAYER_W * k / KP
        if cw < 2.5:
            size_idx.append(-1)
        else:
            size_idx.append(int(np.argmin([abs(w - cw) for w in RIVAL_W])))

    # ---------------- stage data
    mtn = scenery.mountains(512, MTN_H)
    s_lines = ["| Generated by gen_assets.py: stage data", "        .text", "        .even",
               "        .globl  stage_pats", "        .globl  fog_pats", "        .globl  sky_pats",
               "        .globl  mtn_strips", "stage_pats:"]
    for name in stages.ORDER:
        P = stages.pattern_sets(stages.STAGES[name])
        s_lines += longs_lines([P[ph][par][s] for ph in (0, 1) for par in (0, 1) for s in range(4)])
    s_lines.append("fog_pats:")
    fog = stages.STAGES["fog"]["fog"]
    s_lines += longs_lines([stages.rep(fog[par]) for par in (0, 1) for _ in range(4)])
    s_lines.append("sky_pats:")
    for name in stages.ORDER:
        sk = stages.STAGES[name]["sky"]
        s_lines += longs_lines([stages.rep(sk[0]), stages.rep(sk[1])])
    s_lines.append("mtn_strips:")
    for name in stages.ORDER:
        S = stages.STAGES[name]
        strip = scenery.mountain_strip(S, mtn)
        if S.get("fog_k"):
            strip = scenery.pat_plane(MTN_H, 512, S["fog"])
        s_lines += bytes_lines(np.packbits(strip, axis=1).tobytes())
    open(os.path.join(a.out, "gamedata.s"), "w").write("\n".join(s_lines) + "\n")

    flags = []
    for name in stages.ORDER:
        S = stages.STAGES[name]
        flags.append("{%d, %d, %d}" % (int(S.get("grip", 1.0) * 256), 1 if S.get("night") else 0,
                                       S.get("fog_k", 0)))
    h = f"""/* Generated by gen_assets.py */
#ifndef GAMEDATA_H
#define GAMEDATA_H
#define NSTAGES 6
#define MTN_H {MTN_H}
#define KP {KP}
#define NRIVAL_SIZES {len(RIVAL_W)}
#define SPR_RIVAL0 SPR_BLACK_56
#define SPR_TAIL0 SPR_TAIL_56
extern const unsigned long stage_pats[NSTAGES][16];
extern const unsigned long fog_pats[8];
extern const unsigned long sky_pats[NSTAGES][2];
extern const unsigned char mtn_strips[NSTAGES][MTN_H * 64];
typedef struct {{ short grip; short night; short fog_k; }} StageInfo;
static const StageInfo stage_info[NSTAGES] = {{{", ".join(flags)}}};
static const signed char rival_size[{KB + 1}] = {{{",".join(map(str, size_idx))}}};
static const char *const stage_name[NSTAGES] = {{{", ".join('"' + n.upper() + '"' for n in stages.ORDER)}}};
#endif
"""
    open(os.path.join(a.out, "gamedata.h"), "w").write(h)
    print(f"sprites {len(bank.data)} bytes ({len(bank.info)} entries), KP={KP}")


if __name__ == "__main__":
    main()
