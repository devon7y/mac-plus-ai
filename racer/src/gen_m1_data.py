#!/usr/bin/env python3
"""Data for the M1 benchmark: sky rows, morning pattern sets, test track. -> OUT/m1_data.s"""
import argparse
import os
import sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import m1common as M  # noqa: E402


def longs(b):
    out = []
    for i in range(0, len(b), 24):
        chunk = b[i:i + 24]
        out.append("        .long   " + ",".join("0x" + chunk[j:j + 4].hex() for j in range(0, len(chunk), 4)))
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("out")
    ap.add_argument("--w", type=int, default=384)
    ap.add_argument("--h", type=int, default=240)
    ap.add_argument("--hy", type=int, default=80)
    a = ap.parse_args()
    cfg = M.road.RoadConfig(W=a.w, H=a.h, HY=a.hy)
    sky = M.bits_to_bytes(M.sky_rows(cfg))
    pats = M.stages.pattern_sets(M.stages.STAGES[M.STAGE])
    plong = [pats[ph][par][s] for ph in (0, 1) for par in (0, 1) for s in range(4)]
    s = ["| Generated by gen_m1_data.py", "        .even", "m1_sky:", longs(sky), "m1_pats:",
         "        .long   " + ",".join("0x%08X" % v for v in plong), "m1_track:"]
    for ln, ddx in M.TRACK:
        s.append("        .long   %d,%d" % (ln, ddx))
    s.append("m1_track_end:")
    tabs = M.road.build_tables(cfg)
    s.append("m1_pieces:")
    for ph in (0, 1):
        for par in (0, 1):
            L, R, Mt = M.road.piece_tables(tabs, pats[ph][par])
            s.append(longs(L + R + Mt))
    s.append(f"        .equ    M1_LSZ,{len(L)}")
    s.append(f"        .equ    M1_MSZ,{len(Mt)}")
    open(os.path.join(a.out, "m1_data.s"), "w").write("\n".join(s) + "\n")


if __name__ == "__main__":
    main()
