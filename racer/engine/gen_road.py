#!/usr/bin/env python3
"""Generate the 68000 road renderer (GNU as, MIT syntax) for one playfield configuration.

    gen_road.py OUTDIR [--w 384 --h 240 --hy 80]

Writes OUTDIR/road_cfg.inc (constants), OUTDIR/road_kernel.s (code) and OUTDIR/road_data.s
(tables). The game `.include`s all three. See engine/README.md for the API.
"""
import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import road  # noqa: E402

# RoadState field offsets (the caller's parameter block, pointed to by a0)
RS = dict(rs_camz=0, rs_camx=4, rs_segp=8, rs_segend=12, rs_ring=16, rs_ringend=20,
          rs_pats=24, rs_rows=28, rs_size=32)


def words(vals, per=12):
    out = []
    for i in range(0, len(vals), per):
        out.append("        .short  " + ",".join(str(int(v)) for v in vals[i:i + per]))
    return "\n".join(out)


def longs(vals, per=6):
    out = []
    for i in range(0, len(vals), per):
        out.append("        .long   " + ",".join("0x%08X" % (int(v) & 0xFFFFFFFF) for v in vals[i:i + per]))
    return "\n".join(out)


def gen_cfg(cfg, tabs):
    NL = cfg.W // 32
    c = dict(PF_W=cfg.W, PF_H=cfg.H, PF_HY=cfg.HY, PF_KB=cfg.KB, PF_NL=NL, PF_RB=NL * 4,
             PF_MG=cfg.MG, PF_NLV=NL + 2 * cfg.MG, PF_RBV=(NL + 2 * cfg.MG) * 4,
             PF_RECIP=cfg.RECIP, PF_CXL=cfg.CXL, PF_SS=cfg.STRIPE_SHIFT, PF_ZNEAR=cfg.ZNEAR,
             PF_KSTRIPE=cfg.KSTRIPE, PF_SETSZ=road.SETSZ, PF_OFSZ=24,
             PF_RWMAX=int(max(tabs['rw'])), PF_MWMAX=int(max(tabs['mw'])))
    c.update(RS)
    return "| Generated by gen_road.py: playfield constants\n" + "\n".join(
        f"        .equ    {k},{v}" for k, v in c.items()) + "\n"


def gen_data(cfg, tabs):
    KB, W = cfg.KB, cfg.W
    NL = W // 32
    offs = []
    for k in range(KB + 1):
        offs += [4 * int(v) for v in tabs["marked"][k]] + [256 * int(tabs["rw"][k]), 256 * int(tabs["mw"][k]), 0, 0]
    dec_n = 1600 + cfg.MAXOFF          # no clamping in pass 1: covers |cx - W/2| < ~1700 px
    dec = []
    MGP = 32 * cfg.MG
    NLV = NL + 2 * cfg.MG
    for b in range(-dec_n, W + dec_n + 1):
        v = b + MGP                      # position in the virtual row (margins included)
        if v < 0:
            dec.append(0)
        elif v >= NLV * 32:
            dec.append((NLV * 4) << 16)
        else:
            dec.append((((v >> 5) * 4) << 16) | ((v & 31) * 8))
    rmask = [x for i in range(32) for x in ((0xFFFFFFFF >> i), 0)]   # 8 bytes apart
    zrow = [int(z) for z in tabs["zrow"]]
    return f"""| Generated by gen_road.py: road tables ({W}x{cfg.H}, horizon {cfg.HY})
        .even
| zrow[k], k = 0..KB: world depth of road row k (unsigned)
rt_zrow:
{words(zrow)}
| per row (24 bytes): offsets from the road centre x4: -(hw+rw), -hw, m1a, m1b, m2a, m2b, hw, hw+rw;
| then rw*256, mw*256 (piece table offsets), 0, 0
rt_offs:
{words(offs, 12)}
| rmask[i] = $FFFFFFFF >> i, at byte offset 8*i (indexed by the decoded bit * 8)
rt_rmask:
{longs(rmask)}
| dec[b] for b in [-{dec_n}, {W + dec_n}]: high word = byte offset of b's long in the buffer row
| (rows have MG invisible longs on each side; clamped to 0..NLV*4), low word = 4 * bit (0 when
| clamped). rt_dec0 is b = 0.
rt_dec:
{longs(dec[:dec_n])}
rt_dec0:
{longs(dec[dec_n:])}
"""


BOUND = """| --- boundary: offset {off}(a4), next span pattern {q}(a3)
        move.w  %d4,%d0
        add.w   {off}(%a4),%d0
        move.l  0(%a6,%d0.w),%d0
        move.l  0(%a2,%d0.w),%d2
        swap    %d0
        sub.w   %d7,%d0
        bne.s   1f
        move.l  {q}(%a3),%d5
        move.l  %d5,%d3
        eor.l   %d6,%d3
        and.l   %d2,%d3
        eor.l   %d3,%d6
        bra.s   3f
1:      add.w   %d0,%d7
        move.l  %d6,(%a0)+
        subq.w  #4,%d0
        beq.s   2f
        lsr.w   #1,%d0
        neg.w   %d0
        jmp     2f(%pc,%d0.w)
{fills}
2:      move.l  {q}(%a3),%d3
        move.l  %d3,%d6
        eor.l   %d5,%d6
        and.l   %d2,%d6
        eor.l   %d5,%d6
        move.l  %d3,%d5
3:
"""

FLUSH = """| --- flush: write the current long, fill the rest of the row
        move.w  #PF_NLV*4,%d0
        sub.w   %d7,%d0
        beq.s   2f
        move.l  %d6,(%a0)+
        subq.w  #4,%d0
        beq.s   2f
        lsr.w   #1,%d0
        neg.w   %d0
        jmp     2f(%pc,%d0.w)
{fills}
2:
"""


def gen_kernel(cfg, tabs):
    KB, NL = cfg.KB, cfg.W // 32
    NLV = NL + 2 * cfg.MG
    fills = "\n".join(["        move.l  %d5,(%a0)+"] * (NLV - 1))
    o = []
    emit = o.append
    emit("""| Generated by gen_road.py: road renderer kernel. See engine/README.md.
        .even
| ------------------------------------------------------------------------------------------
| road_geom: pass 1. a0 = RoadState. Walks rows k = KB..1 (bottom up), accumulating the
| curve, and writes ROWS[k] = {pattern set ptr.l, cx*4.w, marked.w} at rs_rows + 8k.
| Preserves all registers except d0-d1/a0-a1.
road_geom:
        movem.l %d2-%d7/%a2-%a6,-(%sp)
        move.l  rs_ringend(%a0),-(%sp)  | ring end at 4(sp), ring start at 0(sp)
        move.l  rs_ring(%a0),-(%sp)
        move.l  rs_camz(%a0),%d6
        move.l  rs_segend(%a0),%d5
        sub.l   %d6,%d5                 | d5 = segment end relative to the camera
        movea.l rs_segp(%a0),%a2
        move.l  4(%a2),%d4              | ddx
        movea.l rs_rows(%a0),%a3
        move.w  #-1,8*(PF_KB+1)+6(%a3)  | sentinel record after row KB (rows buffer: 8*(KB+2) bytes)
        adda.w  #8*(PF_KB+1),%a3        | records are written downwards with -(a3)
        movea.l rs_pats(%a0),%a5        | pattern sets: a5 ph0/even, a6 ph0/odd, a0 ph1/even, d7 ph1/odd
        lea     PF_SETSZ(%a5),%a6
        lea     3*PF_SETSZ(%a5),%a4
        move.l  %a4,%d7
        move.w  rs_camx(%a0),%d0
        lea     2*PF_SETSZ(%a5),%a0
        move.w  %d0,%d2
        swap    %d2
        clr.w   %d2
        neg.l   %d2                     | x = -camx << 16
        muls    #PF_RECIP,%d0
        move.l  %d0,%d3                 | dx = camx * RECIP
        lea     rt_zrow+2*(PF_KB+1)(%pc),%a1""")
    for k in range(KB, 0, -1):
        y = cfg.HY + k
        par = y & 1
        stripes = bool(tabs["stripes"][k])
        mark = bool(tabs["has_mark"][k])
        emit(f"| row k={k} y={y}")
        emit("""        moveq   #0,%d0
        move.w  -(%a1),%d0
        cmp.l   %d5,%d0
        bcs.s   1f
        bsr     rg_adv
1:""")
        if k != KB:
            emit("        add.l   %d4,%d3\n        add.l   %d3,%d2")
        emit("""        move.l  %d2,%d1
        swap    %d1
        add.w   #PF_W/2,%d1
        add.w   %d1,%d1
        add.w   %d1,%d1""")
        r0, r1 = ("%a5", "%a0") if par == 0 else ("%a6", "%d7")
        if stripes:
            emit(f"""        add.w   %d6,%d0
        btst    #PF_SS,%d0
        bne.s   1f
        clr.w   -(%a3)
        move.w  %d1,-(%a3)
        move.l  {r0},-(%a3)
        bra.s   2f
1:      move.w  #{1 if mark else 0},-(%a3)
        move.w  %d1,-(%a3)
        move.l  {r1},-(%a3)
2:""")
        else:
            emit(f"""        clr.w   -(%a3)
        move.w  %d1,-(%a3)
        move.l  {r0},-(%a3)""")
    emit("""        addq.l  #8,%sp
        movem.l (%sp)+,%d2-%d7/%a2-%a6
        rts
| advance to the next segment until zrow (d0) < relative end (d5)
rg_adv: addq.l  #8,%a2
        cmpa.l  8(%sp),%a2
        bcs.s   1f
        movea.l 4(%sp),%a2
1:      move.l  4(%a2),%d4
        add.l   (%a2),%d5
        cmp.l   %d5,%d0
        bcc.s   rg_adv
        rts
""")
    def FILL(cnt, preg):
        """write cnt/4 longs of preg (cnt = a data register holding count*4, may be 0)"""
        body = "\n".join([f"        move.l  {preg},(%a0)+"] * NLV)
        return f"""        lsr.w   #1,{cnt}
        neg.w   {cnt}
        jmp     1f(%pc,{cnt}.w)
{body}
1:
"""

    def PIECE(tab, fld, src):
        """two longs from the piece table at set+tab, entry (width field fld of the row, a*8 in src.w)"""
        return f"""        movea.l {tab}(%a3),%a1
        adda.w  {fld}(%a4),%a1
        adda.w  {src},%a1
        move.l  (%a1)+,(%a0)+
        move.l  (%a1)+,(%a0)+
"""

    def GAP(hi, lo):
        """d1 = (long(hi) - long(lo) - 2) * 4; leaves lo swapped (its long index in the low word)"""
        return f"""        move.l  {hi},%d1
        swap    %d1
        swap    {lo}
        sub.w   {lo},%d1
        subq.w  #8,%d1
"""

    def ge2(a, b, fail):
        """branch to fail unless long(a) >= long(b) + 2 (long indices in the high words)"""
        return f"""        move.l  {b},%d1
        swap    %d1
        addq.w  #8,%d1
        move.l  {a},%d3
        swap    %d3
        cmp.w   %d1,%d3
        blt     {fail}
"""

    def CL(reg):
        """clamp a decoded right-hand piece position into the right margin"""
        return f"""        move.l  {reg},%d1
        swap    %d1
        cmp.w   #(PF_NLV-2)*4,%d1
        ble.s   1f
        move.l  #((PF_NLV-2)*4)<<16,{reg}
1:
"""

    def decode(reg, off):
        return f"""        move.w  %d4,{reg}
        add.w   {off}(%a4),{reg}
        move.l  0(%a6,{reg}.w),{reg}
"""
    NEXT = """        lea     PF_OFSZ(%a4),%a4
        bra     rd_row
"""
    emit("""| ------------------------------------------------------------------------------------------
| road_draw: pass 2. a0 = RoadState, a1 = destination of road row k=1 (buffer row HY+1);
| the third C argument (row skip) is ignored: rows are PF_RBV bytes apart.
| Draws rows k = 1..KB (top down); stops at the sentinel record (marked = -1) that road_geom
| writes after row KB. Every long of a row is written exactly once.
| ROWS[k].marked: 0 plain, 1 with lane markers, 2 plain without the fast path (e.g. fog rows,
| whose pattern set has no piece tables). Fast path: rumble strips and markers as two-long
| pieces from per-pattern-set tables (see road.py piece_tables), runs filled in between.
| Decoded positions (rt_dec): high word = long index * 4, low word = bit * 8.
road_draw:
        movem.l %d2-%d7/%a2-%a6,-(%sp)
        movea.l rs_rows(%a0),%a5
        addq.l  #8,%a5                  | ROWS[1]
        movea.l %a1,%a0
        lea     rt_offs+PF_OFSZ(%pc),%a4    | offsets of row 1
        lea     rt_rmask(%pc),%a2
        lea     rt_dec0(%pc),%a6
rd_row: movea.l (%a5)+,%a3
        move.w  (%a5)+,%d4
        move.w  (%a5)+,%d0
        beq.s   rd_fplain
        bmi     rd_done
        subq.w  #1,%d0
        beq     rd_fmark
        bra     rd_gplain
| ---- fast plain row: G | L piece | A | R piece | G
rd_fplain:
""" + decode("%d0", 0) + decode("%d2", 12) + CL("%d2") + ge2("%d2", "%d0", "rd_gplain") + """        move.l  (%a3),%d5
        move.l  8(%a3),%d6
        move.l  %d0,%d1
        swap    %d1
""" + FILL("%d1", "%d5") + PIECE(16, 16, "%d0") + GAP("%d2", "%d0") + FILL("%d1", "%d6") + PIECE(20, 16, "%d2")
         + """        swap    %d2
        move.w  #(PF_NLV-2)*4,%d1
        sub.w   %d2,%d1
""" + FILL("%d1", "%d5") + NEXT + """| ---- fast marked row: G | L | A | M | A | M | A | R | G
rd_fmark:
""" + decode("%d0", 0) + decode("%d2", 12) + CL("%d2") + decode("%d5", 4) + decode("%d6", 8) + CL("%d6")
         + ge2("%d5", "%d0", "rd_gmark") + ge2("%d6", "%d5", "rd_gmark") + ge2("%d2", "%d6", "rd_gmark")
         + """        move.l  8(%a3),%d7
        move.l  (%a3),%d3
        move.l  %d0,%d1
        swap    %d1
""" + FILL("%d1", "%d3") + PIECE(16, 16, "%d0") + GAP("%d5", "%d0") + FILL("%d1", "%d7") + PIECE(24, 18, "%d5")
         + GAP("%d6", "%d5") + FILL("%d1", "%d7") + PIECE(24, 18, "%d6") + GAP("%d2", "%d6") + FILL("%d1", "%d7")
         + PIECE(20, 16, "%d2") + """        swap    %d2
        move.w  #(PF_NLV-2)*4,%d1
        sub.w   %d2,%d1
""" + FILL("%d1", "%d3") + NEXT + """| ---- generic rows (any clipping, narrow far rows): one boundary at a time
rd_gplain:
        moveq   #0,%d7
        move.l  (%a3),%d5
        move.l  %d5,%d6""")
    for off, q in ((0, 4), (2, 8), (12, 4), (14, 0)):
        emit(BOUND.format(off=off, q=q, fills=fills))
    emit(FLUSH.format(fills=fills))
    emit(NEXT + """rd_gmark:
        moveq   #0,%d7
        move.l  (%a3),%d5
        move.l  %d5,%d6""")
    for off, q in ((0, 4), (2, 8), (4, 12), (6, 8), (8, 12), (10, 8), (12, 4), (14, 0)):
        emit(BOUND.format(off=off, q=q, fills=fills))
    emit(FLUSH.format(fills=fills))
    emit(NEXT + """rd_done:
        movem.l (%sp)+,%d2-%d7/%a2-%a6
        rts
""")
    # buffer -> screen copy, NL longs per row, movem in chunks
    regs = ["%d0", "%d1", "%d2", "%d3", "%d4", "%d5", "%d6", "%d7", "%a2", "%a3", "%a4", "%a5", "%a6"]
    chunks, left = [], NL
    while left > 0:
        n = min(left, len(regs))
        chunks.append(n)
        left -= n
    body = []
    off = 0
    for n in chunks:
        rl = "/".join(regs[:n]) if n > 1 else regs[0]
        body.append(f"        movem.l (%a0)+,{rl}\n        movem.l {rl},{off}(%a1)")
        off += 4 * n
    emit(f"""| ------------------------------------------------------------------------------------------
| pf_copy: a0 = first visible long of the source rows (RBV bytes apart), a1 = screen destination,
| d0.w = number of rows. Screen rows are 64 bytes apart.
pf_copy:
        movem.l %d2-%d7/%a2-%a6,-(%sp)
        move.w  %d0,-(%sp)
        subq.w  #1,(%sp)
1:
{chr(10).join(body)}
        lea     64(%a1),%a1
        lea     PF_RBV-PF_RB(%a0),%a0
        subq.w  #1,(%sp)
        bpl.s   1b
        addq.l  #2,%sp
        movem.l (%sp)+,%d2-%d7/%a2-%a6
        rts

| row_copy: like pf_copy but the source rows are d1.w bytes apart (e.g. a pre-shifted strip)
row_copy:
        movem.l %d2-%d7/%a2-%a6,-(%sp)
        move.w  %d0,-(%sp)
        subq.w  #1,(%sp)
        movea.w %d1,%a6                 | source skip = stride - RB (NL <= 12, so a6 is free)
        suba.w  #PF_RB,%a6
1:
{chr(10).join(body)}
        lea     64(%a1),%a1
        adda.w  %a6,%a0
        subq.w  #1,(%sp)
        bpl.s   1b
        addq.l  #2,%sp
        movem.l (%sp)+,%d2-%d7/%a2-%a6
        rts
""")
    return "\n".join(o)


WRAPPERS = """| C-callable entry points (GCC m68k ABI: args on the stack, d0-d1/a0-a1 scratch)
        .globl  RoadGeom
        .globl  RoadDraw
        .globl  PfCopy
        .globl  SprBlit
        .globl  RowCopy
| void RowCopy(const void *src, void *screen, long rows, long srcStride): PF_RB bytes per row
RowCopy:
        movea.l 4(%sp),%a0
        movea.l 8(%sp),%a1
        move.l  12(%sp),%d0
        move.l  16(%sp),%d1
        bra     row_copy
| void RoadGeom(RoadState *rs)
RoadGeom:
        movea.l 4(%sp),%a0
        bra     road_geom
| void RoadDraw(RoadState *rs, void *rowK1, long skip)
RoadDraw:
        movea.l 4(%sp),%a0
        movea.l 8(%sp),%a1
        move.l  12(%sp),%d0
        bra     road_draw
| void PfCopy(const void *buf, void *screen, long rows)
PfCopy:
        movea.l 4(%sp),%a0
        movea.l 8(%sp),%a1
        move.l  12(%sp),%d0
        bra     pf_copy
| void SprBlit(void *dst, const void *src, long rows, long wpr, long dstSkip)
| Whole sprite rows (no column clipping): each row is wpr words stored as (mask.l, image.l) per
| word pair plus (mask.w, image.w) for an odd last word; dst = (dst & mask) | image.
SprBlit:
        movem.l %d2-%d6,-(%sp)
        movea.l 24(%sp),%a0
        movea.l 28(%sp),%a1
        move.l  32(%sp),%d2
        move.l  36(%sp),%d3
        move.l  40(%sp),%d1
        subq.w  #1,%d2
        bmi.s   9f
        move.w  %d3,%d4
        and.w   #1,%d4                  | odd word?
        lsr.w   #1,%d3
        subq.w  #1,%d3                  | pairs - 1 (may be -1)
1:      move.w  %d3,%d5
        bmi.s   3f
2:      move.l  (%a1)+,%d6
        and.l   %d6,(%a0)
        move.l  (%a1)+,%d6
        or.l    %d6,(%a0)+
        dbf     %d5,2b
3:      tst.w   %d4
        beq.s   4f
        move.w  (%a1)+,%d6
        and.w   %d6,(%a0)
        move.w  (%a1)+,%d6
        or.w    %d6,(%a0)+
4:      adda.w  %d1,%a0
        dbf     %d2,1b
9:      movem.l (%sp)+,%d2-%d6
        rts
"""


def gen_header(cfg, tabs):
    KB = cfg.KB
    def arr(name, vals):
        return f"static const {"unsigned short" if name == "rt_zrow_c" else "short"} {name}[{len(vals)}] = {{" + ",".join(str(int(v)) for v in vals) + "};"
    return f"""/* Generated by gen_road.py: road engine interface ({cfg.W}x{cfg.H}, horizon {cfg.HY}) */
#ifndef ROAD_ENGINE_H
#define ROAD_ENGINE_H
#define PF_W {cfg.W}
#define PF_H {cfg.H}
#define PF_HY {cfg.HY}
#define PF_KB {KB}
#define PF_RB {cfg.W // 8}
#define PF_MG {cfg.MG}
#define PF_RBV {cfg.W // 8 + 8 * cfg.MG}   /* buffer row bytes: MG invisible longs each side */
#define PF_ZNEAR {cfg.ZNEAR}
#define PF_ZS {cfg.ZS}
#define PF_SS {cfg.STRIPE_SHIFT}
#define PF_RWMAX {int(max(tabs["rw"]))}
#define PF_MWMAX {int(max(tabs["mw"]))}
/* A pattern set (32 bytes): grass, rumble, road, marker patterns + edge piece tables
   (see road.py piece_tables; entry (w, a) at w*256 + a*8, two longs). */
typedef struct {{ unsigned long pat[4]; const unsigned char *pl, *pr, *pm; long pad; }} PatSet;
typedef struct {{
    unsigned long camz;     /* camera world z */
    short camx;             /* camera x offset (px at the bottom row) */
    short pad;
    const long *segp;       /* current segment {{len, ddx}} holding camz + ZNEAR */
    unsigned long segend;   /* absolute z where it ends */
    const long *ring, *ringend;
    const PatSet *pats;     /* 4 sets: [phase0 even][phase0 odd][phase1 even][phase1 odd] */
    void *rows;             /* 8*(KB+2) bytes: per row {{pattern ptr, cx*4, marked}} + sentinel */
}} RoadState;
/* marked: 0 plain, 1 lane markers, 2 plain without the fast path (pattern set may lack pieces) */
typedef struct {{ const void *pat; short cx4; short marked; }} RoadRow;
void RoadGeom(RoadState *rs);
void RoadDraw(RoadState *rs, void *rowK1, long skip);   /* skip is ignored (rows PF_RBV apart) */
void PfCopy(const void *buf, void *screen, long rows);
void RowCopy(const void *src, void *screen, long rows, long srcStride);  /* PF_RB bytes per row */
void SprBlit(void *dst, const void *src, long rows, long wpr, long dstSkip);   /* whole rows */
{arr("rt_zrow_c", tabs["zrow"])}
{arr("rt_hw_c", tabs["hw"])}
#endif
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("out")
    ap.add_argument("--w", type=int, default=384)
    ap.add_argument("--h", type=int, default=240)
    ap.add_argument("--hy", type=int, default=80)
    a = ap.parse_args()
    cfg = road.RoadConfig(W=a.w, H=a.h, HY=a.hy)
    tabs = road.build_tables(cfg)
    os.makedirs(a.out, exist_ok=True)
    open(os.path.join(a.out, "road_cfg.inc"), "w").write(gen_cfg(cfg, tabs))
    open(os.path.join(a.out, "road_kernel.s"), "w").write(gen_kernel(cfg, tabs))
    open(os.path.join(a.out, "road_data.s"), "w").write(gen_data(cfg, tabs))
    # flat single file for Retro68 (no .include paths needed) + C header
    flat = gen_cfg(cfg, tabs) + "        .text\n        .even\n" + WRAPPERS + gen_kernel(cfg, tabs) + gen_data(cfg, tabs)
