#!/usr/bin/env python3
"""Sprite pipeline: high-resolution masters -> scaled, outlined, masked, pre-shifted 1-bit sprites.

A master is a PIL "LA" image (L: 0 black .. 255 white, A: 0 transparent .. 255 opaque), drawn
large (for example 8x the biggest size). `scale()` box-filters it to each size, thresholds the
alpha, orders-dithers the grey levels (4x4 Bayer) and optionally adds a 1-pixel white outline.

Packed format for one sprite at one size, for each pre-shift s (0..nshift-1, x step 16/nshift):
`h` rows of wpr = ceil((w + maxshift) / 16) words; the sprite is shifted right by s * (16 / nshift)
pixels inside its words. Each row stores word pairs as (mask, mask, image, image) so they can be
drawn a long at a time, then an odd last word as (mask, image); 4 bytes per word in all. Drawing:
dst = (dst & mask) | image (SprBlit in road_engine.s; masks are 1 where the background shows). `emit()` writes the data as assembly and a C table:

    typedef struct { short w, h, wpr, nshift; long off; } SprInfo;   // off: byte offset in spr_data
"""
import numpy as np
from PIL import Image

BAYER4 = (np.array([[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]]) + 0.5) / 16


def scale(master, w, h, outline=True, alpha_cut=0.5):
    """-> (opaque, black) uint8 arrays (h x w)."""
    L, A = [np.asarray(c, dtype=np.float64) / 255 for c in master.split()]
    pre = Image.fromarray((L * A * 255).astype(np.uint8), "L").resize((w, h), Image.BOX)
    al = Image.fromarray((A * 255).astype(np.uint8), "L").resize((w, h), Image.BOX)
    a = np.asarray(al, dtype=np.float64) / 255
    lum = np.where(a > 0, np.asarray(pre, dtype=np.float64) / 255 / np.maximum(a, 1e-6), 1)
    opaque = (a >= alpha_cut).astype(np.uint8)
    thr = np.tile(BAYER4, (h // 4 + 1, w // 4 + 1))[:h, :w]
    black = ((lum < thr) & (opaque == 1)).astype(np.uint8)
    if outline:
        # grow the canvas by one pixel on every side so the outline fits
        o2 = np.zeros((h + 2, w + 2), np.uint8)
        b2 = np.zeros((h + 2, w + 2), np.uint8)
        o2[1:-1, 1:-1], b2[1:-1, 1:-1] = opaque, black
        p2 = np.pad(o2, 1)
        g2 = p2[1:-1, 1:-1] | p2[:-2, 1:-1] | p2[2:, 1:-1] | p2[1:-1, :-2] | p2[1:-1, 2:]
        return g2, b2
    return opaque, black


def pack(opaque, black, nshift=16):
    h, w = opaque.shape
    step = 16 // nshift
    wpr = (w + 16 - step + 15) // 16       # room for the largest shift
    out = bytearray()
    for s in range(nshift):
        sh = s * step
        for y in range(h):
            m = np.zeros(wpr * 16, np.uint8)
            b = np.zeros(wpr * 16, np.uint8)
            m[sh:sh + w] = opaque[y]
            b[sh:sh + w] = black[y]
            mws = [int("".join(map(str, m[c * 16:c * 16 + 16])), 2) ^ 0xFFFF for c in range(wpr)]  # 1 = keep
            iws = [int("".join(map(str, b[c * 16:c * 16 + 16])), 2) for c in range(wpr)]
            for c in range(0, wpr - 1, 2):        # word pairs as longs: mask, mask, image, image
                out += b"".join(v.to_bytes(2, "big") for v in (mws[c], mws[c + 1], iws[c], iws[c + 1]))
            if wpr & 1:                            # odd last word: mask, image
                out += mws[-1].to_bytes(2, "big") + iws[-1].to_bytes(2, "big")
    return bytes(out), wpr


class SpriteBank:
    def __init__(self):
        self.data = bytearray()
        self.info = []      # (name, w, h, wpr, nshift, off)
        self.previews = {}

    def add(self, name, opaque, black, nshift=16):
        h, w = opaque.shape
        blob, wpr = pack(opaque, black, nshift)
        self.info.append((name, w, h, wpr, nshift, len(self.data)))
        self.data += blob
        self.previews[name] = (opaque, black)
        return len(self.info) - 1

    def emit(self, s_path, h_path, prefix="spr"):
        lines = [f"| Generated by sprites.py: {len(self.info)} sprites, {len(self.data)} bytes",
                 "        .text", "        .even", f"        .globl  {prefix}_data", f"{prefix}_data:"]
        d = self.data
        for i in range(0, len(d), 32):
            lines.append("        .byte   " + ",".join(str(x) for x in d[i:i + 32]))
        open(s_path, "w").write("\n".join(lines) + "\n")
        hl = [f"/* Generated by sprites.py */", f"#ifndef {prefix.upper()}_H", f"#define {prefix.upper()}_H",
              "typedef struct { short w, h, wpr, nshift; long off; } SprInfo;",
              f"extern const unsigned char {prefix}_data[];",
              f"static const SprInfo {prefix}_info[{len(self.info)}] = {{"]
        for name, w, h, wpr, ns, off in self.info:
            hl.append(f"    {{{w}, {h}, {wpr}, {ns}, {off}}},  /* {name} */")
        hl.append("};")
        for i, (name, *_rest) in enumerate(self.info):
            hl.append(f"#define SPR_{name.upper()} {i}")
        hl.append("#endif")
        open(h_path, "w").write("\n".join(hl) + "\n")

    def sheet(self, path, names=None, bg=0.5):
        """Preview PNG: sprites on a grey (checker) background, 2x."""
        names = names or list(self.previews)
        ims = [self.previews[n] for n in names]
        W = sum(o.shape[1] + 4 for o, _ in ims) + 4
        H = max(o.shape[0] for o, _ in ims) + 8
        canvas = np.indices((H, W)).sum(0) % 2   # checkerboard background
        x = 4
        for o, b in ims:
            h, w = o.shape
            region = canvas[4:4 + h, x:x + w]
            canvas[4:4 + h, x:x + w] = np.where(o == 1, b, region)
            x += w + 4
        im = Image.fromarray(((1 - canvas) * 255).astype(np.uint8), "L")
        im.resize((W * 2, H * 2), Image.NEAREST).save(path)
