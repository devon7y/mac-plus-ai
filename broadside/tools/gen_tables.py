#!/usr/bin/env python3
"""Generate src/ai_tables.h: fixed-point log2/exp2 tables and the 10-bit popcount table.

The same tables are compiled into the host simulator and the Mac app, so both make exactly the
same decisions (no libm rounding differences)."""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
out = os.path.join(HERE, "..", "src", "ai_tables.h")

log2tab = [0] + [round(256 * math.log2(n)) for n in range(1, 256)]
exp2tab = [round(32768 * 2 ** (i / 256)) for i in range(256)]
pc10 = [bin(i).count("1") for i in range(1024)]


def rows(vals, per=16):
    return ",\n".join("    " + ", ".join(str(v) for v in vals[i:i + per]) for i in range(0, len(vals), per))


with open(out, "w") as f:
    f.write("/* Generated by tools/gen_tables.py: do not edit. */\n")
    f.write("/* round(256 * log2(n)), n = 1..255 (index 0 unused) */\n")
    f.write("static const unsigned short log2tab[256] = {\n%s\n};\n" % rows(log2tab))
    f.write("/* round(32768 * 2^(i/256)) */\n")
    f.write("static const unsigned short exp2tab[256] = {\n%s\n};\n" % rows(exp2tab))
    f.write("/* number of set bits in a 10-bit value */\n")
    f.write("static const unsigned char pc10[1024] = {\n%s\n};\n" % rows(pc10, 32))
print("wrote", os.path.relpath(out))
