#!/usr/bin/env python3
"""Generate a multi-segment Retro68 test app.

    gen.py <outdir> [scale] [data|code]

scale (default 1) multiplies the number of functions per segment (scale 4: about
110 + 110 + 280 KB of code, to probe how big an app the 1 MB Plus can run).
The last argument says where seg_c's 40 KB const table goes: "data" (default; const
data lands in DATA 0, copied into the A5 world at launch and resident for the whole run)
or "code" (section ".text.table_c": it becomes part of seg_c's CODE resource, loaded and
purged with that segment).

Writes seg_a.c, seg_b.c, seg_c.c (generated code, roughly 1 KB of 68000 code per
function), expected.h (results computed here in Python) and segments.segmap
(puts each seg_*.c in its own CODE segment). main.c (hand-written) calls into
every segment, unloads them with UnloadSeg, calls again and records the results
in a 'SEGT' debug block.
"""
import os
import random
import sys

M = 0xFFFFFFFF
SEGS = {"a": 48, "b": 48, "c": 120}     # functions per segment (about 1 KB each)
OPS = 60                                 # operations per function
TABLE_N = 20480                          # entries (2 bytes each) in seg_c's constant table


def gen_func(rng, name):
    ops = []
    for _ in range(OPS):
        k, s, c = rng.randrange(4), rng.randrange(1, 9), rng.randrange(1, 0xFFFFFFFF)
        ops.append((k, s, c))
    lines = [f"unsigned long {name}(unsigned long x)", "{"]
    for k, s, c in ops:
        if k == 0:
            lines.append(f"    x += (x << {s}) ^ 0x{c:08X}UL;")
        elif k == 1:
            lines.append(f"    x ^= (x >> {s}) + 0x{c:08X}UL;")
        elif k == 2:
            lines.append(f"    x = (x << {s}) | (x >> {32 - s});")
        else:
            lines.append(f"    x -= 0x{c:08X}UL ^ (x >> {s});")
    lines += ["    return x;", "}", ""]

    def py(x):
        for k, s, c in ops:
            if k == 0:
                x = (x + (((x << s) & M) ^ c)) & M
            elif k == 1:
                x ^= ((x >> s) + c) & M
            elif k == 2:
                x = ((x << s) | (x >> (32 - s))) & M
            else:
                x = (x - (c ^ (x >> s))) & M
        return x
    return "\n".join(lines), py


def main():
    out = sys.argv[1]
    scale = int(sys.argv[2]) if len(sys.argv) > 2 else 1
    table_attr = '__attribute__((section(".text.table_c"))) ' if len(sys.argv) > 3 and sys.argv[3] == "code" else ""
    for k in SEGS:
        SEGS[k] *= scale
    os.makedirs(out, exist_ok=True)
    rng = random.Random(1986)
    expected = {}
    for seg, n in SEGS.items():
        funcs, pys = [], []
        for i in range(n):
            src, py = gen_func(rng, f"f{seg}_{i}")
            funcs.append(src)
            pys.append(py)
        # The segment's entry point runs every function in order (the last ones sit far
        # beyond 32 KB from the segment start in the bigger segments).
        body = [f"unsigned long seg_{seg}_run(unsigned long x)", "{"]
        body += [f"    x = f{seg}_{i}(x);" for i in range(n)]
        body += ["    return x;", "}", ""]
        decls = [f"unsigned long f{seg}_{i}(unsigned long x);" for i in range(n)]
        table = ""
        if seg == "c":
            # A 40 KB constant table (more than 32 KB) and a function summing it.
            vals = [rng.randrange(65536) for _ in range(TABLE_N)]
            expected["table"] = sum(vals) & M
            rows = [", ".join(str(v) for v in vals[i:i + 16]) for i in range(0, TABLE_N, 16)]
            table = (f"{table_attr}const unsigned short table_c[{TABLE_N}] = {{\n    " + ",\n    ".join(rows) + "\n};\n\n"
                     "unsigned long table_sum(void)\n{\n    unsigned long s = 0;\n    long i;\n"
                     f"    for (i = 0; i < {TABLE_N}; i++)\n        s += table_c[i];\n    return s;\n}}\n\n")
        with open(os.path.join(out, f"seg_{seg}.c"), "w") as f:
            f.write("/* generated by gen.py */\n" + "\n".join(decls) + "\n\n" + table + "\n".join(funcs) + "\n".join(body))
        x = 0x12345678
        for py in pys:
            x = py(x)
        expected[seg] = x
    with open(os.path.join(out, "expected.h"), "w") as f:
        f.write("/* generated by gen.py */\n#define SEED 0x12345678UL\n")
        for seg, v in expected.items():
            f.write(f"#define EXPECT_{seg.upper()} 0x{v:08X}UL\n")
    with open(os.path.join(out, "segments.segmap"), "w") as f:
        for seg in SEGS:
            f.write(f"SEGMENT Seg {seg.upper()}\n    */seg_{seg}.*\n")
    print("expected:", {k: hex(v) for k, v in expected.items()})


if __name__ == "__main__":
    main()
