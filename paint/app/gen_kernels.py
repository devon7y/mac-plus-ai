#!/usr/bin/env python3
"""Generate Doodle's decoder kernels for the app: kernels.s (GNU as, 68000) and kernels.h.

The kernels are the benchmark's (paint/bench/kernels.py, verified bit-exact in M1), with
their globals moved from A5-relative slots into two absolute blocks, dk_g (scalars and
routine pointers) and dk_p (buffer pointers), plus:
  p_fold2   per-drawing category fold with two shifts and per-row multipliers; its last H
            rows give the initial state h0 = TANH[...] (FORMAT.md, "Per-drawing constants")
  dk_init / dk_fold / dk_prime / dk_full   C-callable entry points (save d2-d7/a2-a4/a6)
Usage: gen_kernels.py <out dir>
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
BENCH = os.path.join(HERE, "..", "bench")
sys.path.insert(0, BENCH)
from tables import CENTER, TABLES  # noqa: E402

OUT = sys.argv[1] if len(sys.argv) > 1 else "."
HS = (192, 256, 384)
NOUT, NEMB = 123, 32

PTRS = ["U", "WY", "LUT", "A2", "A3", "M", "MN", "MY", "BY", "E", "B0", "P", "WDX", "WDY", "WE", "EMB",
        "EW", "CX", "S", "GV", "HST", "HQ", "C", "SY", "O", "TL", "SAMP", "SCAL", "TRACE",
        "S_2", "CX_2", "GV_1", "GV_2", "S_3", "M_3", "CX_3", "GV_3", "MC", "WC", "A2O", "A3O", "LUTO", "HQO", "WY2", "MY2", "SY2"]
PIDX = {n: i for i, n in enumerate(PTRS)}
GL, cur = {}, 0
for n in ("SEED", "ENTRY", "MV", "BLD", "GATE", "LCELL", "SIGC", "TANHC", "SECHC", "EXPSC", "EXPP", "RTAB", "COS",
          "ENTRYO", "MVO", "BLDO"):
    GL[n] = cur
    cur += 4
for n in ("H", "G", "R", "A", "SHR", "SHO", "SHA", "SHB", "SHX", "KIND", "PEN", "DX", "DY", "CAT", "INVT", "INVTP", "HLT", "FQ",
          "KINDO", "GO", "AO", "MIXED", "R2O", "SHO2"):
    GL[n] = cur
    cur += 2
GSIZE = (cur + 3) & ~3


def G(name):
    return f"dk_g+{GL[name]}"


def P(name):
    return f"dk_p+{4 * PIDX[name]}"


asm = []
emit = asm.append
emit("""| Generated by paint/app/gen_kernels.py from paint/bench/kernels.py. Do not edit.
        .text""")
exec(open(os.path.join(BENCH, "kernels.py")).read())

SAVE = "%d2-%d7/%a2-%a4/%a6"
emit(f"""
| rand: xorshift32 (x ^= x<<13; x ^= x>>17; x ^= x<<5) -> d0. Preserves all but d0.
rand:   move.l  %d1,-(%sp)
        move.l  {G('SEED')},%d0
        move.l  %d0,%d1
        lsl.l   #8,%d1
        lsl.l   #5,%d1
        eor.l   %d1,%d0
        move.l  %d0,%d1
        swap    %d1
        and.l   #0xFFFF,%d1
        lsr.l   #1,%d1
        eor.l   %d1,%d0
        move.l  %d0,%d1
        lsl.l   #5,%d1
        eor.l   %d1,%d0
        move.l  %d0,{G('SEED')}
        move.l  (%sp)+,%d1
        rts

| p_fold2: for the R + H fold rows: acc = sum_j WC[i][j]*EMB[cat][j] (int8 x int16, 32-bit),
| v = clip16(acc >> SHA), e = clip16(B0[i] + ((v*MC[i]) >> SHB)) -> E[i]. The last H rows
| give h0: HST[j] = TANH[(clip(e, -4096, 4095) >> 3) + 512].
p_fold2:
        movea.l {P('EMB')},%a2
        move.w  {G('CAT')},%d0
        ext.l   %d0
        lsl.l   #6,%d0
        adda.l  %d0,%a2
        movea.l {P('WC')},%a0
        movea.l {P('MC')},%a3
        movea.l {P('B0')},%a4
        movea.l {P('E')},%a6
        move.w  {G('R')},%d6
        add.w   {G('H')},%d6
        subq.w  #1,%d6
        move.w  {G('SHA')},%d7
        move.w  {G('SHB')},%d5
        move.l  #32767,%d3
        move.l  #-32768,%d4
1:      movea.l %a2,%a1
        moveq   #0,%d1""")
for _ in range(NEMB):
    emit("        move.b  (%a0)+,%d0\n        ext.w   %d0\n        muls.w  (%a1)+,%d0\n        add.l   %d0,%d1")
emit(f"""        asr.l   %d7,%d1
        cmp.l   %d3,%d1
        ble.s   2f
        move.l  %d3,%d1
2:      cmp.l   %d4,%d1
        bge.s   3f
        move.l  %d4,%d1
3:      muls.w  (%a3)+,%d1
        asr.l   %d5,%d1
        move.w  (%a4)+,%d0
        ext.l   %d0
        add.l   %d0,%d1
        cmp.l   %d3,%d1
        ble.s   4f
        move.l  %d3,%d1
4:      cmp.l   %d4,%d1
        bge.s   5f
        move.l  %d4,%d1
5:      move.w  %d1,(%a6)+
        dbf     %d6,1b
| h0 from the last H fold values
        movea.l {P('E')},%a0
        move.w  {G('R')},%d0
        add.w   %d0,%d0
        adda.w  %d0,%a0
        movea.l {P('HST')},%a1
        movea.l {G('TANHC')},%a3
        move.w  {G('H')},%d6
        subq.w  #1,%d6
6:      move.w  (%a0)+,%d0
        cmp.w   #4095,%d0
        ble.s   7f
        move.w  #4095,%d0
7:      cmp.w   #-4096,%d0
        bge.s   8f
        move.w  #-4096,%d0
8:      asr.w   #3,%d0
        add.w   %d0,%d0
        move.w  0(%a3,%d0.w),(%a1)+
        dbf     %d6,6b
        rts

| ---------------------------------------------------------------- C entry points
        .globl  dk_init, dk_fold, dk_prime, dk_full, dk_g, dk_p
| kindsel: d0 = kind (0 W4, 1 B4, 2 P4), d1 = groups -> a1 builder, a2 kernel, a3 entry point
kindsel:
        andi.l  #0xFFFF,%d1
        lea     bld_t(%pc),%a1
        lea     mv_W(%pc),%a2
        lea     mvW_end(%pc),%a3
        moveq   #6,%d2
        tst.w   %d0
        beq.s   1f
        lea     mv_B(%pc),%a2
        lea     mvB_end(%pc),%a3
        moveq   #10,%d2
        subq.w  #1,%d0
        beq.s   1f
        lea     bld_p(%pc),%a1
        lea     mv_P(%pc),%a2
        lea     mvP_end(%pc),%a3
        moveq   #6,%d2
1:      mulu.w  %d2,%d1
        suba.l  %d1,%a3
        rts
| dk_init: table pointers; routines for KIND/G (recurrence) and KINDO/GO (output layer).
dk_init:
        movem.l {SAVE},-(%sp)
        jsr     set_tables
        move.w  {G('KIND')},%d0
        move.w  {G('G')},%d1
        jsr     kindsel
        move.l  %a1,{G('BLD')}
        move.l  %a2,{G('MV')}
        move.l  %a3,{G('ENTRY')}
        move.w  {G('KINDO')},%d0
        move.w  {G('GO')},%d1
        jsr     kindsel
        move.l  %a1,{G('BLDO')}
        move.l  %a2,{G('MVO')}
        move.l  %a3,{G('ENTRYO')}
        lea     gate_gru(%pc),%a1
        move.l  %a1,{G('GATE')}
        movem.l (%sp)+,{SAVE}
        rts
| p_outx: output layer. When MIXED, it reads its own quantization of h (scale AO, kind
| KINDO, its own lookup tables): swap the output context in, hq_o, tables, p_out, swap back.
p_outx: tst.w   {G('MIXED')}
        bne.s   1f
        jmp     p_outa
1:      jsr     swapo
        jsr     p_hq
        jsr     p_lut
        jsr     p_outa
swapo:
        move.l  {G('MV')},%d0
        move.l  {G('MVO')},{G('MV')}
        move.l  %d0,{G('MVO')}
        move.l  {G('ENTRY')},%d0
        move.l  {G('ENTRYO')},{G('ENTRY')}
        move.l  %d0,{G('ENTRYO')}
        move.l  {G('BLD')},%d0
        move.l  {G('BLDO')},{G('BLD')}
        move.l  %d0,{G('BLDO')}
        move.w  {G('G')},%d0
        move.w  {G('GO')},{G('G')}
        move.w  %d0,{G('GO')}
        move.w  {G('A')},%d0
        move.w  {G('AO')},{G('A')}
        move.w  %d0,{G('AO')}
        move.l  {P('A2')},%d0
        move.l  {P('A2O')},{P('A2')}
        move.l  %d0,{P('A2O')}
        move.l  {P('A3')},%d0
        move.l  {P('A3O')},{P('A3')}
        move.l  %d0,{P('A3O')}
        move.l  {P('LUT')},%d0
        move.l  {P('LUTO')},{P('LUT')}
        move.l  %d0,{P('LUTO')}
        move.l  {P('HQ')},%d0
        move.l  {P('HQO')},{P('HQ')}
        move.l  %d0,{P('HQO')}
        rts
| p_outa: one- or two-term output layer (R2O). Two-term ("tern_r2o"): a second matrix WY2 over
| the same lookup tables, O = clip16(BY + ((SY*MY) >> SHO) + ((SY2*MY2) >> SHO2)), 32-bit sum.
p_outa: tst.w   {G('R2O')}
        bne.s   1f
        jmp     p_out
1:      movea.l {P('WY')},%a1
        movea.l {P('SY')},%a6
        moveq   #{NOUT - 1},%d6
        movea.l {G('MV')},%a0
        jsr     (%a0)
        movea.l {P('WY2')},%a1
        movea.l {P('SY2')},%a6
        moveq   #{NOUT - 1},%d6
        movea.l {G('MV')},%a0
        jsr     (%a0)
        movea.l {P('SY')},%a0
        movea.l {P('MY')},%a1
        movea.l {P('BY')},%a2
        movea.l {P('SY2')},%a3
        movea.l {P('MY2')},%a4
        movea.l {P('O')},%a6
        moveq   #{NOUT - 1},%d6
        move.w  {G('SHO')},%d7
        move.w  {G('SHO2')},%d3
        move.l  #32767,%d5
        move.l  #-32768,%d4
2:      move.w  (%a0)+,%d0
        muls.w  (%a1)+,%d0
        asr.l   %d7,%d0
        move.w  (%a3)+,%d1
        muls.w  (%a4)+,%d1
        asr.l   %d3,%d1
        add.l   %d1,%d0
        move.w  (%a2)+,%d1
        ext.l   %d1
        add.l   %d1,%d0
        cmp.l   %d5,%d0
        ble.s   3f
        move.l  %d5,%d0
3:      cmp.l   %d4,%d0
        bge.s   4f
        move.l  %d4,%d0
4:      move.w  %d0,(%a6)+
        dbf     %d6,2b
        rts
| app_step: a full pen move with the app's output layer
app_step:
        jsr     p_rec
        jsr     p_inp
        jsr     p_gate
        jsr     p_lut
        jsr     p_outx
        jmp     p_samp
| dk_fold: per-drawing constants, h0, hq, lookup tables
dk_fold:
        movem.l {SAVE},-(%sp)
        jsr     p_fold2
        jsr     p_hq
        jsr     p_lut
        movem.l (%sp)+,{SAVE}
        rts
| dk_prime: one step on the input (PEN, DX, DY) without output layer or sampling
dk_prime:
        movem.l {SAVE},-(%sp)
        jsr     step_prime
        movem.l (%sp)+,{SAVE}
        rts
| dk_full: one step + output layer + sampling; the sample becomes the next input and SAMP
dk_full:
        movem.l {SAVE},-(%sp)
        jsr     app_step
        movem.l (%sp)+,{SAVE}
        rts

set_tables:""")
for name, gname in (("SIG", "SIGC"), ("TANH", "TANHC"), ("SECH", "SECHC"), ("EXPS", "EXPSC"),
                    ("EXPP", "EXPP"), ("RTAB", "RTAB"), ("COS", "COS")):
    emit(f"        lea     T_{name}+{2 * CENTER[name]}(%pc),%a0\n        move.l  %a0,{G(gname)}")
emit("        rts")
for name, t in TABLES.items():
    emit(f"T_{name}:")
    for j in range(0, len(t), 16):
        emit("        .short  " + ", ".join(str(v) for v in t[j:j + 16]))
emit(f"""
        .section .bss
        .even
dk_g:   .space  {GSIZE}
dk_p:   .space  {4 * len(PTRS)}
""")

text = re.sub(r"(jsr\s+|jmp\s+)([A-Za-z_][A-Za-z0-9_]*)\s*$", r"\1\2(%pc)", "\n".join(asm), flags=re.M)
os.makedirs(OUT, exist_ok=True)
open(os.path.join(OUT, "kernels.s"), "w").write(text + "\n")

h = ["/* Generated by gen_kernels.py: the decoder kernels' context (see paint/bench/FORMAT.md). */",
     "#ifndef KERNELS_H", "#define KERNELS_H", "extern char dk_g[], dk_p[];",
     "void dk_init(void);   /* after setting KIND, G (and the table pointers are set) */",
     "void dk_fold(void);   /* CAT -> E, h0, hq, lookup tables */",
     "void dk_prime(void);  /* step on (PEN, DX, DY) */",
     "void dk_full(void);   /* step + output + sample (SAMP; PEN/DX/DY updated) */",
     "#define DKW(n) (*(short *)(dk_g + DKG_##n))", "#define DKL(n) (*(long *)(dk_g + DKG_##n))",
     "#define DKP(n) (*(void **)(dk_p + 4 * DKP_##n))"]
for n, o in GL.items():
    h.append(f"#define DKG_{n} {o}")
for n, i in PIDX.items():
    h.append(f"#define DKP_{n} {i}")
h.append(f"#define DK_NPTRS {len(PTRS)}")
h.append("#endif")
open(os.path.join(OUT, "kernels.h"), "w").write("\n".join(h) + "\n")
print(f"kernels.s: {len(asm)} lines; dk_g {GSIZE} bytes, dk_p {4 * len(PTRS)} bytes")
