def grid():
    return [[0] * 16 for _ in range(16)]


def from_art(s):
    rows = [r for r in s.strip("\n").split("\n")]
    assert len(rows) == 16 and all(len(r) == 16 for r in rows), s
    return [[1 if c == "#" else 0 for c in r] for r in rows]


def rect(fill):
    g = grid()
    for y in range(3, 13):
        for x in range(2, 14):
            edge = y in (3, 12) or x in (2, 13)
            g[y][x] = 1 if edge or (fill and (x + y) % 2 == 0) else 0
    return g


def oval(fill):
    g = grid()
    cx, cy, rx, ry = 7.5, 7.5, 6.0, 5.0
    for y in range(16):
        for x in range(16):
            d = ((x - cx) / rx) ** 2 + ((y - cy) / ry) ** 2
            inner = ((x - cx) / (rx - 1.1)) ** 2 + ((y - cy) / (ry - 1.1)) ** 2
            if d <= 1.0 and inner > 1.0:
                g[y][x] = 1
            elif fill and inner <= 1.0 and (x + y) % 2 == 0:
                g[y][x] = 1
    return g


def select():
    g = grid()
    for y in range(3, 13):
        for x in range(2, 14):
            if y in (3, 12) and (x // 2) % 2 == 0:
                g[y][x] = 1
            if x in (2, 13) and (y // 2) % 2 == 1:
                g[y][x] = 1
    return g


def line():
    g = grid()
    for i in range(12):
        g[13 - i][2 + i] = 1
    return g


