#!/usr/bin/env python3
"""The handwriting the Mac uses to write its answers: original stroke glyphs (catmull-rom splines
through hand-placed points), sampled into short polylines for app/hand_gen.c.

    python3 -I gen_hand.py <outdir>      -> hand_gen.c, hand_gen.h
Units: a digit is 100 tall, y down, baseline at y = 100. Glyphs: 0-9 . - x (times) and E.
"""
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from synth import catmull, ellipse   # noqa: E402

GLYPHS = {
    "0": (70, [ellipse(32, 50, 27, 50, -100, 268, 40)]),
    "1": (44, [catmull([(10, 24), (30, 2), (29, 50), (28, 100)])]),
    "2": (66, [catmull([(6, 26), (30, 1), (54, 22), (42, 54), (6, 99), (34, 97), (60, 98)])]),
    "3": (64, [catmull([(6, 14), (30, 0), (52, 18), (24, 46), (54, 70), (30, 100), (4, 88)])]),
    "4": (68, [catmull([(40, 0), (4, 66), (62, 66)]), catmull([(46, 32), (45, 100)])]),
    "5": (64, [catmull([(52, 1), (14, 0), (9, 45), (32, 37), (55, 62), (43, 95), (5, 92)])]),
    "6": (64, [catmull([(50, 4), (20, 36), (7, 76), (29, 100), (53, 78), (31, 54), (7, 70)])]),
    "7": (62, [catmull([(4, 1), (58, 0), (40, 40), (24, 100)])]),
    "8": (62, [catmull([(48, 14), (28, 0), (7, 17), (28, 46), (53, 72), (29, 100), (4, 75), (28, 46),
                        (49, 19), (30, 1)])]),
    "9": (64, [catmull([(52, 22), (30, 0), (7, 20), (28, 45), (52, 27), (53, 8), (50, 50), (47, 100)])]),
    ".": (22, [np.array([[7.0, 95.0], [9.0, 100.0], [11.0, 97.0]])]),
    "-": (50, [np.array([[5.0, 56.0], [42.0, 55.0]])]),
    "x": (46, [np.array([[6.0, 40.0], [36.0, 74.0]]), np.array([[36.0, 40.0], [6.0, 74.0]])]),
    "E": (54, [catmull([(46, 2), (8, 0), (6, 50), (5, 100), (48, 99)]), np.array([[7.0, 50.0], [38.0, 50.0]])]),
}


def simplify(p, step=6.0):
    """Keep points about `step` units apart along the path (always the ends)."""
    out = [p[0]]
    acc = 0.0
    for i in range(1, len(p)):
        acc += float(np.hypot(*(p[i] - p[i - 1])))
        if acc >= step:
            out.append(p[i])
            acc = 0.0
    if not np.array_equal(out[-1], p[-1]):
        out.append(p[-1])
    return np.array(out)


def main():
    out = sys.argv[1]
    os.makedirs(out, exist_ok=True)
    data, idx = [], []
    chars = sorted(GLYPHS)
    for ch in chars:
        adv, strokes = GLYPHS[ch]
        idx.append((ch, len(data), adv))
        data.append(len(strokes))
        for s in strokes:
            q = np.clip(np.round(simplify(np.asarray(s, np.float64))), 0, 127).astype(int)
            data.append(len(q))
            for x, y in q:
                data += [int(x), int(y)]
    h = ["/* Generated by calc/ref/gen_hand.py; do not edit. */", "#ifndef HAND_GEN_H", "#define HAND_GEN_H",
         f"#define HAND_N {len(chars)}",
         "extern const char handChars[HAND_N + 1];",
         "extern const short handOff[HAND_N], handAdv[HAND_N];",
         f"extern const unsigned char handData[{len(data)}];",
         "#endif", ""]
    c = ["/* Generated by calc/ref/gen_hand.py: the Mac's handwriting (original glyphs); do not edit.",
         " * Per glyph at handOff: stroke count, then per stroke: point count and (x, y) pairs;",
         " * a digit is 100 tall, baseline y = 100. */",
         '#include "hand_gen.h"',
         'const char handChars[HAND_N + 1] = "' + "".join(chars) + '";',
         "const short handOff[HAND_N] = {" + ", ".join(str(o) for _, o, _ in idx) + "};",
         "const short handAdv[HAND_N] = {" + ", ".join(str(a) for _, _, a in idx) + "};",
         f"const unsigned char handData[{len(data)}] = {{"]
    for i in range(0, len(data), 24):
        c.append("    " + ", ".join(str(v) for v in data[i:i + 24]) + ",")
    c.append("};")
    open(os.path.join(out, "hand_gen.h"), "w").write("\n".join(h))
    open(os.path.join(out, "hand_gen.c"), "w").write("\n".join(c) + "\n")
    print(f"hand glyphs {''.join(chars)}: {len(data)} bytes")


if __name__ == "__main__":
    main()
