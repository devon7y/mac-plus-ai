#!/usr/bin/env python3
"""Generate the Mac's classifier code from an integer model (ref.py export).

    python3 -I gen_net.py <model.npz> <outdir>
      -> net68k.s   one routine per ternary layer: void nlK(const short *in, short *raw)
                    (unrolled add/sub of the inputs; zero weights cost nothing)
         net_gen.c  tables (lookup table, requant constants) and net_forward(); with -DNET_HOST the
                    ternary layers are plain C loops over weight arrays instead (the host check)
         net_gen.h

Requant (bit-exact with ref.py): v = (acc * m + bm) >> 16 with bm = b * m + 32768 (32-bit), then
clamp to 0..amax (not for the last layer). acc is int16 (bounds are checked here).
"""
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ref   # noqa: E402

G = 24


def plan(M):
    """Per ternary layer: dict with geometry and tensors."""
    L = M["layers"]
    out = []
    H = G // 2
    C = L[0]["C"]
    amax_in = 127
    for k, l in enumerate(L[1:], 1):
        t = M[f"t{k}"].astype(np.int64)
        b, m = M[f"b{k}"].astype(np.int64), M[f"m{k}"].astype(np.int64)
        last = k == len(L) - 1
        if l["kind"] == "conv":
            s = l["stride"]
            Hc = (H + s - 1) // s
            Ho = Hc // 2 if l["pool"] else Hc
            Co = t.shape[0]
            taps = []
            for dy in range(3):
                for dx in range(3):
                    for ci in range(C):
                        taps.append((((dy * (H + 2) + dx) * C + ci) * 2, t[:, dy, dx, ci]))
            fan = 9 * C
            d = dict(k=k, kind="conv", Hin=H, Cin=C, stride=s, Hc=Hc, pool=l["pool"], Ho=Ho, Co=Co,
                     amax=l["amax"], taps=taps, t=t, b=b, m=m, last=last)
            H, C = Ho, Co
        else:
            n = t.shape[1]
            taps = [(2 * i, t[:, i]) for i in range(n)]
            fan = n
            d = dict(k=k, kind="fc", Hin=1, Cin=n, stride=1, Hc=1, pool=False, Ho=1, Co=t.shape[0],
                     amax=None if last else l["amax"], taps=taps, t=t, b=b, m=m, last=last)
            H, C = 1, t.shape[0]
        bound = fan * amax_in
        assert bound < 32768, (k, bound)
        bm = b * m + 32768
        assert (np.abs(bm) < 2 ** 31 - 2 ** 30).all()
        # the requantised value must fit in 16 bits (scores in particular)
        hi = (bound * m + bm) >> 16
        lo = (-bound * m + bm) >> 16
        assert hi.max() < 32768 and lo.min() > -32768, (k, hi.max(), lo.min())
        d["bm"] = bm
        amax_in = d["amax"] if d["amax"] is not None else 0
        out.append(d)
    return out


def out_layout(P, n):
    """Where layer n writes: (padded?, row stride in shorts between output rows' starts)."""
    d = P[n]
    if d["last"]:
        return False
    nxt = P[n + 1]
    return nxt["kind"] == "conv"


def emit_rq(A, j, m, bm, amax):
    """Requantise accumulator dj (int16 in the low word, upper word 0 or garbage-free) and store."""
    A.append(f"        muls.w  #{int(m)},%d{j}")
    A.append(f"        add.l   #{int(bm)},%d{j}")
    A.append(f"        swap    %d{j}")
    cyc = 74 + 16 + 4
    if amax is not None:
        A += [f"        tst.w   %d{j}", "        bpl.s   1f", f"        moveq   #0,%d{j}", "1:",
              f"        cmp.w   #{amax},%d{j}", "        ble.s   2f", f"        moveq   #{amax},%d{j}", "2:"]
        cyc += 4 + 10 + 8 + 10
    A.append(f"        move.w  %d{j},(%a1)+")
    return cyc + 8


def emit_asm(P):
    """void nlK(const short *in, short *out, long rows): ternary layer K with the requantisation
    fused in. Conv layers process `rows` output rows starting at in/out (in = the top-left of the
    first row's windows in the padded input; out = the first output of the row, padded or flat as
    the next layer wants it); fc layers ignore rows."""
    A = ["| Generated by calc/ref/gen_net.py from the trained model. 68000; do not edit.", "        .text"]
    total_cyc = 0
    for n, d in enumerate(P):
        k, Co = d["k"], d["Co"]
        assert not d["pool"], "pooled conv layers are not supported by the generator"
        name = f"nl{k}"
        A += [f"        .globl  {name}", f"{name}:",
              "        movem.l %d2-%d7/%a2-%a3,-(%sp)",
              "        move.l  36(%sp),%a0",
              "        move.l  40(%sp),%a1"]
        conv = d["kind"] == "conv"
        if conv:
            A += ["        move.l  44(%sp),%a3", "8:", f"        move.w  #{d['Hc']},%a2", "9:"]
        cyc = 0
        for o0 in range(0, Co, 7):
            mm = min(7, Co - o0)
            for j in range(mm):
                A.append(f"        moveq   #0,%d{j + 1}")
                cyc += 4
            for off, col in d["taps"]:
                nz = [(j, int(col[o0 + j])) for j in range(mm) if col[o0 + j] != 0]
                if not nz:
                    continue
                src = "(%a0)" if off == 0 else f"{off}(%a0)"
                if len(nz) == 1:
                    j, v = nz[0]
                    A.append(f"        {'add' if v > 0 else 'sub'}.w   {src},%d{j + 1}")
                    cyc += 8 if off == 0 else 12
                else:
                    A.append(f"        move.w  {src},%d0")
                    cyc += 8 if off == 0 else 12
                    for j, v in nz:
                        A.append(f"        {'add' if v > 0 else 'sub'}.w   %d0,%d{j + 1}")
                        cyc += 4
            for j in range(mm):
                cyc += emit_rq(A, j + 1, d["m"][o0 + j], d["bm"][o0 + j], d["amax"])
        if conv:
            s, Hin, C = d["stride"], d["Hin"], d["Cin"]
            xstep = s * C * 2
            rowskip = (s * (Hin + 2) - d["Hc"] * s) * C * 2
            A += [f"        lea     {xstep}(%a0),%a0",
                  "        subq.w  #1,%a2", "        move.w  %a2,%d0", "        bne.w   9b",
                  f"        lea     {rowskip}(%a0),%a0"]
            if out_layout(P, n):
                A.append(f"        lea     {4 * Co}(%a1),%a1")
            A += ["        subq.w  #1,%a3", "        move.w  %a3,%d0", "        bne.w   8b"]
            cyc = (cyc + 30) * d["Hc"] * d["Hc"]
        A += ["        movem.l (%sp)+,%d2-%d7/%a2-%a3", "        rts", ""]
        d["cyc"] = cyc
        total_cyc += cyc
    return "\n".join(A) + "\n", total_cyc


def carr(name, ctype, vals, per=16):
    vals = [int(v) for v in np.asarray(vals).reshape(-1)]
    rows = [", ".join(str(v) for v in vals[i:i + per]) for i in range(0, len(vals), per)]
    return f"static const {ctype} {name}[{len(vals)}] = {{\n    " + ",\n    ".join(rows) + "\n};\n"


def emit_c(M, P):
    C1 = M["layers"][0]["C"]
    H1 = G // 2
    h = ["/* Generated by calc/ref/gen_net.py; do not edit. */", "#ifndef NET_GEN_H", "#define NET_GEN_H",
         f"#define NET_NCLS {P[-1]['Co']}",
         "/* bits: 24 rows x 3 bytes, MSB = left. abortf (may be NULL) is called between rows; when it",
         "   returns nonzero the pass stops and net_forward returns 1 (scores not written). */",
         "int net_forward(const unsigned char *bits, short *scores, int (*abortf)(void));",
         "#endif", ""]
    c = ["/* Generated by calc/ref/gen_net.py from the trained model; do not edit.",
         " * The classifier's integer forward pass (bit-exact with calc/ref/ref.py). */",
         '#include "net_gen.h"', ""]
    c.append(carr("lut", "unsigned char", M["lut"], 32))
    c.append("#ifdef NET_HOST")
    for n, d in enumerate(P):
        k = d["k"]
        offs = [off // 2 for off, _ in d["taps"]]
        W = np.stack([col for _, col in d["taps"]], 1)
        c.append(carr(f"toff{k}", "short", offs))
        c.append(carr(f"tw{k}", "signed char", W, 32))
        c.append(carr(f"m{k}", "short", d["m"]))
        c.append(carr(f"bm{k}", "long", d["bm"], 8))
    c.append("""static void tern(const short *in, short *out, long rows, const short *off, const signed char *w,
                 int ntaps, int co, int hc, int xstep, int rowskip, int outskip,
                 const short *m, const long *bm, int amax)
{
    int y, x, o, i;
    const short *p = in;
    for (y = 0; y < rows; y++) {
        for (x = 0; x < hc; x++) {
            for (o = 0; o < co; o++) {
                short acc = 0;
                long v;
                for (i = 0; i < ntaps; i++) {
                    signed char t = w[o * ntaps + i];
                    if (t > 0) acc = (short)(acc + p[off[i]]);
                    else if (t < 0) acc = (short)(acc - p[off[i]]);
                }
                v = ((long)acc * m[o] + bm[o]) >> 16;
                if (amax >= 0) {
                    if (v < 0) v = 0;
                    if (v > amax) v = amax;
                }
                *out++ = (short)v;
            }
            p += xstep;
        }
        p += rowskip;
        out += outskip;
    }
}""")
    for n, d in enumerate(P):
        k = d["k"]
        amax = -1 if d["amax"] is None else d["amax"]
        outskip = 2 * d["Co"] if out_layout(P, n) else 0
        if d["kind"] == "conv":
            xs, rs = d["stride"] * d["Cin"], (d["stride"] * (d["Hin"] + 2) - d["Hc"] * d["stride"]) * d["Cin"]
            c.append(f"static void nl{k}(const short *in, short *out, long rows) "
                     f"{{ tern(in, out, rows, toff{k}, tw{k}, {len(d['taps'])}, {d['Co']}, {d['Hc']}, {xs}, {rs}, "
                     f"{outskip}, m{k}, bm{k}, {amax}); }}")
        else:
            c.append(f"static void nl{k}(const short *in, short *out, long rows) "
                     f"{{ (void)rows; tern(in, out, 1, toff{k}, tw{k}, {len(d['taps'])}, {d['Co']}, 1, 0, 0, 0, "
                     f"m{k}, bm{k}, {amax}); }}")
    c.append("#else")
    for d in P:
        c.append(f"void nl{d["k"]}(const short *in, short *out, long rows);")
    c.append("#endif\n")
    for d in P:
        n = (d["Hin"] + 2) * (d["Hin"] + 2) * d["Cin"] if d["kind"] == "conv" else d["Cin"]
        c.append(f"static short in{d['k']}[{n}];")
    c.append("static unsigned char pix[26 * 26], h3[26 * 24];\n")
    f = ["int net_forward(const unsigned char *bits, short *scores, int (*abortf)(void))", "{",
         "    int y, x, c, r;", "    short *dst;", "    unsigned char *q;"]
    f.append("""    /* the raster, zero-padded to 26 x 26, one byte per pixel */
    q = pix;
    for (x = 0; x < 26; x++)
        *q++ = 0;
    for (y = 0; y < 24; y++) {
        *q++ = 0;
        for (c = 0; c < 3; c++) {
            unsigned char b = bits[3 * y + c];
            for (x = 0; x < 8; x++, b = (unsigned char)(b << 1))
                *q++ = (unsigned char)(b >> 7);
        }
        *q++ = 0;
    }
    for (x = 0; x < 26; x++)
        *q++ = 0;
    /* 3-pixel row codes: h3[r][x] = pix[r][x] << 2 | pix[r][x+1] << 1 | pix[r][x+2] */
    for (r = 0; r < 26; r++) {
        const unsigned char *p = pix + r * 26;
        unsigned char hh = (unsigned char)(p[0] << 1 | p[1]), *o = h3 + r * 24;
        for (x = 0; x < 24; x++) {
            hh = (unsigned char)(((hh << 1) | p[x + 2]) & 7);
            o[x] = hh;
        }
    }""")
    f.append(f"""    /* layer 0: table lookups (idx = row codes of the 3 rows), 2x2 max pool, into layer 1's padded input */
    for (y = 0; y < {H1}; y++)
        for (x = 0; x < {H1}; x++) {{
            const unsigned char *a0 = h3 + (2 * y) * 24 + 2 * x, *a1 = a0 + 24, *a2 = a1 + 24, *a3 = a2 + 24;
            const unsigned char *p0 = lut + ((a0[0] << 6 | a1[0] << 3 | a2[0]) * {C1});
            const unsigned char *p1 = lut + ((a0[1] << 6 | a1[1] << 3 | a2[1]) * {C1});
            const unsigned char *p2 = lut + ((a1[0] << 6 | a2[0] << 3 | a3[0]) * {C1});
            const unsigned char *p3 = lut + ((a1[1] << 6 | a2[1] << 3 | a3[1]) * {C1});
            dst = in{P[0]['k']} + ((y + 1) * {H1 + 2} + x + 1) * {C1};
            for (c = 0; c < {C1}; c++) {{
                unsigned char v = p0[c];
                if (p1[c] > v) v = p1[c];
                if (p2[c] > v) v = p2[c];
                if (p3[c] > v) v = p3[c];
                dst[c] = v;
            }}
        }}""")
    for n, d in enumerate(P):
        k = d["k"]
        if d["last"]:
            outp = "scores"
        else:
            outp = f"in{P[n + 1]['k']}"
        if d["kind"] == "conv":
            Ho, Co = d["Ho"], d["Co"]
            if out_layout(P, n):
                ofs = f"((r + 1) * {Ho + 2} + 1) * {Co}"
            else:
                ofs = f"r * {Ho * Co}"
            f.append(f"""    for (r = 0; r < {d['Hc']}; r++) {{
        if (abortf && abortf())
            return 1;
        nl{k}(in{k} + r * {d['stride'] * (d['Hin'] + 2) * d['Cin']}, {outp} + {ofs}, 1);
    }}""")
        else:
            f.append(f"    nl{k}(in{k}, {outp}, 1);")
    f.append("    return 0;")
    f.append("}")
    c += f
    return "\n".join(h), "\n".join(c) + "\n"


def main():
    M = ref.load(sys.argv[1])
    out = sys.argv[2]
    os.makedirs(out, exist_ok=True)
    P = plan(M)
    asm, cyc = emit_asm(P)
    h, c = emit_c(M, P)
    open(os.path.join(out, "net68k.s"), "w").write(asm)
    open(os.path.join(out, "net_gen.h"), "w").write(h)
    open(os.path.join(out, "net_gen.c"), "w").write(c)
    print(f"generated {out}: ternary layers {[d['kind'] + str(d['Co']) for d in P]}, "
          f"estimated asm cycles {cyc} ({cyc / 7.79e6 * 1000:.0f} ms MAME, {cyc / 5.14e6 * 1000:.0f} ms real Plus), "
          + ", ".join(f"nl{d['k']} {d['cyc']}" for d in P))


if __name__ == "__main__":
    main()
