/*
 * Aim table for the attract-mode AI: for each flipper, cradle a ball, let it roll, flip at the
 * first tick it has rolled `along` px (exactly what core/ai.c does), and record the first target
 * the shot reaches. Writes a C header listing, per flipper and target, the flip points that work.
 *
 *   cc -O2 -Icore -I<gen> tests/aimtab.c core/phys.c <gen>/table_data.c -o aimtab && aimtab <gen>/aimtab.h
 */
#include <stdio.h>
#include <string.h>
#include "phys.h"
#include "ai.h"
#include "table_data.h"

static World W;

static int classify(const Event *ev)
{
    switch (ev->type) {
    case EV_DRAIN: return -1;
    case EV_SINK: return AIM_SINK;
    case EV_SPIN: return AIM_ORBIT;
    case EV_DROP: return AIM_DROP;
    case EV_BUMPER: return AIM_BUMPER;
    case EV_SENSOR:
        if (ev->id == ID_RAMP_MADE) return AIM_RAMP;
        if (ev->id >= ID_LANE0 && ev->id <= ID_LANE4) return AIM_LANES;
        if (ev->id == ID_ORBIT && ev->val > 0) return AIM_ORBIT;
        return 0;
    }
    return 0;
}

int main(int argc, char **argv)
{
    static int16_t list[2][AIM_N][64];
    static int n[2][AIM_N];
    int f, k;
    FILE *o = argc > 1 ? fopen(argv[1], "w") : stdout;
    for (f = 0; f < 2; f++) {
        const FlipperDef *fd = &table_flippers[f];
        int16_t ux = fcos(fd->rest), uy = fsin(fd->rest);
        for (k = 2; k <= 80; k++) {           /* 1 .. 40 px along, in half pixels */
            int t, s, flipped = 0, first = 0, e;
            int16_t at = (int16_t)(k * 32);   /* q6 */
            phys_init(&W, table_shapes, NSHAPES, table_mats, TABLE_W * 64, TABLE_H * 64);
            phys_add_flipper(&W, &table_flippers[0]);
            phys_add_flipper(&W, &table_flippers[1]);
            phys_set_ramp_box(&W, RAMP_BOX);
            phys_set_plunger(&W, PLUNGER_X0, PLUNGER_X1, PLUNGER_Y, PLUNGER_PULL, PLUNGER_RATE, PLUNGER_SPEED);
            phys_flipper_button(&W, f, 1);
            phys_add_ball(&W, ((fx)fd->px << 10) + (f == 0 ? 20L : -20L) * 65536, ((fx)fd->py << 10) - 40L * 65536, 0, 0);
            for (t = 0; t < 60 * 3; t++)      /* settle in the cradle */
                for (s = 0; s < STEPS_PER_TICK; s++)
                    phys_step(&W);
            for (t = 0; t < 60 * 4 && !first; t++) {
                int16_t dx = (int16_t)((W.ball[0].x >> 10) - fd->px), dy = (int16_t)((W.ball[0].y >> 10) - fd->py);
                int16_t along = (int16_t)(((int32_t)dx * ux + (int32_t)dy * uy) >> 14);
                if (!flipped && along >= at)
                    flipped = t + 1;
                if (!flipped && t > 150)
                    break;
                phys_flipper_button(&W, f, flipped && t + 1 - flipped < 14);
                for (s = 0; s < STEPS_PER_TICK && !first; s++) {
                    W.nev = 0;
                    phys_step(&W);
                    for (e = 0; e < W.nev && !first; e++)
                        first = classify(&W.ev[e]);
                }
            }
            if (flipped && first > 0 && n[f][first] < 64)
                list[f][first][n[f][first]++] = at;
        }
    }
    fprintf(o, "/* Generated by tests/aimtab.c: flip points (px*64 along the flipper, flipping at the first\n"
               "   tick the cradled ball has rolled that far) that reached each target. */\n");
    fprintf(o, "static const int16_t aim_points[2][AIM_N][17] = {   /* [flipper][target]: count, points */\n");
    for (f = 0; f < 2; f++) {
        int a;
        fprintf(o, "  {");
        for (a = 0; a < AIM_N; a++) {
            int i, c = n[f][a] > 16 ? 16 : n[f][a];
            fprintf(o, "{%d", c);
            for (i = 0; i < c; i++)
                fprintf(o, ",%d", list[f][a][i * n[f][a] / c]);
            fprintf(o, "}%s", a < AIM_N - 1 ? "," : "");
        }
        fprintf(o, "},\n");
    }
    fprintf(o, "};\n");
    for (f = 0; f < 2; f++) {
        static const char *names[AIM_N] = {"any", "ramp", "orbit", "drop", "sink", "lanes", "bumper"};
        int a;
        fprintf(stderr, "%s flipper:", f ? "right" : "left");
        for (a = 1; a < AIM_N; a++)
            fprintf(stderr, " %s %d", names[a], n[f][a]);
        fprintf(stderr, "\n");
    }
    if (o != stdout)
        fclose(o);
    return 0;
}
