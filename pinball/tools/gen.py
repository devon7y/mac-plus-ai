#!/usr/bin/env python3
"""Generate the table's C data from tools/table.py (and the art from tools/art.py).

    python3 -I gen.py OUTDIR

Writes OUTDIR/table_data.h and OUTDIR/table_data.c: materials, shapes (core/phys.h ShapeDef),
flippers, plunger, ids, lamps, and (when art.py is present) the bitmaps.
"""
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import table as T  # noqa: E402

FLAG_BITS = T.SF


def q6(v):
    return int(round(v * 64))


def deg16(a):
    return int(round(a * 65536 / 360)) & 0xFFFF


def q10(v):
    return int(round(v * 1024))


# flipper dynamics at 120.3 steps/s (angle units * 16 per step and per step^2; core/phys.h):
# a full flip takes about 40 ms, the coil's pull builds up over 25 ms
FLIP_ACC, FLIP_DEC, FLIP_BRAKE, FLIP_RISE, FLIP_WMAX = 27584, 6000, 64000, 3, 96000
# plunger: pull 16 px in about 0.8 s; release speed 0.88 px/step (106 px/s) per pixel of pull
PULL_RATE_Q16 = 10896
SPEED_PER_PX = 57600


def shape_c(s):
    flags = 0
    for f in s["flags"]:
        flags |= FLAG_BITS[f]
    kind = T.KIND[s["kind"]]
    mat = T.MAT[s["mat"]]
    rad = int(round(s.get("rad", 0) * 4))         # q6 / 16
    a0 = a1 = 0
    if s["kind"] in ("SEG", "LINE"):
        x0, y0 = s["a"]
        x1, y1 = s["b"]
        if s.get("kick"):
            a0, a1 = deg16(s["kick"][0]), q10(s["kick"][1] / T.STEPS_PER_SEC)
        coords = (q6(x0), q6(y0), q6(x1), q6(y1))
    elif s["kind"] in ("CIRCLE", "DISC"):
        coords = (q6(s["c"][0]), q6(s["c"][1]), q6(s["r"]), 0)
    else:
        coords = (q6(s["c"][0]), q6(s["c"][1]), q6(s["r"]), 0)
        a0, a1 = deg16(s["a0"]), deg16(s["a1"])
    return "{%d, %d, 0x%04X, %d, %d, %d, %d, %d, %d, %d, %u, %u}" % (
        kind, mat, flags, s["layers"], rad, s["id"], coords[0], coords[1], coords[2], coords[3], a0, a1)


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "build", "gen")
    os.makedirs(out, exist_ok=True)
    shapes = T.build()
    # discs (bowls) first is not required; keep the authoring order
    h = ["/* Generated by pinball/tools/gen.py from tools/table.py. Do not edit. */",
         "#ifndef TABLE_DATA_H", "#define TABLE_DATA_H", '#include "phys.h"', "",
         "#define TABLE_W %d" % T.W, "#define TABLE_H %d" % T.H,
         "#define NSHAPES %d" % len(shapes), "#define NMATS %d" % len(T.MATERIALS), ""]
    h.append("enum {")
    for n, v in T.ID.items():
        h.append("    ID_%s = %d," % (n, v))
    h.append("    ID_COUNT = %d" % (len(T.ID) + 1))
    h.append("};")
    h += ["", "extern const Material table_mats[NMATS];",
          "extern const ShapeDef table_shapes[NSHAPES];",
          "extern const FlipperDef table_flippers[2];", ""]
    p = dict(x0=q6(T.SHOOT_X0), x1=q6(T.SHOOT_X1), y=q6(T.PLUNGER_Y), pull=q6(T.PLUNGER_PULL))
    h += ["/* plunger: phys_set_plunger(w, PLUNGER_X0, PLUNGER_X1, PLUNGER_Y, PLUNGER_PULL, ...) */",
          "#define PLUNGER_X0 %d" % p["x0"], "#define PLUNGER_X1 %d" % p["x1"],
          "#define PLUNGER_Y %d" % p["y"], "#define PLUNGER_PULL %d" % p["pull"],
          "#define PLUNGER_RATE %dL" % PULL_RATE_Q16, "#define PLUNGER_SPEED %dL" % SPEED_PER_PX,
          "/* ball start position on the plunger (fx) */",
          "#define RAMP_BOX %d, %d, %d, %d" % tuple(q6(v) for v in T.ramp_box()),
          "#define BALL_START_X %dL" % int(round((T.SHOOT_X0 + T.SHOOT_X1) / 2 * 65536)),
          "#define BALL_START_Y %dL" % int(round((T.PLUNGER_Y - T.BALL_R - 0.5) * 65536)), ""]
    c = ['/* Generated by pinball/tools/gen.py from tools/table.py. Do not edit. */',
         '#include "table_data.h"', ""]
    c.append("const Material table_mats[NMATS] = {")
    for name, e, vrest, mu, kick, kmin in T.MATERIALS:
        r = T.STEPS_PER_SEC
        c.append("    {%d, %d, %d, %d, %d},   /* %s */" % (int(round(e * 256)), q10(vrest / r), int(round(mu * 256)),
                                                         q10(kick / r), q10(kmin / r), name))
    c.append("};")
    c.append("")
    c.append("const ShapeDef table_shapes[NSHAPES] = {")
    for s in shapes:
        c.append("    %s," % shape_c(s))
    c.append("};")
    c.append("")
    c.append("const FlipperDef table_flippers[2] = {")
    for f in T.flippers():
        c.append("    {%d, %d, %d, %d, %d, %u, %u, %d, %d, %d, %d, %d, %d, %d}," % (
            q6(f["pivot"][0]), q6(f["pivot"][1]), q6(T.FLIP_LEN), q6(T.FLIP_RB), q6(T.FLIP_RT),
            deg16(f["rest"]), deg16(f["up"]), FLIP_ACC, FLIP_DEC, FLIP_BRAKE, FLIP_RISE, FLIP_WMAX,
            T.MAT["FLIPPER"], 1))
    c.append("};")
    try:
        import art  # noqa: F401
        hh, cc = art.emit()
        h += hh
        c += cc
    except ImportError:
        pass
    h += ["", "#endif"]
    open(os.path.join(out, "table_data.h"), "w").write("\n".join(h) + "\n")
    open(os.path.join(out, "table_data.c"), "w").write("\n".join(c) + "\n")
    print("wrote %s/table_data.[ch]: %d shapes" % (out, len(shapes)))


if __name__ == "__main__":
    main()
