GLYPHS = {" ": ["....."] * 7}
for _line in _SRC.strip().splitlines():
    _t = _line.split()
    GLYPHS[_t[0]] = _t[1:]
    assert len(_t) == 8 and all(len(r) == 5 for r in _t[1:]), _line

ORDER = " ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789!?.,:-+='/()%x><*_"


def text_width(s, scale=1, gap=1):
    return len(s) * (5 + gap) * scale - gap * scale if s else 0


def draw_text(img, x, y, s, ink=1, scale=1, gap=1):
    """Draw text into a 2-D list/array img[y][x] (1 = black). Returns the width."""
    for i, ch in enumerate(s):
        g = GLYPHS.get(ch) or GLYPHS.get(ch.upper()) or GLYPHS["?"]
        for r in range(7):
            for c in range(5):
                if g[r][c] == "#":
                    for dy in range(scale):
                        for dx in range(scale):
                            yy, xx = y + r * scale + dy, x + i * (5 + gap) * scale + c * scale + dx
                            if 0 <= yy < len(img) and 0 <= xx < len(img[0]):
                                img[yy][xx] = ink
    return text_width(s, scale, gap)
